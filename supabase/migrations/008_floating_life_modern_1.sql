$$# 错过末班地铁

## 第一章：末班车的陌生人

你已经不记得第一次加班到深夜是什么时候的事了。

但你还记得那天晚上的一切细节——十一月的北京，冷风像刀子一样割着脸，你裹紧大衣从写字楼里走出来，街上的出租车已经很少了。你掏出手机看了一眼时间，二十三点十一分，末班地铁还有四分钟。

你跑起来了。高跟鞋敲击地面的声音在空旷的地下通道里回荡，你顾不上狼狈，一路小跑冲进地铁站。刷卡、下电梯、穿过长长的走廊，你看到那趟列车还没有关门。你几乎是跌进了车厢。

车门在你身后合上的那一刻，你才喘过气来。

车厢里很空。空得有些不真实。白炽灯管发出惨淡的光，照着空荡荡的座椅和拉手。你数了一下，整节车厢只有一个人。

那个人坐在你对面的位置上，靠窗，穿着一件深灰色的羊毛大衣，脖子上围着一条藏青色的围巾。ta低着头在看手机，屏幕的蓝光映在脸上，看起来有些疲惫。你看不清ta的五官，但你觉得ta应该也是那种加班到很晚的人。

你找了个位置坐下来，左边，第三个座位。你也不知道为什么选了这个位置，也许是巧合，也许是因为从这个角度刚好能看到车窗外飞速后退的隧道壁。

列车在黑暗的隧道里穿行，发出单调的轰鸣声。你靠着椅背闭上眼睛，感觉整个人都被掏空了。项目方案改了七遍，客户还是不满意，老板说明天早上必须交终版。你想哭，但连哭的力气都没有了。

列车到站了。你睁开眼，发现对面那个人站起来了。ta收好手机，拎起放在脚边的公文包，往门口走去。车门打开的时候，ta回头看了一眼车厢——也许是在确认有没有东西落下，也许是别的什么原因。

就是那一眼。

很短暂，短暂到你几乎以为是自己看错了。但你觉得ta的目光在你身上停留了一秒，只有一秒，像一根羽毛轻轻掠过水面，然后迅速移开了。

车门关上。ta走了。

你一个人坐在空荡荡的车厢里，看着窗外自己模糊的倒影。你想，这个人大概和你一样，都是这座城市里被工作榨干了的灵魂。你们不会再见到了。这座城市有一千多万人，你们不会再有交集。

你错了。

## 第二章：第二个位置的秘密

第二天，你又是末班车。

这一次你没有跑，因为你刻意提前了五分钟下班。你走进车厢的时候，发现那个人又在。同一个位置，对面靠窗，深灰色大衣，藏青色围巾。ta还是低着头看手机，好像整个世界和ta无关。

你犹豫了一下，然后走向了左边第三个座位。昨天坐过的那个位置。你坐下来的时候，心里有一种奇怪的感觉——不是刻意，但也不是完全的巧合。你告诉自己，这个位置离门口近，下车方便。你没有对自己承认的是，从这个位置，你刚好能看到对面那个人。

列车开动了。你们就这样面对面坐着，中间隔着一整节车厢的空旷。没有人说话，甚至没有人抬头。你们像是两个被装进同一个容器里的气泡，各自包裹着各自的沉默，偶尔因为列车的晃动而轻轻碰撞一下边界。

第三天，你加班到更晚。你冲进地铁站的时候，末班车的提示音已经响了。你跑下电梯，看到车门即将关闭，你大喊了一声"等一下"，然后挤了进去。

你弯着腰喘气的时候，听到了一声轻笑。

很轻，轻得像一片落叶飘到水面上。但你听到了。你抬起头，发现对面那个人正看着你，嘴角微微上扬。ta很快就把目光移开了，重新低下头看手机。但你捕捉到了那个笑——温柔的、善意的、甚至有些可爱的。

你也笑了。

你发现ta的嘴角有一颗很小的痣，不仔细看根本看不出来。你发现ta看手机的时候会不自觉地用右手无名指轻敲膝盖，好像在跟着什么节奏。你发现ta的大衣袖口有些磨损，但很干净。你发现ta的公文包上挂着一个很小的毛绒挂件，看起来像是一只柴犬。

你开始好奇了。这个人叫什么名字？做什么工作？为什么每天也都这么晚？住在哪里？有没有人等着ta回家？

但你什么都没有问。你甚至连一声"你好"都没有说。也许是太累了，也许是不想打破什么微妙的东西。你只是坐在这个位置上，安静地存在着，而ta坐在对面，也安静地存在着。

第四天，第五天，第六天。

你们开始形成一种模式。你总是坐在左边第三个位置，ta总是坐在对面靠窗。你们不会刻意对视，但偶尔目光会在空中相遇，然后各自移开。你开始觉得，这节车厢像一个秘密的房间，而你们是这个房间里仅有的两个居民。

有一个晚上，列车在两站之间突然停了。灯光闪了一下，车厢陷入短暂的黑暗。你听到对面传来一声轻微的叹息，然后是手机屏幕亮起的光。ta打开了手机手电筒，白色的光柱在车厢里晃了一下。

"经常这样。"ta说。

你愣住了。这是你们之间说出的第一句话。ta的声音比你想的要低沉一些，带着一种被生活磨出来的平静。

"嗯。"你回答。就一个字。

列车重新启动了，灯光亮起来，一切恢复正常。你看到ta的嘴角又微微上扬了一下，然后ta低下头，继续看手机。

你想说点什么。"你也是每天加班吗？""你坐到哪一站？""你叫什么名字？"这些话在你的舌尖转了一圈，最终还是没有说出口。你只是重新靠回椅背上，假装闭目养神，实际上心跳快得像是要从胸腔里蹦出来。

因为ta和你说话了。虽然只有五个字，但ta和你说话了。

## 第三章：一千零九十五天

三年是一个很漫长的数字。一千零九十五个日夜。如果你把每一天都展开来看，会发现里面装着无数个微小的瞬间，像是一串被穿起来的珠子，每一颗都不起眼，但连在一起就成了一条很长很长的项链。

第一个冬天，你们在末班地铁上相遇了大概四十次。你开始不自觉地记住一些细节。比如ta在很冷的日子里会把围巾拉高，遮住半张脸，只露出一双眼睛。比如ta偶尔会带一个保温杯，拧开盖子喝一口，然后看着窗外发呆。比如ta疲倦的时候会用一只手撑着下巴，手指遮住嘴唇，只露出鼻梁和眼睛。

你发现自己的记忆开始为这个人开辟一个专门的区域。

第二年的春天，有一件小事让你记了很久。那天你上车的时候，发现左边第三个位置被一个醉酒的男人占了。你有些为难地站在车厢中间，拉着吊环。对面那个人看了你一眼，然后往旁边挪了一个位置——ta坐到了原来你坐的那个位置对面的地方。

不是什么大事。但你觉得ta是在为你说："你可以坐我对面。"

你没有坐。你继续拉着吊环站着。但你的心里涌起了一股暖意，像是在冬天喝了一口热可可。下一站，醉酒的男人下车了。你走过去坐下来，发现ta也起身换回了原来的位置。你们没有对视，没有微笑，什么都没有。但车厢里的空气好像温暖了一些。

那年夏天，地铁的空调坏了。车厢里闷热得像蒸笼，你们都满头大汗。ta把大衣脱了，搭在膝盖上，里面穿着一件白色的衬衫。你看到ta的衬衫领口微微敞开，锁骨上有一道淡淡的红痕，可能是背包带子勒的。ta用手扇着风，表情有些无奈。

你犹豫了一下，从包里掏出一包纸巾，放在了你们之间的空座上。

你没有递给ta。你只是放在那里。像一个不设防的礼物，可以接受也可以忽视。

过了大约十秒钟，你看到ta伸出手，把纸巾拿走了。

"谢谢。"ta说。

"不客气。"你说。

这是你们之间说过的所有话的百分之五十。另外百分之五十是那个"经常这样"和"嗯"。

秋天的时候，你们有了第三个默契。你上车的时候，如果ta还没到，你会把对面靠窗的位置空出来，不坐那里。ta上车的时候，会自然地走向那个位置，就好像那个座位上写着ta的名字。如果ta先到，你会发现左边第三个位置也是空着的。

你们从来没有讨论过这件事。没有人说"这是我的位置"或者"我帮你留着"。它就这么自然而然地发生了，像是地球绕着太阳转一样不需要理由。

你还发现了一些更小的细节。比如ta在周五的时候会看一种蓝色的文件夹，在周一的时候会看手机上密密麻麻的表格。比如ta偶尔会在包里翻找什么，然后露出一个沮丧的表情——大概是忘带了什么东西。比如ta有一次在列车到站之前就站起来了，走到门口，然后在门开的一瞬间回头看了你一眼。

那一眼里有很多东西。你不确定自己解读得对不对，但你觉得那里面有某种不舍。

第三年。你们已经不需要刻意寻找对方了。上车，看到那个熟悉的身影，心里就安定下来。像是在茫茫大海里看到了一座灯塔，虽然你永远不会驶向它，但知道它在那里就够了。

你开始害怕有一天ta不在。

## 第四章：雨天

那是第三年秋天的一个周三。

白天下了很大的雨，从早晨一直下到傍晚，没有停的意思。你出门的时候没带伞，因为天气预报说今天是晴天。天气预报是个骗子。

你在写字楼门口站了很久，看着外面的暴雨，像是一道透明的墙把世界隔成了两半。手机叫车软件显示排队一百三十七人，你叹了口气，转身走向地铁站。

地铁站的入口处挤了很多避雨的人。你的裙摆已经湿了半截，贴在小腿上，又冷又难受。你刷卡进站，下电梯，走到站台。末班车还有两分钟。

站台上人不多，大部分人都赶在暴雨之前回家了。你站在黄线外面，看着隧道深处隐隐约约的灯光，那是列车即将到来的信号。

你低头看手机的时候，感觉有人站到了你旁边。不是刻意的那种近，但足够让你感觉到另一个人的体温。你侧头看了一眼。

是ta。

ta也在看你。你们的目光在潮湿的空气里相遇了。ta的大衣右肩湿了一大片，头发也有些凌乱，几缕碎发贴在额头上。ta看起来也很狼狈。

你们没有说话。但这一次，你们之间的距离比以往任何一次都要近。你能看到ta睫毛上挂着的小水珠，能看到ta鼻尖上那一小块因为冷空气而微微发红的皮肤。

列车来了。你们一起走进车厢。这一次车厢里还有其他几个乘客，一个戴着耳机的年轻人，一对靠在一起打瞌睡的中年夫妇，一个抱着大包小包的阿姨。但你们还是坐在了老位置上——你左边第三个，ta对面靠窗。

列车开动了。雨声透过车体传进来，像是一首漫长的白噪音。你看着窗外模糊的隧道壁，心里想着明天还要不要穿这双鞋。

然后你闻到了一种味道。

不是香水，也不是洗衣液。很难形容，像是很淡很淡的皂角，混合着一点点雨水的气息和大衣上羊毛的味道。是ta身上的味道。因为今天车厢里多了几个人，空气不流通，ta又坐得离你很近——比以前任何一次都近。

你偷偷地深呼吸了一次。

你觉得自己像一个变态。但你还是又呼吸了一次。那个味道让你觉得安心，像是冬天回到家里闻到厨房飘来的汤味，像是小时候躲在衣柜里闻到樟木箱的味道。它属于一个你完全不了解的人，但你的身体却本能地把它标记为"安全"。

下一站到了。中年夫妇下车了，车厢里只剩下你和ta，还有那个戴耳机的年轻人。年轻人坐在很远的另一头，像是在另一个世界。

列车重新启动的时候，你感觉到一种前所未有的勇气。你想开口。你想说："今天雨好大。"你想说："你没带伞吗？"你想说："我叫……"

但你没有。

因为在那个瞬间，ta抬起头看了你一眼，然后微微笑了一下。那个笑容很轻很淡，像是雨水落在湖面上泛起的涟漪。然后ta又低下头去了。

你觉得那个笑容是在说："我知道你在。"

你觉得那就够了。

那天你下车的时候，雨已经小了很多。你站在地铁出口，看着细密的雨丝在路灯下斜斜地飞舞。你回头看了一眼，ta还在后面慢慢走着，一只手插在大衣口袋里，一只手拎着公文包。

你想等ta。你真的想了。你的脚步放慢了，你的呼吸屏住了，你的心跳在催促你回头。但你最终还是没有。

你走进雨里，向左拐，走向你租住的那栋老公寓。你没有回头。

你不知道的是，ta在后面停下了脚步，看着你的背影消失在雨幕里，站了很久很久。

## 第五章：消失

周一。

你记得很清楚，因为那天你难得准时下班。你没有加班，没有赶末班车，而是在正常的时间走进了地铁站。你坐了平时那趟线，但不是末班车，车厢里挤满了人。你被夹在一个背着大书包的学生和一个拎着菜篮子的大妈之间，完全看不到对面。

你觉得有点不习惯。

你告诉自己，从明天开始还是坐末班车吧。虽然辛苦，但那种一个人的安静已经成了你需要的东西。你需要那节空旷的车厢，需要列车在隧道里穿行时的白噪音，需要——

需要看到那个人。

周二。你加班了。你赶上末班车，走进车厢，第一时间看向对面靠窗的位置。

空的。

你愣了一下，然后坐下来。你告诉自己，ta可能今天不加班，可能提前走了，可能请假了，可能有无数个合理的理由。你掏出手机，假装在看什么，但你的眼睛一直从手机屏幕上方偷看对面的位置。

三站过去了。没有人坐到那个位置上。一个抱孩子的女人上了一站又下了另一站，一个穿工装的工人在车厢连接处靠着门打瞌睡。但对面靠窗的位置，始终空着。

那天的列车好像比平时慢了一些。每一站之间的间隔都被拉长了，灯光比平时更白，空气比平时更冷。你觉得自己像是在一个被抽走了什么东西的房间里——一切都还在，但少了某种让你安心的元素。

周三。你一下班就走了，专门赶末班车。你走进车厢，看到对面靠窗的位置上坐着一个戴帽子的老人。你的心沉了一下。

老人在下一站下车了。位置又空了。

周四。空的。周五。空的。周六你特意跑了一趟，虽然你知道周六没有加班。空的。

第二周。你每天坐末班车。对面靠窗的位置换了一批又一批的人——一个打电话的中年男人，一个哭花了妆的年轻女孩，一对牵手的小情侣。但都不是ta。

你开始慌了。

你以前从来没有意识到，一个人的存在可以在你的生活里占据这么大的空间。ta甚至没有名字，没有声音，没有一个明确的面孔——在黑暗的车厢里，你从来没有清楚地看清过ta的五官。但ta在那里，就像夜空中的一颗星星，你不需要看到它的全貌，只需要知道它在那个位置上亮着。

现在那颗星灭了。

你开始在白天也想这件事。上班开会的时候，你看着投影屏幕上的PPT，脑子里想的却是末班地铁那节车厢。午休的时候你坐在茶水间里，同事们聊着八卦，你盯着窗外想，ta去了哪里？是换了工作？搬家了？还是——你不敢想下去。

第三周。你做了一个决定。

## 第六章：末班地铁的侦探

你开始问人了。

你找到地铁站的保洁阿姨，问她有没有注意到一个穿深灰色大衣、围藏青色围巾的人。阿姨看了你一眼，说："每天坐末班车的人那么多，我哪记得住。"

你找到站台的安保小哥，问他有没有印象。小哥笑着说："姐，你这是找人呢？叫啥名字？"

你没有名字。

你这才意识到，你对这个人一无所知。你不知道ta的名字、年龄、职业、住址、电话号码。你不知道ta在哪一站下车——你从来没有注意到，因为你总是比ta先下车，或者你总是在闭着眼睛假装休息。你不知道ta在哪个出口离开，不知道ta走哪个方向，不知道ta乘坐这一班地铁已经多久了。

三年。你们在末班地铁上相处了三年，而你能够描述ta的只有这些：深灰色大衣，藏青色围巾，右手无名指会轻敲膝盖，嘴角有一颗很小的痣，公文包上挂着一只柴犬毛绒挂件，身上有很淡的皂角味道。

你甚至不确定ta是男是女。在昏暗的车厢灯光下，在匆匆一瞥的目光中，在三年无数个疲惫的深夜里，ta的轮廓已经模糊成了一个符号，一种感觉，一个你无法命名的存在。

你觉得荒谬。你觉得可笑。三年，一千多个日夜，你为一个人留了一个位置，而你不能确定ta是男是女。

但你还是在找。

你开始在每一站都留意下车的人。你把路线延长了两站——本来你应该在第六站下车，但你坐到了第八站，然后往回坐。你走遍了终点站的每一个出口，看着零星的乘客从闸机口鱼贯而出，消失在城市的夜色里。

没有ta。

