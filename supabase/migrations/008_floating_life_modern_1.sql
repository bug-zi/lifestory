你笑了笑，把箱子推到墙角，然后站在客厅中央环顾四周。这是你第一次以"另一半住在这里"的身份看这个空间，感觉和以前完全不同。以前你来这里做客，目光所及都是ta的东西、ta的选择、ta的品味。但现在这个空间里有你了，哪怕只是两个箱子，你也觉得自己在这个房间里有了坐标。

头几天像是在度蜜月。你们一起逛宜家，买了新的床单、抱枕、一盏落地灯。你们为了选什么颜色的床单争论了二十分钟——你想要浅灰色的，ta想要奶白色的，最后你们选了一个介于两者之间的米色，两个人都不太满意但都能接受。ta说你这个人真是麻烦。你说你才是麻烦。然后你们对视了一眼，同时笑了出来。

你们买了新的碗碟——白色的，带一圈细蓝边。你挑了很久，最后选了这个最简单的款式。ta说你选东西倒是挺快。你说因为我知道自己想要什么。ta说什么？你说简单就好。

那天晚上你们用新碗碟吃了在一起之后的第一顿饭。你做的番茄鸡蛋面。ta站在旁边看你切番茄，说你刀工还行啊。你说我只会做面条和煎蛋，你要是期望值太高以后会失望的。ta说我期望值本来就不高。你用沾着番茄汁的手弹了一下ta的额头，ta啊了一声跑开了。

日子就这样过起来了。

早上你们轮流做早餐。你的固定搭配是吐司加煎蛋，ta的是燕麦粥加水果。你吃不惯燕麦粥，说那口感像在吃墙皮。ta说你没吃过墙皮怎么知道像。你说那我以后不说了。但下次ta做燕麦粥的时候你还是忍不住说了一句"又在吃墙皮"，然后被ta用勺子敲了一下脑袋。

晚上你们一起做饭。说是"一起"，其实大多数时候是你做饭ta打下手——ta负责洗菜和递调料。你一边炒菜一边指挥ta把盐递过来、把酱油递过来、把那个什么递过来。ta说那个什么到底是哪个。你说就是那个什么嘛。ta说我又不是你肚子里的蛔虫。你说你应该是我肚子里的蛔虫才对，这样你才知道我在想什么。

ta翻了个白眼，但嘴角是翘着的。

吃完饭你们一起洗碗。你洗，ta擦干放好。你们发明了一套很高效的流水线——你负责把碗碟上的泡沫冲干净递给ta，ta负责用干布擦好放进橱柜。洗碗的时候你们会聊天，聊今天公司发生了什么事、聊最近在追的剧、聊周末想去哪里玩。有时候聊着聊着就会因为一件很小的事情笑起来，笑到最后碗都洗完了还在笑，站在厨房里笑得前仰后合，你自己都不知道在笑什么，但就是停不下来。

那些笑声你现在还记得。它们像琥珀一样封存在你的记忆里，透明、温暖、完好无损。你后来再也没有那样笑过，不是因为后来没有开心的事情，而是因为那种笑需要的不仅仅是开心——它还需要一种毫无保留的放松，一种确信身旁有人会接住你的笃定。

周末你们会赖床。阳光从那扇大窗户照进来的时候，你们还窝在被子里，你靠着ta的肩膀，ta靠在你的头顶。你们有时候聊天，有时候不聊，就那么躺着，听着窗外偶尔传来的车声和鸟叫。你觉得那就是你能想到的最好的周末。

但住在一起也不全是甜蜜。

你们的生活习惯有很多不同。你晚睡，ta早起；你喜欢开着窗户睡觉，ta觉得风直吹头疼；你吃完饭习惯把碗泡在水池里等会儿再洗，ta觉得碗必须立刻洗不能过夜。你把衣服丢在椅背上，ta说衣架就在旁边你怎么就不能多走一步。你说我等会儿再挂。ta说你每次都说等会儿然后等到第二天。你说那第二天我挂了不就行了。ta说这不是挂不挂的问题这是习惯的问题。

第一次吵架是因为马桶盖。

你觉得马桶盖不需要每次都放下来，ta觉得必须放下来。你说这有什么区别。ta说区别在于我半夜坐下去的时候不想掉进马桶里。你说你不会开灯看一下吗。ta说你半夜上厕所会开灯吗。你说我会。ta说你骗人。

你们因为马桶盖冷战了一个晚上。谁也不和谁说话，各自窝在沙发的一端，中间隔着两个抱枕的距离。你看你的手机，ta看ta的书。电视开着，播的是什么你们都没在看。

快到半夜的时候，你受不了了。你站起来去了一趟洗手间，出来的时候顺手把马桶盖放了下来。然后你走回客厅，站在ta面前。ta抬起头看着你。

"马桶盖放下来了。"你说。

ta看了你一眼，嘴角微微动了一下，像是在忍笑。"哦。"ta说。

"别哦了，"你说，"过来。"

ta放下书站起来，你一把抱住了ta。你把脸埋在ta的肩窝里，闻到了洗衣液和一点点沐浴露的味道。ta的手臂环上来，搂住你的背。

"我们以后不要因为马桶盖吵架了。"ta的声音闷闷地从你头顶传来。

"好。"

"因为你会放下来的。"

"我会的。"

"每次都放。"

"……每次都放。"

你们在黑暗中抱了很久。你觉得自己有点傻，为了一个马桶盖闹了一整个晚上。但你后来想，也许那些小吵小闹也是住在一起的一部分——你们在用最笨拙的方式学习如何共享一个空间，如何在"我"和"你"之间找到一个"我们"。

那年夏天你们去了一趟海边。坐了四个小时的火车，到了一个你叫不出名字的小镇。海水很蓝，沙子很细，人不多。你们在沙滩上躺了一整个下午，晒得皮肤发红。你涂防晒霜的时候涂不到后背，ta说帮我涂一下。你帮ta涂的时候手指碰到ta后背的皮肤，觉得温热、光滑，像一块被太阳晒暖的玉石。

傍晚的时候你们在海边散步。潮水退了，沙滩上留下了很多贝壳和小螃蟹。ta蹲下来捡贝壳，捡了一个又一个，最后两只手都捧不下了。你说你捡那么多干嘛又不能吃。ta说好看啊。你说好看有什么用。ta说好看就是有用，不是所有东西都要有用的。

你站在ta身后，看着ta弯着腰认真挑贝壳的样子。夕阳把ta的侧脸染成了金色，海风吹乱了ta的头发。你觉得那个画面很美，美到你想用什么东西把它装起来，藏在口袋里，什么时候想看了就拿出来看看。

"你发什么呆呢？"ta直起身来，回头看你。

"看你。"你说。

ta歪了歪头，好像在判断你说的是不是真话。然后ta笑了，把手里最大的一个贝壳递给你。

"给你。"

"为什么给我？"

"因为你刚才看我的样子，好像很想得到什么。"

你接过贝壳，握在手心里。贝壳的纹路硌着你的掌心，有点疼，但你没有松手。

那天晚上你们住在海边的小旅馆里，窗户开着，能听到海浪的声音。你躺在床上，ta的头枕在你的肩膀上，你的手搭在ta的腰上。月光照在地板上，像泼了一地的水银。

"你说，"ta的声音轻得像在说梦话，"我们能一直这样吗？"

"怎样？"

"就这样。住在一起，吃一起做的饭，吵一些无聊的架，然后和好。"

你说："会的。"

你说这话的时候是认真的。百分之百地、毫无保留地认真。

## 第三章：第三年——平淡

新鲜感是什么时候消失的，你说不清楚。

不是某一个瞬间，不是某一个事件，而是一个极其缓慢的过程，缓慢到你身在其中根本感觉不到。就像你每天看着镜子里的自己，觉得和昨天没有什么不同，但如果你翻出几年前的照片对比一下，你会发现原来一切都变了。

在一起第三年的时候，你们的对话开始变少了。

不是没有话说，而是很多事情不需要说了。你知道ta几点起床、怎么喝咖啡、用什么姿势看书、睡前会不会看手机。ta知道你洗澡要洗多久、喜欢吃什么外卖、难过的时候会沉默而不是倾诉。你们像两本已经被对方翻烂了的书，每一页的内容都烂熟于心，再翻一遍也不会有新的惊喜。

你开始觉得日子有些重复了。

每天早上同样的时间起床，同样的流程洗漱，同样的早餐搭配。出门的时候说"我走了"，ta说"嗯"；回家的时候说"我回来了"，ta说"嗯"。偶尔有一方加班晚了回来，另一方已经睡了，留了一盏床头灯和一条微信："饭在锅里，热一下就能吃。"你看到微信的时候会说一句"谢谢"，第二天早上ta问你饭吃了没，你说吃了。

就这样。日复一日，像一列准点运行的列车，从起点到终点，中间不停站。

你并不是不开心。你只是不那么开心了。这两者之间的区别很微妙，微妙到你自己都说不清楚。就像一杯加了太多水的果汁，你不能说它不是果汁，但你也喝不出多少果汁的味道了。

你开始注意到一些以前不会注意的事情。

比如ta刷牙的时候声音很大，你会觉得吵。以前你觉得那个声音是生活的背景音，白噪音一样，甚至有点安心。但现在你躺在床上听着水龙头哗哗地响和牙刷在牙齿上快速摩擦的声音，会皱一下眉。

比如ta看剧的时候喜欢把声音开得很大，你说过很多次了能不能小一点，ta说这就已经很小了你再小就听不见了。你说你可以戴耳机。ta说戴耳机不舒服。你说那你就小一点。ta说我都说了这就已经很小了。你们的对话绕了一圈又回到原点，像一条蛇咬住了自己的尾巴。

比如你们越来越难一起做决定了。以前吃什么、看什么电影、周末去哪里，你们总能很快达成一致，或者一方心甘情愿地迁就另一方。但现在你们经常陷入一种微妙的僵局——你说"随便"，ta也说"随便"；你说"你决定"，ta也说"你决定"。最后谁也不决定，外卖翻了半小时还没点，电影看了半天还没选，周末到了中午还没出门，最后你们窝在家里各自看各自的手机，一天就这么过去了。

你觉得你们之间好像缺了点什么，但你不知道缺的是什么。

三月份的一个周末，你提议出去走走。ta说去哪。你说你想去。ta想了想，说没什么想去的地方。你说那就在附近走走也行。ta说也行。然后你们出门了，沿着小区外面的街道走了一圈。走了大概二十分钟，你们经过了一家花店，你停下来看了一眼。ta也停下来。

"要买吗？"ta问。

"也不是。"你说。

"那就走吧。"

你走了两步，忽然回头看了一眼那家花店。门口摆了一桶一桶的鲜花，玫瑰、百合、向日葵、满天星。你想起你们刚在一起的时候，你曾经在一个普通的周三下班后，顺手买了一束白色的小雏菊带回家。ta接过去的时候眼睛亮了一下，说"干嘛突然买花"。你说"没干嘛，看到好看就买了"。ta笑了，把花插在一个玻璃杯里放在窗台上。那束花活了大概一个星期，凋谢的时候ta还叹了一口气。

你没有回头看的那两步里，你已经走过了那家花店。

你们继续往前走。谁也没有说话。春天的风很温柔，路边的樱花正在开，花瓣被风吹落了一些，像粉色的雪。你们走在樱花树下，花瓣落在你的肩膀上，落在ta的头发上。你本应该觉得浪漫的，但你没有。你只是觉得风有点凉。

那天晚上你躺在床上想了很多。你想你们是不是出了什么问题。你想是不是每一段感情到了某个阶段都会变成这样——不再有心动，不再有惊喜，只剩下惯性和惯性之间的缝隙里那些越来越少的温度。

你翻了个身，看到ta已经睡着了。ta的呼吸很平稳，脸上没有任何表情。你看了ta很久，久到你的眼睛开始发酸。你想伸手去摸一下ta的脸，但你的手抬到一半又放下了。

你不知道自己在害怕什么。

也许你害怕的是——ta的脸摸起来和以前一样温暖，但你已经感觉不到那种"被烫到了"的悸动了。

你的手缩回被子里。你闭上眼睛，努力让自己入睡。窗外的月光照在天花板上，还是那道窄窄的河。但这次河的两边没有人在说话。

## 第四章：第四年——裂痕

第一次真正意义上的吵架发生在你们在一起的第四年。

起因是一件小得不能再小的事情——你忘记了你们的纪念日。

说"忘记"也不准确，更准确的说法是"没有放在心上"。你知道那天是纪念日，你甚至在前一天看到了日历上的标记，但你没有做任何准备。没有订餐厅，没有买礼物，甚至没有在早上出门的时候多说一句话。你就是——忘了。或者说，你记得，但你的身体和大脑没有做出任何与"纪念日"相匹配的反应，就像你知道明天要下雨但你没有带伞一样，知道归知道，行动归行动。

那天你加班到九点回家，推开门看到餐桌上摆了两副碗筷和两个蜡烛杯。蜡烛已经熄了，蜡油凝固在桌面上，像两滴白色的眼泪。桌上的菜已经凉透了，你可以看到它们表面凝结的一层薄薄的油膜。

ta坐在沙发上，电视开着但没有声音。ta看着你，眼神里没有愤怒，也没有委屈，只有一种你很陌生的疲倦。

"今天什么日子你知道吗？"ta问。

你的脑子嗡了一下。你当然知道。但你张了张嘴，说出来的却是："对不起，我太忙了忘了——"

"你总是太忙了。"ta打断你。

"我确实很忙——"

"我不是在说忙不忙的问题。"ta的声音不高，但每个字都像是从牙缝里挤出来的，带着一种压抑了很久的力度。"我在意的是你根本不在乎。你记得你周一有个会，记得你周三要交报告，记得你周五要和客户吃饭。但你记不住我们的纪念日。"

"我记住了，我只是——"

"你只是什么？"

你沉默了。因为ta说得对。你确实记得很多事情，工作上的、朋友们的、甚至邻居家的狗叫什么名字。但你不记得去准备一份纪念日的惊喜。你甚至不记得在那天早上出门前说一句"纪念日快乐"。

ta站起来，走进了卧室，把门关上了。不是摔上的，是轻轻带上的。但那个"咔嗒"的关门声比任何摔门都让你难受。

你站在客厅里，看着桌上那两副碗筷和熄灭的蜡烛。你坐下来，夹了一口已经凉透了的菜。菜是ta拿手的红烧排骨，你的最爱。你嚼了几下，味道还是那个味道，但你觉得像在嚼纸。

那天晚上你没有进去卧室。你睡在沙发上，把沙发巾拉过来盖在身上。客厅的灯你一盏也没关，亮堂堂地照了一整夜。你觉得那些光很刺眼，但你没有起来关。你就那么躺着，睁着眼睛，一直到了天亮。

你们和好了。你道了歉，补了礼物，请了一顿很贵的晚餐。ta收下了，说"下次别忘了"。你说不会了。

但你忘没忘，你自己心里清楚。

那之后你们开始频繁地吵架。不是每次都像纪念日那次那么严重，大多数时候是为了一些鸡毛蒜皮的小事——你回家晚了没提前说一声、ta把你桌上的东西整理了但你找不到、你在ta说话的时候看手机、ta在你加班的时候打了三个电话你觉得烦。每一次吵架都不大，但每一次都像在一条绳子上剪一刀。一刀不够，绳子不会断。但十刀、二十刀、三十刀呢？

你们开始冷战了。

冷战是一种很奇怪的状态——你们明明住在同一个屋檐下，睡在同一张床上，呼吸着同样的空气，但你们之间有一堵看不见的墙。你们各做各的事，各吃各的饭，偶尔不得不说的话就像两个同事之间的工作交接——精确、简短、不带一丝多余的温度。

"今天的垃圾我倒了。"

"嗯。"

"洗衣机里的衣服你记得晾。"

"好。"

就这样。你们曾经的那些废话、那些没有意义的闲聊、那些纯粹为了听对方声音而说的话，全部消失了。你们之间的对话被压缩到了最基本的功能性交流，像两个合租的陌生人。

最可怕的是，你发现冷战有一种惯性。一旦你们进入了那种互不理睬的状态，要打破它就需要其中一个人先低头。而先低头的那个人会觉得自己输了，另一个人会觉得自己赢了。但实际上没有人赢。你们都输了。你们输掉的是那些沉默的小时、那些背对背的夜晚、那些想说但没有说出口的话。

有一次你们冷战了三天。三天里你们没有说过一句话。第三天晚上你躺在床上，背对着ta，听到ta翻了一个身。然后你感觉到ta的手伸了过来，搭在了你的腰上。

你没有动。

ta的手停在那里，很轻，像是在试探。过了大概十秒钟，ta的手指微微收紧了一点，像是在确认你还在。

你的眼眶忽然就热了。

你翻过身来，在黑暗中摸索着抱住了ta。ta的身体僵了一下，然后慢慢地放松了。你把脸埋在ta的胸口，听到了ta的心跳。很快，比平时快。你忽然意识到，也许ta这三天也没有睡好，也许ta也在等着谁先伸手。

"对不起。"你说。你不知道自己在为什么道歉——为你先发起冷战的那个原因，还是为冷战本身，还是为你没有先伸手的这三天。但你说出来了，你觉得这三个字比任何解释都管用。

ta没有说话，但ta的手臂把你抱得更紧了。

你们就这样和好了。没有讨论，没有分析，没有"下次我们应该怎样"的约定。只是抱了一下，就翻过了这一页。但你后来想，也许问题就在这里——你们总是在翻页，但从来没有真正读过那一页上写了什么。你们把矛盾折叠起来塞进抽屉里，假装它不存在，但抽屉越来越满，已经快关不上了。

## 第五章：第五年——疲惫

到了第五年，你们不吵架了。

不是因为问题都解决了，而是因为连吵架的力气都没有了。

你还记得以前吵架的感觉吗？愤怒、委屈、不甘心，所有的情绪像沸水一样翻滚着，你觉得你必须说出来，必须让ta知道你有多不满、多受伤、多想让ta明白你的立场。吵架是一种暴力的沟通方式，但至少它在沟通——你们还在试图让对方听到自己的声音。

但现在你们连那个力气都没有了。

你开始觉得吵架没有意义。你说了ta也听不进去，ta说了你也改不了。你们的矛盾就像一个循环——发生问题、吵架、冷战、和好、问题没有解决、下一个问题出现、再吵架、再冷战、再和好。你累了。你累得不想再跑这个圈了。

于是你选择沉默。

不是那种刻意不理人的沉默，而是一种更深层的、更本能的沉默——你连生气的欲望都没有了。ta做了让你不舒服的事情，你的第一反应不再是"我要和ta说"，而是"算了"。算了，说了也没用。算了，说了又要吵。算了，不如省点力气。

你不知道从什么时候开始，"算了"成了你心里最常出现的词。

ta好像也一样。你们像两只被驯服了的兽，不再龇牙，不再低吼，只是各自缩在自己的角落里，用一种近乎麻木的平静注视着对方。你们不再有激烈的冲突，但你们也不再有任何激烈的东西了——没有激烈的快乐，没有激烈的悲伤，没有激烈的拥抱，没有激烈的吻。你们的感情被调成了静音模式，所有的声音都还在，但你们听不见了。

有一天晚上你在公司加班到很晚。回到家的时候已经十一点了。你推开门，客厅的灯亮着，ta坐在沙发上，面前的茶几上摊着一堆文件。ta在加班。

你换了鞋走进来，去厨房倒了一杯水。你端着水杯走到客厅，经过ta身边的时候，ta抬头看了你一眼。

"回来了。"

"嗯。"

"吃饭了吗？"

"吃了。"

"那我继续忙了。"

"嗯。"

你端着水杯走进了卧室。你坐在床边，喝了一口水，然后把杯子放在床头柜上。你看着那杯水，忽然觉得它很可怜——一杯水被倒出来，端了那么远，最后被放在一个陌生的桌子上，没有人喝它。你觉得你就是那杯水。

你开始越来越多地一个人做事情。

一个人吃饭，一个人看电影，一个人逛超市。不是刻意避开ta，而是你发现一个人的时候反而更轻松。你不用考虑另一个人的感受，不用衡量自己的每一句话、每一个表情会不会引发什么连锁反应。你可以安静地吃一碗面，看一场烂片，在超市的零食货架前站二十分钟选薯片，没有任何人会催你，没有任何人会问你"你在看什么"。

你以前觉得"你在看什么"是一句温暖的话。它意味着有人在关注你，有人对你的世界感兴趣。但现在你听到这句话的时候，第一反应是"没什么"。不管你在看什么，你都只想说"没什么"。

你知道这不正常。你知道一段感情不应该是这样的。但你没有做任何改变。不是因为你不想改变，而是因为你不知道怎么改。你甚至不确定问题出在哪里——是出在ta身上？出在你身上？还是出在"你们"这个组合身上？

你想过分手吗？

想过。不是认真地想，而是一种走神式的想——你在地铁上发呆的时候会想，你在排队等咖啡的时候会想，你在深夜睡不着的时候会想。你想到分手之后的生活，想到一个人住、一个人吃饭、一个人面对空荡荡的房间。你觉得那个画面也不坏。至少它是安静的。

但每次想到分手，你都会接着想到你们在一起的日子——你们第一次牵手时河边的风、你们搬进新家时一起拼的那张书桌、你们在海边捡的贝壳、你们在沙发上笑得停不下来的那些夜晚。这些记忆像一根根线，密密麻麻地缠绕在你的心上。你想抽刀斩断它们，但每根线都连着一个你舍不得的画面。

于是你什么也没做。

你继续过你的日子，上班下班，吃饭睡觉。ta也一样。你们像两个住在同一座房子里的钟，各自走着各自的时间，偶尔在同一秒重合一下，然后继续各自走。

那年的纪念日你们没有庆祝。你提了一句，说"今天是我们——"。ta说"嗯，我知道"。然后你们对视了一眼，都从对方的眼神里看到了同一种东西——不是期待，不是惊喜，不是甜蜜，而是一种淡淡的、疲惫的"然后呢"。

然后呢？没有然后了。你去做你的事，ta去做ta的事。这一天和昨天一样，和明天也会一样。

你有时候会想起你们刚在一起的时候。那时候你觉得ta是全世界最有趣的人，你想知道ta所有的事情——ta小时候是什么样的，ta最喜欢的颜色是什么，ta难过的时候会做什么。你问了，ta也说了。你记住了，ta也记住了你说的每一句话。

但现在你觉得你已经了解了ta全部。你不再好奇了。而ta大概也是一样。

你想知道这是不是就是爱情的尽头——不是某个戏剧性的崩塌，不是第三者介入，不是什么不可饶恕的背叛，只是两个人慢慢地把对方了解完了，然后不知道还能用什么理由继续待在一起。

你没有答案。你也没有去找答案。

你只是继续往前走。和ta一起。或者不如说，和ta并排。

## 第六章：第六年——疏离

你们睡在同一张床上，但中间的距离足够躺下第三个人。

这不是一夜之间发生的事。它是慢慢来的，一点一点地，像两块原本紧挨着的冰，在温水中慢慢地、慢慢地分开。你甚至说不清是从哪一天开始，你们的身体不再自然地靠近了。以前你们睡觉的时候总是贴在一起，你的腿搭在ta的腿上，ta的手搭在你的腰上，姿势不雅但很安心。后来变成了肩并肩，再后来变成了背对背，再后来变成了各睡各的——你在这边，ta在那边，中间是一大片空荡荡的床单。

你有时候会在半夜醒来，侧过头看看ta。月光照在ta的脸上，ta的睡颜很安静，和刚在一起的时候没有什么不同。你还是觉得ta好看——那种好看的形状没有变，但你的感受变了。以前你看ta会觉得心跳加速，现在你看ta就像看一件熟悉的家具，你知道它的位置、它的形状、它的颜色，但你不会再特别注意到它。

你被自己的想法吓到了。你怎么能把一个人比作家具呢？但你又觉得这个比喻没那么离谱——你们之间的关系，现在不就是和家具一样吗？你不会每天对沙发说"我好喜欢你"，你也不会每天对ta说。你依赖沙发，你依赖ta，但依赖和喜欢不是一回事。

或者说，依赖和"喜欢的温度"不是一回事。

你们的对话越来越少，短到有时候一天说不满十句话。早上出门的"我走了"，回家的"回来了"，睡前的"晚安"。偶尔加几句事务性的话——"牛奶没了你明天记得买"、"水电费交了吗"、"周六我有个聚餐不回来吃了"。你们的对话像一栋被精简到了极致的建筑，只剩下了承重墙，所有的装饰、花纹、窗台上的花盆都被拆掉了。它还能站，但没有人会觉得它好看。

你有时候想主动说点什么。比如你在路上看到一只很胖的猫，你想拍下来发给ta，但你打开相机的时候犹豫了。你问自己：ta会感兴趣吗？你觉得不会。ta会说"嗯挺胖的"，然后话题就结束了。你不想面对那种"嗯"，所以你放下了手机，什么也没有发。

你不知道ta是不是也一样。ta是不是也在某个瞬间想和你分享什么，但最终选择了沉默？ta是不是也觉得你们之间的桥梁断了，但谁也没有去修？

你们不再吵架了，但你们也不再聊天了。你们不再冷战了，但你们也不再和好了。你们不再刻意疏远，但你们也不再主动靠近。你们的关系进入了某种真空状态——没有热，也没有冷；没有好，也没有坏；没有爱，也没有恨。只有一种巨大的、中性的、空洞的"在"。

你们还在"一起"，但那个"一起"已经不包含任何温度了。

有一天你下班回家，推开门，看到ta坐在窗台边看书。夕阳照进来，把ta的侧脸照得轮廓分明。那个画面很美，和你们刚在一起的时候一样美。你站在门口看了几秒钟，心里涌上来一种很复杂的情感——你不确定那是不是爱，还是怀念，还是遗憾，还是只是习惯性地觉得"这个画面我应该觉得美"。

ta听到了你进门的声音，抬起头来。"回来了？"

"嗯。"

"今天回来挺早的。"

"嗯，没什么事了就走了。"

"哦。"

ta低下头继续看书。你换了鞋，走进卧室，把包放下。你站在卧室门口犹豫了一下，想走过去和ta一起坐在窗台边，像以前那样，靠着ta的肩膀，一起看窗外渐渐暗下去的天空。但你的脚步没有迈出去。你走到厨房去给自己倒了一杯水，然后坐到了沙发上。

你和ta之间隔了一整个客厅。

你喝了那杯水。水很凉，从嗓子一路凉到胃里。

那段日子你常常失眠。不是因为焦虑，也不是因为难过，只是睡不着。你躺在床上，听着ta平稳的呼吸声，数着天花板上的裂纹。有一条裂纹从灯的边缘延伸到墙角，像一条弯弯曲曲的河。你盯着那条河看，看它流啊流，流到眼睛发酸。

凌晨三点的时候你拿出手机，在备忘录里打了一行字："我不知道我们怎么变成这样了。"

你看了那行字很久，然后删掉了。

你曾经以为两个人之间最大的距离是异地。现在你知道了，最大的距离是同床。你们呼吸着同样的空气，盖着同一床被子，枕着同一个枕头，但你们之间的那条河越来越宽，宽到你喊不到对岸，宽到你已经不想喊了。

你有时候会想起ta以前说过的一句话："我这个人，喜欢一个人可以喜欢很久。"很久是多长？你想。六年够不够长？还是不够？

你不知道答案。你开始怀疑，也许"喜欢很久"和"一直喜欢"之间，隔着一个你以为自己能跨过去、但其实跨不过去的距离。

那年秋天你们去参加了一个朋友的婚礼。仪式上新人交换戒指的时候，你偷偷看了ta一眼。ta也在看你。你们目光相遇的那一瞬间，你读到了一些东西。你不确定那是什么，但它让你移开了视线。

婚礼结束后你们走在回家的路上，沉默了很久。

ta突然说："你觉得他们能在一起多久？"

"什么？"

"新郎新娘，你觉得他们能在一起多久？"

你想了想："不知道。看他们自己吧。"

"你觉得我们呢？"

这个问题像一颗石子扔进了平静的水面。你看着涟漪一圈一圈地扩散，不知道该怎么回答。

"我们挺好的啊。"你说。

ta没有说话。你不知道ta是不认同，还是懒得反驳。

那天晚上你躺在床上，睁着眼睛看天花板。你听到身边ta的呼吸声，均匀的、平稳的，什么情绪都没有。你突然觉得非常孤独。

那种孤独不是一个人的孤独，而是两个人在一起却无法交流的孤独。比一个人还孤独。因为一个人至少可以幻想有人在等你，而你清楚地知道——你身边明明躺着一个人，但你们之间的距离，比天涯还远。

## 第七章：第七年——放手

ta是在一个普通的周三晚上说的。

那天你照常加班到八点，回家的时候带了一份炒饭和一份酸辣粉。你推开门，看到ta坐在餐桌前，桌上没有摆碗筷，但摆了两个杯子，里面倒了水。不是茶，不是酒，就是白开水。你看着那两杯水，忽然觉得有点紧张。

"今天怎么这么早就坐好了？"你把外卖放在桌上，试图用轻松的语气打破那种微妙的凝重。

ta看着你。那个眼神很平静，平静到让你觉得ta已经排练过很多遍了。

"我们谈谈吧。"ta说。

你坐下来。你没有打开外卖。

"谈什么？"你问。你其实知道ta要说什么。你不知道自己是怎么知道的，也许是因为那个眼神，也许是因为那两杯白开水，也许是因为你的身体比你的大脑更早地感受到了某种终结的气息。

ta沉默了一会儿。你能看到ta的手指在杯子边缘轻轻地摩挲，那是ta紧张时的习惯动作。你以前会伸手握住ta的手，但现在你没有。

"我觉得……"ta开口了，声音很轻，"我们可能走不下去了。"

你听到了。你每一个字都听到了。但你没有立刻反应，好像你的身体需要一些时间来处理这些字的含义。

"你这么觉得？"你说。你的声音比你想的要平静。

ta点了点头。"我想了很久了。不是突然的想法。"

"想了多久？"

"大概……半年。也许更久。"

半年。你在心里重复了这个词。半年前的你在做什么？你想想。你想不起来。你们的日子太相似了，每一天都像前一天，你分不清哪天是哪天。

"是因为什么？"你问。

ta摇了摇头。"不是'因为什么'。不是某一个原因。是很多很多小小的东西加在一起。是我们不再说话了，不再拥抱了，不再——"ta停了一下，"不再像两个在一起的人了。"

你沉默了。因为ta说的每一个字都是事实。

"你还记得我们刚搬进来的时候吗？"ta忽然问。

"记得。"

"那时候我们为了选什么颜色的床单争论了二十分钟。"

"你选白色，我选灰色。"

"最后我们选了米色。"

"两个人都不满意。"

"但都很开心。"ta的声音在最后三个字上轻轻颤了一下。

你看着ta。月光不知道什么时候已经取代了夕阳，照在ta的脸上。ta的眼睛亮亮的，你不确定是因为月光还是因为别的什么。

"你觉得可惜吗？"你问。

ta想了一会儿。"不是可惜。是……"ta在找那个词，"是难过。为我们的难过。为我们本来可以不一样的难过。"

"本来可以不一样"——这七个字击中了你。你忽然想到了很多"本来可以"：你本来可以记住那个纪念日的；ta本来可以多和你说说话的；你本来可以在某个失眠的夜晚翻过身去抱住ta的；ta本来可以在某个加班的晚上给你发一条"早点回来"的。你们有无数个"本来可以"的瞬间，但你们一个也没有抓住。

"那你觉得现在还来得及吗？"你问。你自己都不确定你是想听到"来得及"还是"来不及"。

ta看着你，眼神里有一种很温柔的东西——那种温柔不是给恋人的，而是给一个曾经很重要的人的，是告别的温柔。

"我不知道。"ta说，"但我觉得……我们都不想再试了。对吗？"

你张了张嘴，想说"不，我还想试"。但你没有说出来。因为ta说得对。你不想再试了。不是因为你不在乎，而是因为你太累了。你们都太累了。你们在这段关系里耗尽了所有的热情、耐心、好奇心和力气，剩下的只有惯性。而惯性不足以支撑两个人走完一生。

你低下头。你看着桌上那两杯白开水，水面上映着天花板的倒影。你的倒影和ta的倒影各自倒映在各自的水杯里，没有交集。

"好吧。"你说。

两个字。很轻。轻得像一片落在水面上的花瓣。

ta听到了，没有说话。你看到ta的眼眶红了。你自己的眼眶也红了。你们就那么坐着，隔着一张餐桌，各自红着眼眶，谁也没有哭。

过了一会儿，ta站起来，走到你身边。你抬起头，看到ta的眼睛里有泪光，但ta在笑。那个笑很淡，像冬天早晨的第一缕阳光。

"谢谢你这七年。"ta说。

你也站起来。你想说点什么，你想说"谢谢你"或者"对不起"或者"我不后悔"或者很多很多别的话。但你的喉咙堵住了，你什么都说不出来。

最后你只是伸出手，轻轻地握了一下ta的手。ta的手指还是凉的，像你们第一次牵手那天一样凉。

你松了手。

ta转身走进了卧室。你听到了拉行李箱的声音。

你坐在沙发上，看着窗外的月亮。月亮很圆，像一盏挂在天上的灯。你忽然想起很久以前ta说过的一句话——"月亮是世界上最大的聚光灯，谁被照到谁就要说实话。"

你想告诉ta你现在在想什么。你想说你后悔了。你想说我们应该再试一次。你想说不要走。你想说——

但你什么都没说。

你听到卧室的门打开了。ta拖着行李箱走出来，站在玄关换鞋。你站起来，走到ta面前。

"那个贝壳还在，"你说，"你送的，海边那个。"

ta看着你，眼睛里有什么东西碎了。然后ta凑过来，在你的额头上很轻很轻地落了一个吻。

"再见。"ta说。

"再见。"你说。

门关上了。咔嗒一声。

你站在玄关，看着那扇关上的门。你等了很久。等到脚步声消失在走廊尽头，等到电梯的叮咚声响起又消失，等到整个世界安静下来。

然后你走到窗前，看着外面。城市的灯光很亮，亮到你看不到几颗星星。但你还是抬起头去找了，像一个固执的人在废墟里翻找还能用的东西。

你什么也没有找到。

你回到沙发上坐下来。茶几上还摆着那两杯白开水，已经凉透了。你端起来喝了一口。水没有任何味道，但你喝出了咸的。

你拿出手机，在备忘录里打了一行字："七年。从心动到沉默，从沉默到放手。"

你看了那行字很久。然后你按了保存。

窗外，月亮依然很圆。但你已经不想说实话了。


## 最终总结

