这是大二春天的事了。南方城市的春天说下雨就下雨，你养成了每天看天气预报的习惯。你会在书包里塞两把伞——一把你用，一把以备不时之需。但你从来不会把第二把伞拿出来自己用。你会趁教室没人的时候，悄悄走到ta常坐的位置旁边，把伞放在桌洞里。

你不知道ta发现伞之后是什么反应。也许ta以为是上一个坐在这里的人落下的。也许ta直接丢进了失物招领处。也许ta用了。你不关心结局。你只关心ta没有被雨淋。

有一次你刚把伞放好，还没来得及走，门口传来脚步声。你慌了，灵机一动，蹲下来假装系鞋带。进来的人刚好是ta。ta看了你一眼，说："鞋带开了？"你说："嗯。"ta笑了笑，走到自己的位置坐下，然后从桌洞里掏出了你的伞。

你看着ta把伞拿出来，看了两秒，然后放进了自己的书包里。

你蹲在地上系了两分钟的鞋带，直到ta离开教室才站起来。你的腿都麻了，但你的心脏跳得像是要炸开。ta拿了。ta收下了。虽然ta不知道那把伞是你放的，但ta没有把它丢掉。

那一整天你都在笑。室友问你怎么了，你说中午的鸡腿特别好吃。

又比如占座这件事。

期末考试周，图书馆的座位比春运火车票还难抢。你每天早上五点半起床，六点准时站在图书馆门口等开门。你抢到位置之后先放下自己的东西，然后再去帮ta占一个位置——在你旁边，隔一个座位，不远不近。

你不知道ta来不来，但每天你都占着。大部分时间ta会来。ta来了之后环顾一圈找位置，你假装不经意地抬头，然后对ta说："这里有空位。"ta说谢谢，然后坐下来。你们中间隔着一个空座位，像一个心照不宣的距离——近到你可以闻到ta洗衣液的味道，远到你的手肘不会碰到ta的手肘。

有一个下午，ta趴在桌子上睡着了。你从书本上方偷偷看ta，看了好久好久。ta睡着的时候嘴微微张着，呼吸很轻很轻，像一只打盹的猫。窗外的阳光照在ta的侧脸上，你能看到ta皮肤上细细的绒毛，像蜜桃表面的那层白霜。你的手指不自觉地动了一下，想碰一碰ta翘起来的那缕碎发。

你当然没有碰。你把目光收回来，重新盯住面前的书。那一页你看了两个小时，一个字都没有读进去。

还有一件更傻的事情——你收藏了ta丢掉的草稿纸。

那是大三期末，你在阶梯教室的自习桌上发现了一张揉皱的草稿纸，上面是ta的字迹——你认得，因为你在摄影社看过ta写的活动策划。那是一张数学草稿，写得密密麻麻，有些公式你完全看不懂，旁边画着几个小人，还有一个歪歪扭扭的笑脸。

你把那张纸捡起来，展开，抚平，夹在了你的笔记本里。

后来你又捡到过几次。一张画着猫的便签纸，一张写着"周三买牛奶"的备忘录，一张被揉成团丢在教室后排的考试大纲。你把每一张都收好，按时间顺序排列，放在你书桌抽屉最里面的一层。

你室友有次打扫卫生差点把它们当垃圾扔了，你几乎是尖叫着冲过去抢回来的。室友吓了一跳，问你那些废纸是什么。你说"复习资料"。室友疑惑地看了一眼那些写着小人涂鸦的草稿纸，没有再问。

你没有告诉任何人这件事。因为连你自己都觉得有点变态。但你控制不住。你只是想拥有一些和ta有关的东西——哪怕是被ta丢弃的、不重要的、毫无意义的废纸。它们是唯一允许你触碰的、来自ta世界里的碎片。

你把它们放进一个牛皮纸信封里，信封上写着"那些你不知道的事"。

## 第四章：ta有了喜欢的人

大三下学期，一个星期五的傍晚，ta约你在学校门口的奶茶店见面。

你们的关系在这三年里已经从"不认识"变成了"还不错的同学朋友"。你们会在走廊里点头打招呼，会在公共课上坐得不远不近，会在社团活动结束以后一起走一段路回宿舍。你知道ta喜欢喝少糖去冰的柠檬茶，知道ta的生日在三月，知道ta有一个在北方上大学的青梅竹马。你不知道的是，今天ta要告诉你一件事。

你到奶茶店的时候ta已经坐在那里了。面前摆着两杯柠檬茶——少糖去冰，一杯是ta的，一杯是你的。ta记得你的口味。你坐下来的时候心里暖了一下，但很快就被接下来的话冲散了。

"我好像……喜欢上一个人了。"ta说。

ta低着头搅动吸管，脸微微泛红。你看不清ta的表情，但你能感觉到ta的紧张和期待。ta的手指在杯壁上轻轻敲着，就是那个你很熟悉的节奏——ta紧张的时候就会这样。

你拿着柠檬茶的手僵住了。你的第一反应不是心碎——心碎是后来的事情，是在深夜里一个人躺在床上的时候才慢慢裂开的。你的第一反应是：我该怎么办。你的表情不能变。你的声音不能抖。你要像一个正常的朋友那样作出反应。

"谁啊？"你问。声音很平稳。你佩服自己。

"就是我们隔壁班那个……你知道的，上次社团联谊认识的。"ta抬起头看你，眼睛亮亮的，像装了一整个银河。"ta约我这个周末去看电影，你说我去不去？"

你的胃在翻搅。你感觉有什么东西在胸腔里坍塌了，无声地，像一座大楼被定向爆破，外面看着完好无损，里面全是废墟。但你的嘴角在上扬。你在笑。

"去啊，为什么不去？"你说。

"可是我怕……我怕我太紧张了，到时候不知道说什么。"ta咬着吸管，像个拿不定主意的小孩。

"那就别想那么多。看电影嘛，又不用一直说话。买爆米花，吃就完了。"

ta被你逗笑了。"你说的也对。"

你陪着ta讨论了半个小时的穿搭。ta问你穿什么好看，你说白色那件衬衫不错——你记得那件衬衫，因为那是你们第一次见面时ta穿的那件。ta又问你第一次约会要不要送礼物，你说不用，太刻意了。ta问你万一冷场怎么办，你说不会的，你那么有趣——

这句话说完你就后悔了。因为这句话暴露了你对ta的关注程度。但ta好像没有注意到。ta只是笑了笑，说"谢谢你啊，你总是这么靠谱"。

你靠谱。你是一个靠谱的朋友。你是一个可以倾诉暗恋对象的朋友。你是一个帮ta出主意、帮ta挑选衣服、帮ta预演约会的朋友。

这个角色你演了整整一个晚上。从奶茶店出来的时候，ta开心地和你挥手告别，说"你是我最好的朋友"。你笑着挥了挥手，转身走向宿舍的方向。

走到路灯照不到的地方，你蹲了下来。

你没有哭。你只是蹲在那里，双手抱膝，感觉身体里有什么东西在被一点一点抽走。你想起你放在桌洞里的伞、你凌晨六点抢的座位、你夹在笔记本里的草稿纸、你吃了三个月的北区食堂麻辣烫。这些东西加起来，在你心里是一整个宇宙，在ta心里只是"谢谢，你真靠谱"。

你站起来，拍了拍裤子上的灰。你走到宿舍楼下的时候已经完全恢复了。室友问你去了哪里，你说出去喝了杯奶茶。

那天晚上你失眠到凌晨四点。你反复告诉自己，这是好事，ta找到了喜欢的人，你应该替ta开心。你确实替ta开心。但你也替自己难过。这两件事同时存在，像两列相向而行的火车，在你胸口猛烈地撞在了一起。

## 第五章：毕业合照

大四毕业那天下了雨。

六月的校园到处是穿着学士服拍照的人，三五成群，搂着抱着笑着哭着。你站在图书馆门口的台阶上，穿着借来的学士服，帽子歪歪地扣在头上。你的行李已经收拾好了，下午的火车，回老家。工作找在了南方一个二线城市，和你大学四年没有任何交集的地方。

你本来不打算和ta拍照。

你们的关系始终停留在一个不上不下的位置——比普通同学亲近一点，比真正的朋友又差那么一层。你们偶尔在食堂碰到会坐在一起吃饭，偶尔在图书馆遇见会点头微笑，偶尔在微信上聊几句不痛不痒的话。但仅此而已。ta不知道你暗恋ta，不知道你为ta做过那些事，不知道你在ta身上投注了多少个日日夜夜的思念。

是ta先走过来的。

"哎，我们拍张合照吧。"ta提着学士服的下摆小跑过来，脸上带着笑，眼角有一点点红——也许是因为刚才和别人告别哭过。"四年了，怎么也得留个纪念。"

你说好。

ta站在你右边，伸手搂住了你的肩膀。ta的手搭在你肩上的那一刻，你整个人都僵了。ta的手很温暖，带着六月雨天的潮气和洗衣液的味道。那个味道你太熟悉了——图书馆里隔着一个座位飘过来的、三年如一日的味道。

"笑一个！"帮你拍照的同学喊了一声。

你笑了。你笑得很用力，用力到你怕自己一松懈就会哭出来。闪光灯亮了一下，然后又一下。ta转过头来对你说："你笑得好僵硬。"你说是吗，可能是太紧张了。ta拍了拍你的肩膀，说"毕业又不是生离死别"，然后哈哈笑了。

但你知道，毕业就是生离死别。至少对你来说是。

你们之后又和社团的几个人一起拍了几张大合照。在这些照片里你站在最边上，ta站在最中间——ta总是人群的中心，而你是人群边缘默默注视着ta的那个人。你们之间隔着两三个人，隔着微笑和拥抱的距离，隔着整整四年没有说出口的话。

拍完照，人群散了。你一个人站在图书馆门口，看着雨丝从屋檐滴下来。你的学士帽被雨打湿了，黑布上结了一层细密的水珠。你没有躲雨。

你掏出手机，找到了刚才拍的合照。ta搂着你的肩膀，你笑得僵硬。你的眼睛里有什么东西在闪光——不是闪光灯的反光，是别的什么。

你把那张照片设成了手机壁纸。

后来你换了三次手机，每一次都会把那张照片从旧手机传到新手机。再后来你把它洗了出来，塞进了钱包的夹层里。你不知道为什么要洗一张实体照片——也许是因为你怕有一天手机坏了，云端数据丢了，你就再也看不到ta的脸了。

那张照片在你钱包里待了七年。纸边磨损了，颜色泛黄了，ta的笑脸依然清晰。有一次你掏钱付账的时候照片掉了出来，和你一起吃饭的同事捡起来看了一眼，问是谁。你说是大学同学。同事说看起来关系很好的样子。你说是啊，很好的朋友。

很好的朋友。你用这四个字定义了你们之间所有的关系。但你心里清楚，这四个字是一堵墙，墙上写着四个大字：你进不去。

## 第六章：婚礼请柬

请柬是周三下午到的。

你正在办公室里对着电脑改方案，微信弹出一条消息。是ta发来的。你们已经很久没有联系了——偶尔朋友圈点个赞，过年发一句"新年快乐"，生日的时候发一个表情包。频率低到你几乎可以骗自己说你们只是普通同学。

但ta发消息来的时候，你的手还是比你的大脑先做出了反应。你在一秒之内点开了对话框。

"好久不见！我要结婚啦，请你来参加婚礼！"后面跟着一个邀请函的小程序链接，粉色的底，烫金的字，两个名字并排写在一起。ta的名字旁边是另一个人的名字，你不认识的，但在这一刻成了世界上最刺眼的一串字符。

你盯着屏幕看了很久。

你点开了邀请函。日期，地点，时间，着装要求。一切都安排得妥妥当当，一切都那么幸福。照片里ta笑得很好看，和另一个人搂在一起，背景是一片薰衣草花田。ta的笑脸和七年前那个九月午后一样好看，但那个笑不再是因为你了——它从来没有因为你过。

你把手机屏幕扣在桌面上。

你继续改方案。你的手指在键盘上敲着，节奏很稳定，和平时没有两样。你的同事从你身边经过，和你说了句什么，你笑着回应了。没有人看出任何异常。

但你的方案改了两个小时，一个字都没有推进。

下午五点半下班。你开车回到出租屋，把包扔在沙发上，在黑暗中坐了下来。你没有开灯。窗外路灯的光透过窗帘照进来，在天花板上投下一个模糊的矩形光斑。

你重新打开那条微信消息。你又开始看那张结婚照。你数了数ta眼角的细纹——ta也老了，老了也好看。你看了看ta无名指上的戒指——银色的，简单的款式，你猜是ta自己挑的，ta一直喜欢简单的东西。

你把手机放下，又拿起来。放下，又拿起来。你不知道自己想做什么。你想回一句"恭喜，我会去的"，但你的手指打完"恭喜"两个字就停住了。你删除了，重新打。又删除了。又重新打。

你对着那条消息坐了整整一个晚上。

从天亮坐到天黑，从天黑坐到深夜。外卖点了没有吃，凉了，你也没有热。你只是坐在沙发上，手机屏幕亮了又暗，暗了又亮。你打开了很多次对话框，又关掉了。你甚至打了一段很长的话——"其实我一直想告诉你……"但你看了一遍，觉得太矫情了，就删除了。

凌晨两点，你终于回了消息。

"恭喜！一定到。"

五个字。你用了八个小时。

然后你关掉手机，走进浴室，打开花洒，站在热水下面。水很烫，但你感觉不到烫。你把脸仰起来对着水流，这样就算流泪也看不出来。

你没有哭出声。你只是站在那里，让水流过你的脸，流过你的脖子，流过你的肩膀。你想起大一那年的秋天，想起图书馆大厅里的阳光，想起北区食堂的麻辣烫，想起桌洞里的伞，想起凌晨六点的图书馆座位，想起夹在笔记本里的草稿纸，想起奶茶店里那句"我好像喜欢上一个人了"，想起毕业那天ta搂着你肩膀的手。

你想把这些记忆全部打包扔掉。但你做不到。它们已经长在了你的身体里，和骨头长在一起，你想拔掉它们就得把肉一起撕下来。

你在浴室里站了四十分钟。出来的时候镜子上的雾气凝成了水珠，缓缓滑落下来，像一面正在哭泣的镜子。

你打开钱包，翻出那张毕业合照。七年了。照片上的ta和现在的ta已经不太一样了，但那个笑容一模一样。你把照片放回去，关了灯，躺在床上。

你一夜没睡。

## 第七章：婚礼

你穿了自己最好的一套衣服。

一套藏青色的西装——你后来才意识到这个颜色和ta大学时那条围巾一模一样。你在镜子前站了很久，打领带打了三次才满意。你甚至喷了香水，那瓶买了一年多都没有拆封的香水，你一直觉得没有场合用。今天有了。

婚礼在城南的一家酒店，开车要四十分钟。你提前了一个小时出门。在路上你把车载音响的声音开得很大，随便什么歌都行，你需要声音来填满车厢里的沉默。

你到的时候婚礼还没有开始。酒店门口立着粉色的气球拱门，地上铺着红毯，两旁摆着签到台和鲜花。你签了到，递上红包——你包了一个很大的红包，大到你的银行卡余额有些吃紧。你觉得值得。你觉得这是你最后一次为ta花钱了，得大方一点。

你走进宴会厅，找了一个角落的位置坐下来。你选角落不是因为你想躲起来——好吧，也许有一点。但主要是因为从这个角度，你可以清楚地看到舞台上的每一个细节。

宴会厅里人很多。你认识的不多，大都是ta的亲戚和现在的朋友。你看到几个大学时的面孔，打了招呼，聊了几句。他们问你最近怎么样，你说挺好的。你问他们怎么样，他们也说挺好的。然后大家就不说话了。你们之间隔着七年的距离，已经找不到太多共同话题了。

婚礼开始了。

门开了，ta走进来。

你看到ta的那一刻，手里的筷子差点掉在地上。

ta穿着白色的礼服，头发梳得整整齐齐，比大学时瘦了一点，也好看了一点。ta的脸上带着笑，那种笑你看了一千遍一万遍，每一个细节你都记得，从眉眼弯起的角度到嘴角上扬的弧度。但今天的笑不一样。今天的笑不是对着你的，从来都不是对着你的，但今天你比任何时候都更清楚地意识到这一点。

另一个人走过来，牵着ta的手。你们一起走上舞台。

司仪说的话你没有怎么听进去。你的耳朵里嗡嗡响着，像是有一千只蜜蜂在振翅。你听到"爱情"、"承诺"、"永远"这些词从司仪嘴里蹦出来，每一个词都像一颗小石子，准确地击中你心里某个柔软的地方。

"请问，你愿意吗？"

"我愿意。"

