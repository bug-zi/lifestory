这就是她留给世界的全部了。一些小事，一封信，一个没有说出口的名字。你忽然觉得一个人活了一辈子，最后留下的不是什么伟大的成就，不是什么惊天动地的故事，只是一些小事和一封信，这似乎太少了。但转念一想，也许不少。也许一个人活着的全部意义，就是记住那些小事——喜欢听雨声，喜欢公交车最后一排靠窗，喜欢深夜泡面加蛋。这些小事加在一起，就是一个人的一生。而她的一生，被装在了一封信里，藏在一面墙的夹层中，等了二十年，终于被人发现了。

