你说："我也是。"

你们在那张长椅上坐了一个下午。你们聊了很多，也沉默了很多。沉默的时候你看着湖面，忽然觉得这个画面和梦里的那条河边很像。她靠在你肩上——和梦里一样的姿势。你忽然觉得，也许梦不是梦，也许是你们在前世或者某个平行世界里，就是这样过的。也许那些场景不是凭空产生的，也许它们来自某种更深的联系——深到你们自己都不知道。

