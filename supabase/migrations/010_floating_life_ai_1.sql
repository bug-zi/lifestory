他很久才回复。很久。你等了三天。三天后他回复了，只有三个字："是我。"

你们约在一个咖啡馆见面。沈屿来了，三十八岁，戴眼镜，穿了一件深灰色的外套，看起来很疲惫，眼底有很深的黑眼圈。他坐下来的时候手一直在搓裤腿，看得出来很紧张。

