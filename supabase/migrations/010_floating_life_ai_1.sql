你开始有意识地去看那些告白的世界。你想知道，如果告白了会怎样。

在第七号世界里，你在高二那年夏天，在学校操场的梧桐树下告白了。你买了一瓶冰可乐——因为那天三十八度——你走到她面前，把冰可乐递给她，说："我有个事想跟你说。"她说什么事。你说你喜欢她。她愣了几秒钟，然后接过可乐，说好。你们在一起三年。后来你们考上了不同城市的大学，异地恋撑了一年半，最后在一通很长的电话里平静地分手了。分手那天她哭了，你也哭了。你说对不起。她说不用对不起，我们都没有做错什么。但你们后来还是朋友，逢年过节会发消息说一声"新年快乐"或者"中秋快乐"。有时候她会发一张梧桐树的照片给你，什么都不配文字。你知道那是在说"我还记得"。

在第十二号世界里，你在高三毕业典礼那天告白了。你把一束花藏在书包里，九十九朵玫瑰，你攒了三个月的零花钱买的。等到所有人都走了，操场上只剩你们两个，你才拿出来给她。你说你喜欢她，从高一就开始了。她沉默了很久。然后她说"谢谢你告诉我"。她没有接受，但她说"谢谢你"。她说她现在不想谈恋爱，她要去很远的地方读书。后来她去了北方的大学，你留在南方。你们没有再联系，但你偶尔会在朋友圈看到她的动态。她去了很多地方，拍了很多照片，看起来过得很好。你看着那些照片会笑。不是苦涩的笑，是那种"我知道你过得好所以我也好"的笑。

在第二十三号世界里，你告白的方式很笨拙。你在QQ上发了一条消息："我喜欢你。"然后你立刻关了电脑，跑出了家门，在街上走了两个小时，不敢回去看她的回复。你走了三条街，在一个公园的秋千上坐了很久。后来你鼓起勇气回家，打开电脑，看到她回了一句："我知道。我也是。"你看着那五个字，在电脑前哭了。不是因为难过，是因为太高兴了。你们在一起了，后来结了婚。婚后生活不算轰轰烈烈，但你们从来没有吵过架。你们养了一只猫，周末一起去超市买菜。她买菜的时候会挑很久，你推着购物车在旁边等。你从来不催她。

在第三十一号世界里，你告白的时候下雨了。夏天的大雨，倾盆而下。你淋着雨站在她家楼下，喊她的名字。她从窗户探出头来，看到你淋成落汤鸡的样子，先是愣了一下，然后笑了。她拿了一把伞跑下来。她说："你傻不傻？"你说："可能有点。"她把伞撑到你头顶上，说："那我也陪你傻。"你们撑着一把伞在雨里走了很久。后来你们也分手了，但分手的原因很平淡——不是因为不爱了，是因为工作把你们拖到了不同的城市。你们在机场告别的时候，她说："谢谢你淋着雨站在我家楼下。"你说："谢谢你跑下来。"

在第四十二号世界里，你告白的方式是最普通的那种。你什么都没准备，就是在放学的时候走在她后面，走到校门口的时候忽然说了一句"我喜欢你"。声音很小，小到你自己都不确定有没有说出来。但她听到了。她停下脚步，转过头看着你。她说："你刚才说什么？"你的脸红了。你又大声说了一遍。她笑了，笑得很大声，笑到旁边的人都在看你。她说："终于。"她说终于。你不知道她等了多久。你也不知道你等了多久。你们在一起了，后来一起考上了同一所大学。大学四年你们几乎形影不离，你们一起泡图书馆，一起在食堂吃饭，一起在操场上散步。后来毕业了，你们去了一座城市工作，租了一间很小的公寓。公寓很小，但你们觉得够了。因为那间小公寓里住着两个人，而这两个人刚好是彼此最想见到的人。

你看了很多很多世界。几十个，上百个。有告白的世界，也有没有告白的世界。你发现了一个规律。

在所有告白的世界里，结局不尽相同——有的在一起了，有的被拒绝了，有的在一起又分开了。但在每一个告白的世界里，你都没有遗憾。因为你说出来了。不管结果如何，你把心里的话说出来了。你给了自己一个答案。你没有在深夜辗转反侧地想"如果当时说了会怎样"。

而在所有没有告白的世界里，无一例外，你都遗憾了。

🌙 没有告白的世界

你看了那些没有告白的世界。那些世界里的你，活得好像也没什么问题——该上学上学，该工作工作，该吃饭吃饭。表面上看一切正常。但你在那些世界的自己眼睛里看到了一种东西。

一种空缺。

一种"差一点"的空缺。像一首歌到了副歌部分忽然停了，像一个句子写到最后一个字被人把笔抽走了。

在第四十五号世界里，你上了大学，谈了别的恋爱，结了婚，有了孩子。你的人生看起来很圆满，圆满到你自己都信了。但有一天你在家整理旧物的时候，翻到了一张高中合照。合照上有陈念。她站在最后一排的角落里，低着头，好像在看什么。你拿着那张照片看了很久，看着她低着头的样子，忽然想起她做数学题的时候就是这个姿势。你轻轻把照片放回了箱子里，放在最底层，压在别的东西下面。你的妻子从旁边经过，问你在看什么。你说没什么。

在第六十二号世界里，你在十年后的同学会上见到了陈念。她胖了一点，剪了短发，穿了一件米色的连衣裙。你们聊了很多，聊各自的近况，聊以前的老师和同学，聊学校门口那家奶茶店是不是还在。你们聊到很晚，其他人都走了，只剩你们两个。散场的时候你送她到小区门口。她说"再见"，你也说"再见"。你转身走了几步，忽然想回头。你停下了。你真的很想回头。但你没有。你不知道为什么。你告诉自己已经太晚了，十年都过去了，回头能改变什么。你走到停车场，坐进车里，发动了引擎，然后趴在方向盘上，很久很久没有动。车里的空调吹着你的脸，冷冷的。你不知道自己在那里趴了多久。

在第七十八号世界里，你听说陈念结婚了。你在朋友圈看到了她的婚纱照。她穿着白色的婚纱，笑得很开心，旁边站着一个你不认识的男人。那个男人长得比你高，比你好看，笑起来很阳光。你看了那张照片很久，注意到她手腕上戴着一条细细的手链，那是她的习惯——她喜欢戴细的手链。然后你点了一个赞。你关掉手机，坐在黑暗的房间里。窗外有月光照进来，在地板上投下一块白色的光斑。你就坐在那块光斑旁边，不知道在想什么。也许在想"如果"。也许什么都没想。

在第九十三号世界里，你一辈子都没有告过白。你过了一辈子，一个普通人的普通一辈子。你退休了，搬到了一个小城市，每天早上去公园打太极，下午在家看电视。有一天你在公园的长椅上坐着，看到一个年轻女孩走过去。她的背影很像陈念——低马尾，走路的样子不紧不慢。你盯着她的背影看了很久。你知道那不是她。但你的眼眶还是湿了。你想起了十七岁那年的教室，你坐在她的斜前方，偶尔回头偷偷看她。她总是在做数学题，总是咬着笔帽。你回头看了无数次，一次都没有被她发现。你忽然想，如果你当时被她发现了，如果你当时被她看到你在看她，也许一切都会不一样。

你把这些世界一个一个看完。看得很慢，很仔细。然后你明白了。

你明白了告白的世界和不告白的世界之间的区别不在于结局好不好。告白可能被接受，也可能被拒绝。在一起可能白头偕老，也可能半路分道扬镳。但这些都不重要。重要的是你有没有给自己一个答案。告白的世界给了你答案，不管答案是什么，你至少知道了。你可以往前走了。没有告白的世界什么都没给你，只给了你一个永远无法回答的"如果"。这个"如果"不会随时间消失，它只会越来越重，重到压在你每一个深夜的胸口上。

✨ 现在

你站在那面镜子前，最后一次擦了擦镜面。镜子给你看了你当前所在的这个世界。这个世界里的你，十七岁，还没有告白。每天在教室里偷偷回头看陈念，一次都没有被她发现。

你放下手，转身走出了巷子。你走得很快，像是怕自己会后悔。你走到陈念家楼下的时候气喘吁吁的，不是累的，是紧张的。你抬头看了一眼她家的窗户，灯亮着。她在楼上。

你不知道该说什么，不知道她会不会答应，不知道如果被拒绝了你们还能不能做朋友。你不知道的事情太多了。但你想起那些没有告白的世界里的自己——他们在深夜辗转反侧，在同学会上欲言又止，在朋友圈的婚纱照前久久凝视，在公园的长椅上看着一个陌生女孩的背影湿了眼眶。你不想成为他们。你不想在十年后的某个深夜里，趴在方向盘上，不知道自己在想什么。

你拿出手机，给她发了一条消息。

"陈念，你有空吗？我想跟你说一件事。"

她很快回复了："什么事？"

你打了几个字，又删掉了。你打了"我喜欢你"，删掉了。又打了"其实我一直"，删掉了。又打了"我有个秘密想告诉你"，删掉了。你的手指在屏幕上悬了很久。你不知道为什么这么难。你已经看过那么多个世界的自己告白了，你知道告白之后的结局可能好可能坏，但无论好坏都比不告白好。你什么道理都懂。但道理归道理，手还是在抖。

你想起第三十一号世界里那个淋着雨站在楼下的自己，那个"傻"的自己。你想起第十二号世界里那个攒了三个月零花钱买花的自己。你想起第二十三号世界里那个发了消息就跑出家门在街上走两个小时的自己。他们都很傻。但他们都不遗憾。

你深吸一口气，打了五个字：

"我喜欢你。"

你按了发送。

消息发出去了。你盯着屏幕，心快要从嗓子眼里跳出来。你觉得自己可能要死了。不是真的要死，是紧张到觉得自己要死了。你等着她的回复。一秒。两秒。三秒。每一秒都像一个世纪。

她的回复来了。

"终于。"

只有一个词后面跟了一个句号。但你看了很久很久。你把那两个字看了很多遍。"终于"。她说"终于"。这意味着她也等了很久。意味着她也在等你说出口。意味着你们浪费了很多本来可以不浪费的时间。你忽然觉得鼻子很酸，不是难过，是一种说不出的感动。你想起第九十三号世界里那个在公园长椅上看年轻女孩背影的老头，他等了一辈子都没有等到这两个字。而你等了几个小时就等到了。你比他幸运。

你靠在墙上，抬头看着天空。天很蓝，有几朵云，白白的，软软的，像棉花糖。你忽然觉得这个天空和所有平行世界的天空都不一样。因为这个世界的天空下面，你终于说出口了。而她说"终于"。

你不知道你们后来会怎样。也许会在一起，也许不会。也许会白头偕老，也许会在某一天平静地分开。也许会养一只猫，也许会各自远行。但这些都不重要了。重要的是，在你所有的平行世界里，你选择了活在一个没有"如果"的那一个。

那个没有"如果"的世界，就是最好的世界。

