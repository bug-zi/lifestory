🌸 第三十七号柜台

周暮白已经在那条巷子里走了半个小时了。巷子很窄，两边是老旧的砖墙，头顶只露出一线天光。他踩过几块碎瓦片，绕过一辆生锈的自行车，在一扇很窄的木门前停下来。门上挂着一盏昏黄的灯笼，灯笼上写着一个字——"忘"。

他已经失眠四十七天了。

四十七天里，周暮白试过所有能想到的办法。酒精、跑步、褪黑素、数羊。他把和沈念安有关的东西全部扔了——照片、衣服、那盆她最喜欢的薄荷。但脑子里的东西扔不掉。她笑起来右边的酒窝，她生气时咬下嘴唇的样子，她走路时踩落叶发出的咔嚓声，她手指上冬天会生的冻疮，她每年冬天都说不让他买护手霜但每次都收下了的那种别扭。这些东西像是长在了他的骨头里，剔不掉。

他是在一个深夜的论坛帖子里看到这家店地址的。那时候凌晨三点，他又睡不着，躺在黑暗里刷手机，屏幕的蓝光照着天花板，像是海底漏下来的一缕光。帖子只有一句话："城西老巷尽头，有一家店，可以卖记忆。"底下两条评论，一条说"骗人的吧"，另一条说"我去过，是真的。但别去。"

周暮白第二天请了假，从下午找到天黑，才找到这个地方。他推门走了进去。

里面比外面看起来大得多。柜台很长，上面摆满了大小不一的玻璃瓶。每个瓶子里都有一团淡淡的光——暖黄的、浅蓝的、粉红的，像是傍晚天边最后一抹霞。有的光很亮，还在微微颤动，像是刚从什么人身上抽出来。有的已经很暗了，几乎看不清，像是随时都会灭掉。每个瓶子上都贴着一张小标签，写着日期和一个词。周暮白凑近看了一个，上面写的是"2019.夏——初恋"。另一个写的是"2015.冬——背叛"。还有一个只写了两个字："母亲"。再往里看，有一个瓶子特别小，标签上写着"2021.春——一只猫"。

店主是个老人，头发全白了，穿一件灰色长衫，像是从旧照片里走出来的人。他抬起头看了周暮白一眼，目光里没有好奇也没有同情，只有一种见多了的平静。

"要卖什么？"

"我想卖一段记忆。"

老人从柜台下面拿出一个空瓶子，递给他。瓶子比巴掌大一点，瓶口很宽，瓶壁很薄，摸上去有一种温热的触感，像是活的。

"把手放上去，想着你要卖掉的那段记忆。它会自己吸出来的。"

周暮白把右手掌心贴在瓶口上。他闭上眼睛，想起了沈念安。

🌸 沈念安

沈念安。他在心里默念这个名字的时候，胸口还是会发紧。

他们在一起四年。大一的秋天认识的，在图书馆三楼，靠窗的位置。窗外是一排银杏树，叶子已经黄了大半，金灿灿地挂在枝头。她穿一件米白色的针织衫，头发散着，耳朵里塞着耳机，面前摊着一本很厚的书。她侧脸的线条很好看，看书时会不自觉地转笔，偶尔叹一口气——不是烦躁的叹气，是看到好句子时的那种满足。

他们就这样安静地各自看了半个月的书，谁也没跟对方说话。后来有一天她没来，周暮白发现自己一下午都在看那个空位。书翻了两页就停下来，眼睛不听话地往右边瞟。他心里骂自己没出息，但第二天还是提前半小时占了那个靠窗的位子。

第三天她来了。他鼓起勇气递了一张纸条过去，上面写着"你昨天没来"。她看完纸条抬起头，冲他笑了一下。就是那个笑——右边有一个浅浅的酒窝，要很仔细看才能看到——把他整个人都点着了。后来周暮白无数次想，如果那天他没有写那张纸条，如果她没有笑，他的人生会不会完全不同。大概会的。但他不确定那是不是更好的人生。

后来他们在一起了。一起养过一只橘色的猫，胖得像个年糕，沈念安叫它"汤圆"。猫最喜欢趴在沈念安的膝盖上睡觉，她看书的时候它打呼噜，声音不大不小，像一台微型的拖拉机。一起在出租屋的阳台上种过一盆薄荷，她喜欢摘薄荷叶泡水喝，说嘴巴里会有凉丝丝的味道。周暮白嫌薄荷味道太冲，她就端着杯子凑到他嘴边说"你尝一口嘛"，然后在他喝的瞬间笑得眼睛弯起来。一起在深夜的便利店买过关东煮，她每次都拿萝卜和鱼丸，周暮白说你能不能换点别的，她说萝卜最好吃你别不懂。

有一次她发高烧，三十九度五。周暮白背着她跑了三条街去医院，十一月的夜风刮得脸疼。沈念安趴在他背上，额头滚烫，贴着他的后颈。她说："周暮白，你要是敢把我摔了，我就再也不理你了。"他说不会的。她又说："那你要背我一辈子。"他说好。她在他背上轻轻笑了一声，像猫打呼噜。

后来呢。后来一切都变了。

不是感情出了问题，不是吵架，不是背叛。是她的病。白血病，查出来的时候已经是晚期了。那天下午沈念安在学校门口的超市里买草莓，突然流了鼻血，怎么都止不住。周暮白接到电话赶到医院的时候，她坐在急诊室的椅子上，怀里还抱着那袋没来得及付钱的草莓，鼻子里塞着棉球，对他笑了笑说："草莓打折，可惜了。"

从确诊到离开，只有四个月。四个月里沈念安瘦了二十斤，头发掉光了，最后连说话的力气都没有了。周暮白每天守在病床旁边，看着她一点一点地变成另一个人。她的手本来是热的，后来变凉了。她的眼睛本来是亮的，后来变暗了。她不再说"你尝一口嘛"，不再踩落叶，不再在深夜拉着他去便利店买萝卜和鱼丸。

她走的那天晚上，外面下着雨。很大的雨，打在窗户上噼里啪啦的。周暮白握着沈念安的手，感觉她的手一点一点变凉，像是在慢慢融化。病房里很安静，只有心电监护仪的声音，滴、滴、滴，越来越慢。

沈念安最后跟他说的话是："你要好好的。"

周暮白说好。

但她没有说要他忘掉她。这是他自己决定的。他觉得记着太痛苦了，觉得自己活不下去了。他不吃不喝不睡，白天像行尸走肉一样上班，晚上缩在被子里发抖。他觉得自己快疯了。所以他来了这家店。

🌙 提取

瓶子亮了起来。

一团暖黄色的光从周暮白的掌心被抽出来，慢慢流进瓶子里。那团光里装着他们第一次见面时她穿的那件针织衫，装着他们第一次吵架后她在他枕头上留下的泪痕，装着他们在阳台上一起摘薄荷叶的下午，装着她在超市门口抱着草莓对他笑的那个傍晚，装着她最后叫他名字时的声音——已经哑了，像是从很远的地方传来的。光离开他手掌的时候，周暮白的心跟着空了一下。

他忽然觉得脑子里空了一块，像是一本书被人撕掉了中间的几页。他还在想她，但他已经不记得她的脸了。他知道他爱过一个人，但他不知道她长什么样了。他知道他很痛，但已经不记得为什么。这种感觉像什么呢——像手里抓着一根绳子，绳子的另一头系着什么很重的东西，但低头看的时候，绳子断了一半，另一头消失在雾里。你知道那里有东西，但你看不见。

瓶子里的光在微微颤动。周暮白透过玻璃看进去，那团暖黄色的光里有影子在动——一双手、一条围巾、一盆绿色的植物、一个橘色的胖东西。但他已经不知道这些画面意味着什么了。它们只是画面，没有温度，没有情感，像是在看一部和自己无关的老电影。

店主把瓶盖拧紧，在瓶身上贴了一张标签。他问："要多少钱？"

"随便。"

老人给了他一个数字。周暮白收了钱，转身走出了店门。

🌧️ 空洞

周暮白以为卖掉记忆会轻松。他错了。

记忆没了，感觉还在。而且因为没有记忆做载体，那些感觉变成了无根的浮萍，漂在他的身体里，找不到停靠的地方。

他走在街上，看到一家便利店，忽然胸口一阵发紧。他不知道为什么，只是觉得自己应该走进去买一份关东煮。但他不知道为什么要买，也不知道买给谁。他走进去了，站在关东煮的柜台前，看着锅里的萝卜和鱼丸发呆。萝卜煮得软烂，浮在褐色的汤里，冒着热气。店员问他"要什么"，他张了张嘴，什么都没说出来。他转头看了看便利店里的座椅区，靠窗的位置空着。他不知道为什么觉得那个位置不应该空着。转身走出去，站在门口，眼眶忽然就湿了。

回到家，打开冰箱，发现里面有一袋猫粮。周暮白不养猫。但他看着那袋猫粮，觉得它很重要，重要到不敢扔掉。他把它从冰箱里拿出来放在桌上，看了很久。手无意识地在桌上敲着，像是在等什么东西跳上来。桌面上有划痕，很浅的几道，像是猫爪留下的。他不知道那些划痕是怎么来的。

他开始失眠。不是因为想念——他已经不记得该想念谁了。是因为空洞。人生好像缺了一大块，他知道那里曾经有很重要的东西，但已经不知道是什么了。这种不知道比知道更可怕。知道痛在哪里，你还能捂住那个地方。不知道痛在哪里，只能整个人蜷缩起来，像被一张看不见的网兜住了。

夜里两点醒来。不是因为做了噩梦——他连梦都没有了。醒来只是因为胸口闷。他坐起来把灯打开，看着空荡荡的房间。双人床，只有一个人睡，另一边的被子叠得整整齐齐，像是在等人回来。衣柜里有两件不属于他的衣服，一件女式毛衣，一条围巾。围巾是红色的，很软，摸上去像是有人刚摘下来。他不知道那是谁的，但觉得那两件衣服散发着一种熟悉的气息，让他想哭。不是悲伤的哭，是那种丢了东西却想不起来丢了什么的哭。

他去看了心理医生。医生问他怎么了，他说他觉得心里缺了什么东西，但不知道是什么。医生问有没有经历什么变故。他说没有。他的人生很平淡，没发生什么特别的事。但他说完这句话忽然觉得自己在撒谎。他觉得有什么事发生过。很大的事。但就是想不起来。

医生给他开了药，说是抗焦虑的。他吃了，没什么用。那种空洞没有被药物填上，因为药物只能抑制情绪，不能制造记忆。他需要的不是平静，他需要的是知道。知道他失去了什么。知道他为什么这么痛。

🌀 第三十七号瓶子

周暮白每天都去那家店。不买东西，也不卖东西。只是站在柜台前，看着那个属于他的瓶子。瓶子被放在第三排第三十七号的位置上。里面的光一天比一天暗了。

店主起初不搭理他。后来大概是看烦了，问他为什么每天都来。

"我想看着它。"

"记忆不是看着就能留住的。"

"我知道。"周暮白说，"但我没办法。我怕有一天来了，那个瓶子已经灭了。"

老人沉默了一会儿。他从抽屉里拿出一个旧笔记本，翻到某一页，递给周暮白看。那一页上密密麻麻地写满了名字和日期，每个名字后面都有一个括号，里面写着"已灭"。

"这些都是来过的人。"老人说，"卖了记忆的，最后都会来。不是来买回去——规矩是卖出去就买不回来。他们是来看的。和你一样。"

"然后呢？"

"然后有的不来了。有的一直来，来好几年，直到瓶子灭了。灭了之后就不来了。不是不想来，是没有理由来了。你记不住那个瓶子了——连你卖过记忆这件事都会忘掉。"

周暮白看着笔记本上那些名字。有的名字旁边画了一条短线，像是一个句号。有的名字后面是空的，说明他们的瓶子还在亮着。他忽然问了一个自己也没想过的问题："那些瓶子灭了之后，那些记忆去哪了？"

"哪也没去。"老人说，"不存在了。就像从来没有发生过一样。"

周暮白站在柜台前，看着架子上那几百个瓶子。每个瓶子里都有一团光，每团光都是一个人的记忆。他忽然想，这座城里有这么多人卖掉了自己的记忆，他们现在是不是也和他一样，在一个深夜醒来，觉得胸口空了一块，却不知道那里曾经住着谁。

🕯️ 那个女人

有一天，周暮白在店门口碰到了一个女人。她大概二十五六岁，穿着一件浅蓝色的风衣，头发剪得很短，脸上没有表情。她走进店里，他走出来。擦肩而过的时候，他闻到了她身上有一股很淡的薄荷味。

薄荷味。

周暮白停下了脚步。他不知道为什么，这个味道让他觉得心口发堵。他站在门口，透过半掩的门缝看到那个女人走到柜台前。

"我想卖掉全部。"她说。

"全部？"

"嗯。全部。二十年的。父母、童年、初恋、所有的快乐。"她的声音很平，像是在说一件跟自己无关的事情，"过去太重了，我走不动了。"

店主看了她很久，像是在确认她是不是认真的。然后他从柜台下面拿出了最大的一个瓶子。那个瓶子比其他所有瓶子都大一圈，瓶壁上没有灰尘，像是专门为这种时候准备的。

周暮白转身走了。他没有回头看。他不敢看。他怕自己会冲进去拦住那个女人，告诉她不要卖。但他凭什么拦？他自己不也卖了吗？他连自己卖掉的记忆是什么都想不起来了。

他走在巷子里，头顶的那一线天光已经变成了晚霞的颜色。橘红色的光落在他肩膀上，暖的，像是有人把手放在那里。

周暮白忽然停住了。他站在巷子中间，低着头，看着地上的影子。影子很长，只有一个人的。但那影子的形状好像不太对，像是旁边少了一个人的轮廓。

他想，如果有来生——虽然他不记得自己为什么会有这种想法了——他不会再卖掉那些记忆了。那些痛、那些眼泪、那些深夜里翻来覆去睡不着的日子，都值得留着。因为那证明他爱过。一个人连痛都感觉不到了，那和死了有什么区别？

但周暮白已经不记得自己为什么站在巷子里了。他只是觉得胸口空了一块，那里曾经住着一个人。叫什么来着？他想不起来了。名字在舌尖上转了一圈，又缩回去了。他只知道那个人的手在冬天会很凉，喜欢喝一种凉丝丝味道的水，笑起来右边有一个浅浅的酒窝。

这些碎片已经拼不出一张脸了。

他抬头看了看天。天空很蓝，蓝得有点过分。巷子尽头的那盏灯笼亮了起来，昏黄的光在暮色里晃了一下，像是眨了一下眼。

灯笼上那个"忘"字，被风吹得转了半圈。
