🌙 温知夏

许言深认识温知夏是在高中。准确地说，是高二那年秋天的语文课上。语文老师让他们读史铁生的《我与地坛》，然后写一篇读后感。许言深写了一篇中规中矩的东西，温知夏交上去的却是一首诗。

老师把那首诗投影在黑板上。许言深记得很清楚，诗的最后一句是："地坛不是一座园子，是一个人对自己说'我还在'的方式。"全班安静了几秒钟，然后有人开始鼓掌。

许言深没有鼓掌。他转过头去看温知夏。她坐在靠窗的位置，阳光打在她侧脸上，她低着头，耳根是红的。她耳根红起来的样子很好看——这是许言深后来才知道的事，因为温知夏被夸的时候耳根总会红。

他们熟起来是因为一本借来借去的书。温知夏喜欢读诗，许言深喜欢读小说。他们交换书看，在扉页上写批注。温知夏的批注总是很短，三五个字，像是怕多说一个字就泄露了什么秘密。许言深的批注很长，写着写着就变成了一封小信。温知夏看了会在下面画一个笑脸，然后还给他。

高三那年冬天，许言深在温知夏的书里夹了一张纸条，上面写着："温知夏，我喜欢你。如果你也喜欢我，就在明天的早读课上戴那条蓝色的围巾。"

第二天，温知夏没有戴围巾。但她在许言深的桌兜里放了一杯热可可，杯子下面压着一张纸条："我不戴围巾。但我带了热可可。笨蛋。"

许言深看着那杯热可可，笑了整整一个早读课。

✨ 后来

后来他们在一起了。高中最后半年，他们一起上学、一起放学、一起在图书馆复习、一起在天台上看夕阳。温知夏喜欢在天台上念诗给许言深听，声音被风吹散了一半，他只听清了那些温柔的字眼。

然后高考来了。许言深考上了北方的大学，温知夏去了南方。他们约定好四年，说等毕业了就在同一个城市找工作。

但大学的第二年，温知夏的信开始变少了。不是不再写，而是间隔越来越长。从一周一封变成两周一封，再变成一个月一封。信里的内容也从日常琐事变成了大段的沉默，空白处多过文字。许言深给她打电话，她接了，但说话的声音听起来很疲惫。

"你怎么了？"

"没什么。就是有点累。"

他信了。或者说，他选择了相信。因为二十岁的许言深不知道，有些累不是因为学业，而是因为身体。

温知夏在大学第三年被确诊了。先天性心脏病，一直瞒着所有人。她小时候做过手术，医生说复发的概率很低，但低不等于零。零在大学三年级的时候来了。

她没有告诉许言深。她怕他担心，怕他放弃北方的学业跑回来，怕自己成为他的负担。她把所有的恐惧和疼痛都塞进了那些越来越短的信里，然后用"没什么，就是有点累"把它们封住。

许言深最后一次见到温知夏是在寒假。她比以前瘦了很多，脸色苍白，但笑起来还是那个样子——耳根会红。他们在县城的老街上走了一圈，路过高中学校门口，路过他们第一次交换书的那家书店，路过天台所在的旧教学楼。温知夏走得很慢，许言深以为她是冷。

"手好凉。"他握紧她的手。

"嗯，冬天嘛。"她笑了笑，把头靠在他肩膀上。

那是他们最后一次一起走路。

