这些梦境太真实了。真实到你白天会恍惚，会分不清哪些事情发生在梦里、哪些事情发生在现实中。你走到便利店，会下意识地想买两份关东煮。你坐在沙发上看电视，会下意识地往旁边挪一挪，给她腾位置。你出门的时候，会在门口站一会儿，好像在等谁跟你说一句"路上小心"。

