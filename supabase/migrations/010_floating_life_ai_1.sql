🌙 梦的终点

你们见了一面。她坐了四个小时的高铁来找你。你们约在一个公园的湖边，因为你说这个公园有一个长椅，面朝湖水，背靠一排柳树，和你梦里那条河边很像。你站在长椅旁边等她。你穿了一件白衬衫，出门前换了三次衣服。你站在那里，看着来来往往的人。你很紧张，手心全是汗。

