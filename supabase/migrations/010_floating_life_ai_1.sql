许言深在整理旧公寓的时候，在衣柜和墙壁之间的夹缝里发现了一封信。

那是一个很普通的白色信封，边角已经发黄了，上面没有写收件人，只用蓝色圆珠笔写了一行字——"等你想看的时候再看"。字迹娟秀，他一眼就认出来了。

是温知夏的字。

许言深蹲在地上，手里捏着那个信封，半天没动。窗外的阳光从半拉的窗帘缝隙里挤进来，照在地板上，灰尘在光柱里缓缓浮动。这间公寓他已经住了十年，衣柜搬进来的时候就没有再挪过位置。十年。三千六百五十天。而这封信在夹缝里等了更久。

