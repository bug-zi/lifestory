你没有说话。你只是握紧了她的手。

梦境重合这件事，你们始终没有找到一个合理的解释。科学家会说这是巧合，心理学家会说这是集体潜意识，浪漫的人会说这是命中注定。但你后来想明白了——有些事情不需要解释。两个陌生人做了一样的梦，梦里的他们是一对恋人，然后他们在现实中相遇了。这到底是巧合还是命运？你不知道。但你知道一件事：从你握住她手的那一刻起，你的梦终于醒了。不是梦消失了，而是梦变成了现实。

