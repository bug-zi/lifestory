你开始找沈屿。

又花了一个月。你在社交媒体上搜了无数个叫沈屿的人，一个一个看，一个一个排除。名字对不上的、年龄对不上的、地区对不上的，全部排除。最后你找到了一个。他的个人简介上写着"原XX社区居民"，和林晚住过同一个社区。他的头像是一张侧脸照，戴眼镜，看起来三十多岁。

