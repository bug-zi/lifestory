删掉吗？

删掉就意味着，那些笨拙的开场白、深夜的倾诉、吵架后的道歉、旅行前兴奋的语音、分手后仅剩的客套——统统都要消失。不是被放进某个回收站可以找回来，而是彻底地、永久地消失。

你的拇指微微发抖。

你想起今天下午，闺蜜林小薇说的那句话："你都分手三个月了，还留着聊天记录干嘛？等着过年翻出来复习一下怎么哭吗？"

当时你没吭声，端起咖啡喝了一口，烫了舌头。

但你心里清楚，你不是舍不得那些聊天记录。你是舍不得删掉它们的那个动作。因为一旦开始删，就意味着你真的承认了——这段关系，已经结束了。不是暂停，不是中场休息，是彻底地、不可逆地结束了。

你深吸一口气，退出了设置页面。

你决定，不用那个一键清空的功能。你要一条一条地删。从最后一条开始，往上，慢慢地，像拆除一座建筑，从顶层开始，一层一层地往下拆。每删掉一条，你就跟那段记忆做一次告别。

你觉得这是你欠自己的仪式。

凌晨两点三十四分，你坐起身来，把枕头垫在背后，调亮了手机屏幕。窗外的城市安静得像一座空城，只有远处偶尔传来一两声夜归汽车的引擎声。

你把聊天记录翻到最底部，看着那两条最后的消息。

一条是你发的："最近还好吗？"

另一条是他隔了八个小时之后回的："嗯，好。"

你盯着"嗯，好"看了很久。你想，这个句号真是干净利落，像是给一本书画上的句号。不拖泥带水，不留余地。

你按住了那条消息，手指在屏幕上停了两秒钟。手机震动了一下，弹出了操作菜单。你的手指移到"删除"上面，按了下去。

那条消息消失了。

你又开始删你自己的那条"最近还好吗？"

消失了。

聊天记录的最底部，变成了他发的："那就这样吧。"

那是你们分手那天，他说的最后一句话。当时你哭得喘不上气，打了一长串话想要挽回，又一个字一个字地删掉，最后只发了一个"好"。

那是三个月前的事了。

你捏了捏鼻梁，告诉自己不要哭。你今晚还有很多条消息要删。

你抬头看了看窗外，路灯的光透过窗帘的缝隙照进来，在墙上画了一道细长的金色线条。你突然觉得那道光很像你此刻的状态——细窄、孤独，但至少还亮着。

好吧，你对自己说。开始吧。

## 二、最早的记录

你把聊天记录拉到最顶端。

第一条消息的时间是2023年3月12日，晚上八点零四分。

发消息的人是他。内容是："你好，我是今天在书展上遇到的那个，穿灰色卫衣的。"

你看到这句话，嘴角不由自主地往上弯了弯。你记得那天。那是一个周日下午，市图书馆在办春季书展，你去淘旧书，在一堆落灰的外文小说里翻来翻去。你刚从书架上抽出一本毛姆的《刀锋》，一转头，就撞上了一个人的胸口。

那件灰色卫衣是纯棉的，你记得你闻到了洗衣液的味道，淡淡的薰衣草香。

"对不起对不起。"你手忙脚乱地道歉，手里的书差点掉了。

他帮你接住了那本书，低头看了一眼封面，笑了笑说："《刀锋》？品味不错。"

就是那么一句话，你就觉得这个人不太一样。不是因为什么一见钟情的心动，而是因为他没有像别人一样露出"一个女孩子看毛姆"的表情。

你们在书展上聊了二十分钟，从毛姆聊到加缪，从《局外人》聊到《鼠疫》。他说他最喜欢《鼠疫》里那句话——"在苦难中，我学到的是一个人的内心深处，总有些什么东西比苦难更强大。"

你当时想，这个人说话有点文绉绉的，但听起来不讨厌。

他问你加没加微信。你犹豫了一下，还是让他扫了你的码。

他的微信名叫"走神"，头像是一张模糊的城市夜景，看不出是哪个城市。你后来问他为什么叫这个名字，他说："因为我老走神。别人说话的时候，我经常听不进去，脑子里在想别的事。"

你说："那你怎么跟我聊天的时候不走神？"

他发了一个笑哭的表情，然后说："因为你说话比较有意思。"

你往下翻，看到了自己回复的第一条消息。

"你好！我也记得你，你推荐的《星辰的继承者》我打算找来看看。"

你看着这句话，觉得那时候的自己真是拘谨得可爱。明明心里想着"这个人还不错"，嘴上却只说"我打算找来看看"。实际上你当天晚上就在网上下了单，第二天书就到了，第三天你就看完了。

你在第三天晚上给他发了一条消息："看完了。你说得对，霍尔德曼确实被低估了。"

他秒回："才三天？你是不是没睡觉？"

你说："睡了，就是看得快。"

他说："那你看完《永远的战争》了吗？"

你说："没有，但已经买了。"

他说："那我们有个读书计划了。"

就是这样一段对话。平淡得像白开水，但你那时候喝得甘之如饴。你们开始频繁地聊天，从书聊到电影，从电影聊到音乐，从音乐聊到各自的工作和生活。他是一名建筑设计师，加班是常态，经常晚上十一点还在改图纸。你是一名中学语文老师，每天跟一群精力旺盛的初中生斗智斗勇。

你们的作息完美互补——他白天忙，你晚上忙，刚好能在对方空闲的时候聊上天。

你继续往下翻，看到了那些最初的消息。没有暧昧，没有试探，只有两个年轻人因为一本毛姆而产生的纯粹的好奇和好感。

"你今天看了什么书？"

"加班到十一点，终于把方案改完了。"

"我们班有个学生写了一篇特别搞笑的作文，我给你念念。"

"念吧，我现在需要笑一笑。"

你按住了一条消息，犹豫了一下，还是删了。

然后又删了一条。

又一条。

每删一条，就像是从一本相册里抽走一张照片。你知道那些照片还在你的记忆里，但相册正在变得越来越薄。

你的手指在屏幕上机械地滑动着：翻到消息，长按，删除，翻到下一条，长按，删除。屏幕上的文字一行一行地消失，像是在倒计时。

你删掉了你们讨论《刀锋》的那十几条消息。你记得那天晚上，你跟他说拉里最后选择了"晃膀子"，不去追求世俗的成功。他说他能理解拉里，因为他有时候也想什么都不做，就在街上走走，看看天。

你当时觉得他好浪漫。

现在你看着那些被删掉的消息留下的空白，觉得那些空白才是最真实的东西。因为人和人之间的关系，说到底就是不断产生又不断消失的文字。此刻的你正在加速这个过程。

你揉了揉眼睛，继续删。

## 三、在一起的日子

你翻到了2023年5月17日的聊天记录。

那一天，他跟你表白了。

那时候你们已经聊了两个多月，每天的消息从三五条变成了二三十条，周末的时候能聊到上百条。你们像两个贪吃的小孩，捧着手机不停地往对话里塞文字，生怕停下来就会失去什么。

他的表白并不浪漫。那天晚上十一点多，你正准备睡觉，他突然发了一条消息过来。

"我想了很久，不知道怎么开口。"

你问："怎么了？"

他说："我喜欢你。不是朋友的那种喜欢。"

你盯着屏幕看了整整三分钟，心跳声大得像是有人在你耳朵旁边敲鼓。你打了一行字又删掉，打了又删掉，反反复复七八次，最后只回了两个字。

"我也。"

他说："'我也'什么？"

你说："'我也'喜欢你。"

他发了一连串感叹号，然后说："天哪，我以为你会拒绝我。"

你说："我为什么要拒绝你？"

他说："因为我不知道我哪里好。"

你说："你也不用知道。我觉得你好就行了。"

那天晚上你们一直聊到凌晨四点。他问你现在能不能打电话，你说你穿着睡衣头发乱糟糟的，他说他才不在乎你长什么样。然后他的电话就打进来了，你犹豫了两秒，接了。

他的声音从听筒里传过来，比你想的要低沉一些："喂。"

你说："喂。"

然后两个人都不说话，就那么沉默了十几秒钟。但你一点也不觉得尴尬。你能听到他那边轻微的电流声，还有他呼吸的声音。你觉得那十几秒钟的沉默，比你们之前说的所有话加在一起都亲密。

从那天开始，聊天记录就变了味道。

以前是两条平行线，偶尔交叉一下。现在变成了麻花辫，拧在一起分都分不开。

"早安。"

"早安呀，昨晚睡得好吗？"

"还行，梦见你了。"

"梦见我什么？"

"梦见你请我吃火锅，结果你自己把毛肚全吃完了。"

"哈哈哈哈哈这个梦太真实了。"

你翻到了六月份的消息。那段时间你们恨不得24小时黏在一起，但各自都要上班，只能在手机上弥补。

"中午吃了什么？"他问。

"食堂的糖醋排骨，难吃死了。你呢？"

"外卖，一份难吃的黄焖鸡。"

"那我们扯平了。"

"没有，因为你在难吃的同时还很好看。"

"油嘴滑舌。"

"你说得对，我嘴确实甜。"

你看到这里，手指停住了。你差点就要打一行字过去——"你现在也是这样跟别人说话的吗？"但你及时收住了自己。你们已经分手了，你没有资格问这种问题。

你继续往下翻。

七月，你说你想去看海。他说等他忙完这个项目就带你去。你说你不想等。他说那就下个周末。你说好。

然后那个周末真的去了。你们坐了三个小时的高铁到了海边，住在一个能看到海的民宿里。晚上你们坐在阳台上，海风把你的头发吹得乱七八糟，他伸手帮你拢了拢头发，说："你的头发里有海水的味道。"

你说："你的衣服也是。"

他笑了笑，把下巴搁在你的头顶上。

你记得那一刻，你觉得全世界都安静了，只剩下海浪的声音和他的心跳声。

回来之后，你给他发了一条消息："今天很开心。"

他说："我也是。每天都很开心。因为有你。"

你看到这句话的时候，眼睛酸了一下。不是因为感动，而是因为你知道这句话现在听起来有多么讽刺。每天都很开心。因为有你。可是后来呢？后来那些"每天"变成了"有时候"，"很开心"变成了"还行吧"，"因为有你"变成了没有下文。

你用力地按住了一条消息，删了。

然后删了下一条。

又一条。

你删掉了所有的"早安"和"晚安"，删掉了所有的"想你"和"等你"，删掉了那些只有情侣之间才会说的、旁人看了会起鸡皮疙瘩的甜蜜废话。

你删得很用力，好像在跟那些甜蜜的日子较劲。删得越多，你的动作越快，像是一个人在黑暗中拼命往前走，不敢停下来，因为一停下来就会发现自己有多害怕。

但你还是在一条消息前面停住了。

那是他发的一张照片。照片里是你的手，放在一杯咖啡旁边，手背上有一道浅浅的疤——那是你小时候被猫抓的。照片下面他写了一行字："你的手真好看。"

你盯着那张照片看了很久，久到屏幕自动变暗了。

你没有删这条。

你把它截图保存到了相册里，然后才删掉了原消息。

你觉得自己真是无可救药。

## 四、异地

九月份，他被公司派到了另一个城市的分部，为期半年。

你们开始了异地恋。

最初的几天还好。你们视频、打电话、发语音消息，好像距离只是一串数字，不代表任何实质性的东西。他给你看他那边的出租屋，小得像一只火柴盒，窗外是一面灰色的墙。你说："好惨。"他说："习惯了。我这个人不怕苦。"

你说："你怕不怕孤独？"

他沉默了一下，说："有你在，就不怕。"

那段时间，聊天记录变成了你们唯一的纽带。你们在消息里分享每一天的细节——他画了多少张图纸，你批改了多少份作业，他吃了什么外卖，你跟同事吵了什么架。事无巨细，什么都往聊天框里塞。

"今天加班到九点，回来发现楼下那家兰州拉面关门了，只能吃泡面。"

"可怜。"

"你呢？今天怎么样？"

"还行。上课的时候有个学生睡着了，我走到他面前敲桌子，他居然说'老师我在闭目思考'。"

"哈哈哈哈这学生是个天才。"

"我都快被他气死了。"

"气完记得笑一笑，笑一笑十年少。"

"你以为你是我的养生顾问吗？"

"不，我是你的男朋友。男朋友的职责就是让你笑。"

你看到这些消息，发现你们的异地恋在最初的几个星期里并没有想象中那么难。因为你们都很努力。你每天给他发你看到的有趣的事——一只在路灯下打盹的流浪猫、一棵被台风吹歪的行道树、学生写的一句让你笑出声的造句。他每天给你发他的工作进展——一条新画好的线、一个终于通过的方案、一张窗外的晚霞照片。

"你看，今天的晚霞。"他发了一张照片，天空是橘红色的，像打翻了一罐果酱。

你回了一张你这边天空的照片——灰蒙蒙的，什么都看不到。"你看看我这边。"

他说："没关系，你那边看不到晚霞，就看我拍的。就当是替你看的。"

你说："你什么时候变得这么会说话了？"

他说："自从遇到你以后。"

你翻到这里，发现那时候的你真的很快乐。异地恋的苦你几乎没有尝到，因为他总是用各种各样的方式把那些苦给裹上糖衣。但你后来才知道，糖衣终究是糖衣，里面的苦是裹不住的。

十月中旬，你请了两天假，坐了五个小时的高铁去看他。

你到了他的城市之后，在火车站给他发消息："我到了。"

他回："什么？你怎么来了？"

你说："惊喜啊。惊不惊喜？"

他说："你疯了吧，我这边乱得跟狗窝一样。"

你说："我又不是来看你的房子的。"

他来火车站接你的时候，穿着那件你熟悉的灰色卫衣，瘦了一圈，眼睛下面有明显的黑眼圈。你看到他的第一反应不是感动，而是心疼。你说："你是不是没好好吃饭？"

他摸了摸你的头，说："你好好的来干嘛，多折腾。"

你说："我想你了。"

他没有说话，只是抱了抱你。那个拥抱很紧，紧到你有点喘不上气。后来你才知道，他抱得那么紧，不是因为想你，而是因为愧疚。

那两天你们在他那个小出租屋里度过了平平淡淡的时光。你帮他收拾了房间，给他做了一顿饭——用的是你从家里带来的调料包。他吃了第一口就笑了，说："好吃。比外卖好吃一百倍。"

你说："那你赶紧回来，回来我天天给你做。"

他说："好。"

那个"好"字说得轻飘飘的，像一片落在水面上的叶子。你当时没有听出来，但后来回想起来，那个"好"字里面已经有了犹豫。

你离开的时候，他在火车站的检票口外面站着，隔着人流看了你一眼。你朝他挥了挥手，他也挥了挥手。然后你转身走进了检票口，没有回头。

你后来给他发了一条消息："我上车了。"

他回了一个"嗯"。

你盯着那个"嗯"字看了很久，总觉得少了点什么。以前他会说"到了告诉我"或者"路上小心"或者"想你了"，但现在只有一个"嗯"。

你告诉自己，他可能是累了。他加班那么辛苦，你去看他，他又得陪你还得工作，肯定累。

你不断地替他找借口。那是你最好的本事——自欺欺人。

你删掉了那些异地恋的消息，一条一条地删。视频通话的记录删了，语音消息删了，他拍的晚霞照片删了，你拍的天空照片删了。你删得很快，因为你不想在那些甜蜜的消息里停留太久。你知道自己会陷进去。

但你还是在一条消息前面停了一下。

那是他发的一句话："有你在，就不怕。"

你咬了咬嘴唇，删掉了。

屏幕上空了一小块。像是一件毛衣被抽掉了一根线，正在慢慢地、一点一点地散开。

## 五、裂痕

十一月，你们的消息从每天几十条变成了十几条，再变成了几条。

裂痕就是这样出现的。不是某一天突然裂开的，而是像瓷器上的冰裂纹，一条细线接着一条细线，慢慢地蔓延，直到整只碗碎掉。

起初你安慰自己，说异地恋就是这样，新鲜感过了，话题少了，很正常。你试着找新的话题——你看了一本新书，你看了一部新电影，你发现了一家新开的小面馆。但他的回复越来越短了。

"我今天看了一部很好看的电影，叫什么来着……对，《坠落的审判》。你看过吗？"

"没有。"

"推荐你看，特别好。"

"好。"

就一个"好"字。你不知道这个"好"是什么意思。是"好的我记下了会去看"，还是"好的我知道了别再说了"？你没有问。你怕问了之后他的回答会让你失望。

你开始数他回复消息的时间。以前他都是秒回，或者最多隔几分钟。现在动不动就是一两个小时，甚至更久。你告诉自己他在忙，但你知道他中午有休息时间，下班之后也不是一直在画图。

有一天你忍不住了，问他："你最近是不是很忙？"

他说："还好。"

你说："怎么都不怎么跟我聊天了？"

过了四十分钟，他回："就是累了，没什么精力。"

你说："是不是我哪里做得不好？"

他说："没有，你别多想。"

你别多想。

