## 六、最后的记录

分手那天是2024年1月6号。

你记得很清楚，因为那天是周六，你本来打算给他一个惊喜——你买了一件新毛衣，打算下周穿着去看他。你发了一条消息问他："下周我来看你好不好？"

过了两个小时，他回了一条消息，很短。

"我觉得我们需要谈谈。"

你看到这条消息的时候，心猛地往下沉了一下。你知道"我们需要谈谈"这五个字意味着什么——它是一颗信号弹，升到空中之后，照亮的不是希望，而是即将到来的灾难。

你回："谈什么？"

又过了一个小时。你在这一个小时里什么都做不了，坐在沙发上，抱着一个抱枕，电视开着但你什么都没看。

他的消息终于来了。

"我觉得我们可能不合适。"

你说："为什么？"

他说："我这边的事情太多了，我没有精力维持一段感情。"

你说："我可以等。等你忙完了就好了。"

他说："不是忙不忙的问题。是我觉得……我们不合适。从一开始就不太合适。"

这句话像一把刀，从你的胸口直直地捅了进去。你不知道一个人可以说出"从一开始就不太合适"这样的话——什么意思？那之前那些甜蜜的话都是假的吗？那些早安晚安、想你等你、在一起很开心、有你在就不怕——那些全都是假的？

你打了一行字："你是说，你从一开始就在骗我？"

然后你删掉了，重新打了一行："你能不能说清楚？"

他又沉默了很久。

然后他说："我没有骗你。我只是觉得……我们不够了解彼此。异地恋太难了，我撑不住了。"

你说："那你为什么之前不说？"

他说："我不想伤害你。"

你笑了。不是开心地笑，而是那种被悲伤压垮之后的苦笑。他不想伤害你，所以选择了在你毫无防备的时候说出分手。他不想伤害你，所以用了最残忍的方式——把所有的问题归结为"不合适"，把所有的责任摊在两个人头上，好像这段感情的失败你也有份。

你发了最后一条消息："好。那就这样吧。"

他回了一个字："嗯。"

然后你们就再也没有说过话。直到三个月后，你发了那条"最近还好吗"，他回了"嗯，好"。

你翻到了分手当天的聊天记录，看着那些文字，感觉像在看另一个人的故事。那个在沙发上抱着抱枕哭了一整晚的人是你吗？那个反复查看他朋友圈看他有没有更新的人是你吗？那个半夜醒来拿起手机看有没有新消息的人是你吗？

是的，都是你。

你删掉了那些分手时的消息。每一条都删得很慢，像是在拆一封信，每拆一页都要读一遍，然后折好，放进火里。

你删掉了他的"我觉得我们需要谈谈"。删掉了你的"谈什么"。删掉了他的"我觉得我们可能不合适"。删掉了你所有的挽留。删掉了他的"我不想伤害你"。删掉了你的"好。那就这样吧。"

最后你删掉了那个"嗯"字。

那个终结了一切的"嗯"。

你删掉它的时候，手指在屏幕上停了很久。你忽然想把它抄下来，抄在纸上，折好，放进抽屉里。但你没有那么做。因为你已经从这段关系里学到了一件事——留存任何东西，都是给自己留一个痛苦的入口。

删完了。

你长出了一口气，发现你的手在发抖。不是冷的，是那些文字被你删掉之后的空洞感，让你的身体产生了一种失重的错觉。

你继续往上翻，看到了那些分手后仅存的几条消息——你发的"最近还好吗"，他发的"嗯，好"。然后你再往上翻，看到了那三个月沉默期里的一条朋友圈消息。不是他发的，是你发的。你发了一条朋友圈说"一个人也要好好生活"，配了一张你做的番茄炒蛋的照片。

他点了赞。

那是你们分手后他唯一一次出现在你的世界里——一个赞，轻飘飘的，像一片羽毛落在了水面上，连涟漪都没激起就沉了下去。

你删掉了你们在沉默期之后的那几条消息。客气、疏离、像两个在电梯里偶遇的陌生人，点点头就算打了招呼。

删完了这些，你发现聊天记录已经所剩不多了。三千七百多条消息，你删了大半，剩下的那些散落在不同的日期里，像是一片废墟里残存的几面墙。

## 七、删除

凌晨四点四十八分。

你已经删了两个多小时了。

你的眼睛干涩得厉害，手机屏幕的光已经从舒适变成了刺眼。你的脖子酸痛，手指僵硬，但你不想停下来。因为你已经走了一千步了，你不想在最后一步的时候放弃。

你看着剩下的那些零散的消息，有些是你们讨论书的，有些是他加班时你发去的鼓励，有些是你旅行时拍的照片，有些是你们互发的表情包——一只歪着头的柴犬、一个捂脸哭的卡通猫、一个比心的手指。

你一条一条地删。

删掉了他发给你的第一张自拍——他站在公司楼下，穿着深蓝色的羽绒服，对着镜头笑了一下。照片拍得不好，光线暗，他的脸有一半在阴影里。但你当时觉得那张照片是世界上最好看的照片。

删掉了你发给他的一段语音。那是一个深夜，你喝了一点酒，借着酒意给他念了一首诗。你念的是辛波斯卡的《一见钟情》——"他们彼此深信，是瞬间迸发的热情让他们相遇。"你念完之后，他回了一句话："你的声音真好听。"

删掉了你们约好一起跨年时发的消息。那是2023年的最后一天，你们本来约好一起倒数，但他临时被通知加班。你一个人在出租屋里看跨年晚会，到了零点的时候给他发了一句"新年快乐"。他过了二十分钟才回了一句"新年快乐"。

那一晚你的"新年快乐"里有很多话没说出口——"我想你"、"你什么时候回来"、"我一个人好孤独"。但你只说了四个字，因为你知道说多了只会让他觉得烦。

你删掉了那条"新年快乐"。

然后你删掉了下一条，又一条。

聊天记录变得越来越短了。屏幕上的空白越来越多，像是一本书正在被一页一页地撕掉。你看到那些你曾经反复阅读过的消息正在消失，一条又一条，无声无息地退出了你的世界。

你终于删到了最后几条。

那是最初的几条消息——你加他微信之后的对话。他说"你好"，你说"你好"。他说"我是今天在书展上遇到的那个"，你说"我也记得你"。

你的手指在这几条消息上面停留了很久。

你想起了那天在书展上，你撞上了他的胸口，闻到了他卫衣上的薰衣草洗衣液味。你想起了他低头看着《刀锋》封面时的笑容，想起了他说"品味不错"时的表情。

