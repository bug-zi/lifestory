你又拿了一瓶牛奶。全脂的，玻璃瓶装的那种。以前她总说你喝牛奶像小孩子，你都三十岁的人了还抱着奶瓶喝。你就笑着说那你也喝，她就真的也买了一瓶，两个人在出租屋里面对面喝牛奶，喝完了还比谁的奶胡子更长。

你在货架间转了两圈，拿了泡面和牛奶准备去结账。经过啤酒货架的时候，你犹豫了一下，还是没拿。你不是一个喜欢借酒消愁的人，虽然今晚你觉得这个念头格外诱人。

那个灰卫衣的女孩还在冷柜前。你路过她身边的时候，发现她手里拿了一盒关东煮——就是那种便利店自己煮的，装在纸碗里，冒着热气。她还拿了两罐啤酒，一罐已经打开了，握在另一只手里。

她的脸你终于看到了——不是那种让人过目不忘的漂亮，但眼睛很大，睫毛很长，鼻尖有点红。你在心里猜测她大概也哭了很久。因为你的眼睛也是那样，红红的，肿肿的，像是被什么东西泡过。

便利店里播放着某首老歌，你听不太清歌词，只有旋律在白炽灯下缓缓流淌。你们两个人就这样各自在货架间穿行，像两条平行线，各自挑选着各自的孤独，谁也没有看谁一眼。

但你觉得，在这个凌晨两点的便利店里，你们大概是全世界最相似的两个陌生人。

## 三、收银台

你先走到收银台前。店员扫了你的方便面和牛奶，报了一个数字，你扫码付了钱。整个过程没有一句话。你把牛奶塞进口袋，方便面夹在胳膊底下，转身准备走。

就在这时候，她也走过来了。

她把关东煮和两罐啤酒放在收银台上。店员扫完码，她掏出手机付钱。你注意到她的手在发抖，不是冷的那种抖，是那种情绪上来之后控制不住的抖。她付完钱之后深吸了一口气，像是要把什么东西压回去。

你们在收银台前对视了一秒。

就一秒。但你在那一秒里看到了很多东西——她的眼睛是湿的，嘴唇在微微颤动，下巴上有一颗不太明显的痣。她看起来二十多岁，也许跟你差不多大，也许更小。她整个人散发着一种"我刚哭过但我不想让任何人知道"的气息。

而你知道，你自己也是这样。

你们几乎同时往门口走。便利店的门是自动的，你走左边，她走右边，两个人差点撞到一起。你侧身让她先过，她小声说了句"谢谢"，声音沙哑得像是被砂纸打磨过。

你愣了一下。不是因为她说谢谢，而是因为她的声音让你觉得——这个世界上，在此时此刻，不止你一个人在熬。

你推开门走出去，夜风扑面而来，带着初春特有的凉意。你打算在便利店门口把泡面吃了——回去泡太麻烦了，家里那个电水壶你不确定有没有水，而且你不想一个人坐在空荡荡的出租屋里吃泡面，那样会更难受。

你打开方便面的包装袋，把调料包撕开倒进去。便利店门口有一个免费供应热水的机器，你接了热水，找了双一次性筷子，然后在门口的台阶上坐了下来。

三秒钟之后，她也出来了。

她手里捧着那碗关东煮，两罐啤酒夹在胳膊和身体之间，也在找地方坐。你看到她四下看了看，最后目光落在你旁边的台阶上。

她犹豫了一下，还是走过来坐下了。你们之间隔了大约一个拳头的距离。

谁也没有说话。

## 四、门口的台阶

便利店门口的台阶是水泥的，坐上去又硬又凉。但凌晨两点的你根本不在乎这些，你的身体已经麻木了，感受不到冷暖。你只顾着低头吃泡面，热气扑在脸上，模糊了你的视线——也许模糊的不只是热气。

她也在吃东西。关东煮的热气比泡面还大，整个纸碗都在冒白烟。她用竹签扎起一块鱼豆腐，咬了一口，然后轻轻"嘶"了一声——烫到了。

你没忍住笑了一下。很小的一声，几乎听不见。但她听到了，侧过头看了你一眼。

你赶紧把笑收回去，低下头继续吃面。

她也转回头去，继续吃她的关东煮。

台阶下面是空荡荡的街道。路灯把你们两个人的影子投在地上，影子的方向是一致的，像是两个人肩并肩坐在一起。偶尔有出租车开过去，车灯扫过你们的脸，一闪而过。便利店的玻璃门上映着你们的背影，一个弯着腰吃泡面，一个捧着碗吃关东煮，看起来像是两个无家可归的人。

她喝完了汤，把纸碗放在一边，打开了一罐啤酒。易拉环拉开的声音在安静的夜里格外清脆。她喝了一口，然后长长地呼了一口气。

你也喝了一口牛奶。冰凉的液体从嗓子滑下去，和嘴里泡面的热度混在一起，形成一种奇怪的口感。

"你也是睡不着吗？"

她突然开口了。声音还是沙哑的，但比刚才在收银台时好了一些。

你抬起头看着她。她没有看你，眼睛盯着对面的街道，手里的啤酒罐在指尖慢慢转动。

"嗯。"你说。

"我也是。"她说。

然后又沉默了。

但这次的沉默跟刚才不一样了。刚才你们是两个完全的陌生人，互相保持着警惕和距离。现在，因为那一问一答，你们之间多了一条看不见的线。这条线很细，但足以让你们不再是完全的陌生人。

她把另一罐啤酒推到你面前。

"喝吗？"

你看了看手里的牛奶，又看了看她推过来的啤酒。你把牛奶放下，接过了啤酒。

"谢谢。"

易拉环拉开的声音又一次响起。你们同时喝了一口。

啤酒是冰的，夜风是凉的，台阶是冷的。但你觉得有什么东西在你的胸口慢慢热起来——不是爱情，不是心动，而是一种更朴素的东西。是一种"原来我不是一个人"的感觉。

这种感觉很轻，但在凌晨两点的便利店门口，它足够让一个碎掉的人觉得自己还没完全碎。

## 五、对话

"你失恋了吧？"她先问的。

你愣住了。不是因为她说中了，而是因为她问得太直接。你本以为自己隐藏得很好，但原来在凌晨的便利店灯光下，一切伪装都是透明的。

"你怎么知道？"

"因为你跟我一样。"她转过头来看着你，嘴角有一个很浅的弧度，不算笑，但也不是哭。"一看就知道。眼睛红的，脸是肿的，走路的时候拖着脚，选泡面的时候在货架前站了五分钟。"

"你注意到了？"

"很难不注意到。整个便利店就我们两个人。"

你无话可说。她说得对，凌晨两点的便利店是一个很小的世界，小到你们根本不可能忽略彼此的存在。

"她不要你了？"你问。

"嗯。"她低下头，手指抠着啤酒罐上的拉环。"三年了。她说明明是两个方向的人，再走下去只会互相耽误。"

"她？"

"对，她。"她抬起头看了你一眼，眼神坦坦荡荡的。"你介意吗？"

"不介意。"你说。你是真的不介意。在凌晨两点的便利店门口，谁还在乎那些东西呢。

"你呢？"她问，"是'她'还是'他'？"

"她。"

"多久？"

"两年。"你喝了口啤酒，让酒精在嘴巴里停留了一会儿才咽下去。"她说她不想再等了，说我给不了她想要的生活。"

"什么生活？"

"她自己大概也说不清楚。大概就是那种——有房子、有车子、有未来规划的、让人安心的生活吧。而我只有一堆不确定。"

她沉默了一会儿，然后说："我们真像。"

"哪里像？"

"都被一个人用一个模糊的理由丢下了。你被'未来'丢下了，我被'方向'丢下了。其实说白了，就是不够爱了。不够爱了就什么都可以成为理由。"

你觉得她说得对。太对了。对到你想哭。

但你没有哭。你只是用力攥了攥手里的啤酒罐，铝皮被你捏得变了形。

"你哭了多久？"她问。

"没哭。"你说。

她看了你一眼，没有拆穿你。

"我哭了整整一个下午。"她主动坦白。"从三点哭到六点，然后擦干眼泪出门吃饭，吃完饭回来又哭。枕头湿了两面，后来实在没地方哭了我才出来的。"

"你比我坦诚。"你说。

"跟陌生人有什么不能坦诚的。"她说着，嘴角终于有了一个真正的笑容。"你又不认识我，我不怕你笑话我。明天天一亮，你我各自消失在人群里，谁也不认识谁。"

你觉得她说的这个道理很深刻。人在最亲近的人面前反而要藏着掖着，因为害怕失去。而在陌生人面前，倒是可以把所有伤口都摊开来看。反正不会再见，反正不必在意对方的评价。

于是你也打开了话匣子。

你跟她说你们是怎么认识的，在朋友的生日聚会上，她坐在你对面，你鼓起勇气跟她搭了第一句话。你跟她说你们第一次约会是在一家很小的日料店，她点了一碗味噌汤，喝了一口说好咸，然后整碗都喝完了。你跟她说你们一起养过一盆绿萝，后来绿萝死了，她说是你浇太多水了，你说是她放的位置晒不到太阳。你跟她说分手那天你准备了很长时间的告白——不是求复合的那种告白，而是想把所有没说过的话都说出来。

"说出来了吗？"她问。

"没有。她没给我机会。她说完那句话就走了，我张了张嘴，什么声音都没有发出来。"

"那你现在说给我听吧。"她看着你，眼睛在路灯的光里亮晶晶的。"我替她听着。"

你看着她。一个在凌晨两点的便利店里遇到的陌生女孩，穿着灰色卫衣、鼻尖通红、手里拿着一罐啤酒，说要替一个再也不会回来的人听你说话。

你真的说了。

你说了所有你想说但没有机会说的话。你说你其实一直都知道她不太开心，只是你不知道该怎么办。你说你有时候觉得自己就像一杯温水，不够烫也不够凉，没什么存在感。你说你最难过的时候不是她说分手的那一刻，而是她转身离开之后，你一个人站在那里，感觉自己像一棵被连根拔起的树。

她听着，一直听着，没有打断你。等你终于说完了，她沉默了好一会儿，然后轻轻说了一句：

"你说的这些，都很好。她错过了。"

就这五个字——"她错过了"——让你觉得胸口那个堵了好几天的东西突然松动了。

然后她也开始说。

她说她们是在大学里认识的，她大一，对方大三。她说她喜欢对方身上那种沉稳的气质，什么都安排得井井有条，跟她自己的兵荒马乱完全相反。她说她们在一起的三年是她人生中最好的三年，也是她最害怕失去的三年。她说分手的时候对方非常平静，平静到她怀疑对方是不是早就在心里演练过很多遍了。

"最可怕的不是她不爱我了，"她说，"是她不爱我了，但还一脸不忍心的样子。好像我是什么需要被小心放下的易碎品。我宁可她狠一点，干脆一点，不要那种温柔。那种温柔比刀子还疼。"

你听着，用力点了点头。你懂。

你们就这样交换着彼此的故事。像是两个在黑暗中摸到对方的人，你不知道她是谁，她也不知道你是谁，但你们在这个凌晨的便利店门口，把各自最柔软的部分展示给了对方。

不是因为信任。是因为不需要信任。

陌生人之间的坦诚，不需要信任作为前提。只需要时机，以及一个足够安静的夜晚。

## 六、天亮了

你们不知道聊了多久。

当你再次抬头看天的时候，东方已经泛起了鱼肚白。那条街尽头的高楼背后，天空从深蓝变成了浅蓝，再变成淡淡的橙色，像是有人在灰色的画布上慢慢兑了颜料。

"天亮了。"她说。

你看了看手机，五点四十一分。你们在便利店门口坐了将近四个小时。四个小时里，你们吃完了泡面和关东煮，喝完了三罐啤酒和一瓶牛奶，说完了两个关于失恋的故事，交换了两个彼此不会记得名字的人生。

她的眼睛还是红的，但不再是那种刚哭过的红了。更像是熬了一夜之后的充血，带着一种疲惫的坦然。你的眼睛大概也是一样的。

一辆洒水车从街上缓缓开过去，放着那首熟悉的《兰花草》。清晨的街道开始有了人——环卫工人在扫地，早起的老人在遛弯，一只橘猫从你们面前的垃圾桶旁边溜过去，头也不回。

她站起来，拍了拍裤子上的灰。你也站起来，腿麻了，踉跄了一下。

她笑了。这一次是真笑，不是刚才那种牵动嘴角的假笑。笑声不大，但在清晨的空气里传得很远。像一颗小石子扔进平静的水面。

"你笑什么？"

"笑你腿麻了还假装没事。"

你也笑了。这是你三天来第一次笑。不是因为好笑，而是因为——在经历了这样一个夜晚之后，你发现自己居然还有笑的能力。

她把空啤酒罐和关东煮纸碗丢进垃圾桶，你也把手里的泡面盒和牛奶瓶扔了进去。你们在垃圾桶旁边站了一会儿，面对面，像是在做一个无声的告别。

"谢谢你。"她突然说。

"谢什么？"

"谢谢你陪我坐了一夜。"她的声音不再沙哑了，清晨的空气像水一样清洗了她的嗓子。"我一个人坐在台阶上吃关东煮的话，大概会哭出来的。因为你在，所以我没哭。"

你张了张嘴，想说点什么煽情的话，但最后只是说了一句：

"我才该谢你。"

你确实该谢她。在遇到她之前，你觉得自己是世界上最倒霉的人，全世界都抛弃了你，你的人生已经完了。但坐在台阶上跟她聊了四个小时之后，你发现——原来碎掉的人不止你一个。原来这个城市的凌晨两点，有人在便利店门口吃关东煮，有人在路灯下拖着脚步走，有人在出租屋里对着天花板发呆。

大家都碎着，也都在想办法把自己粘回去。

她把帽子重新拉起来，遮住了大半张脸。你看到她卫衣的袖口有一个小洞，不知道什么时候磨破的。

"那我走了。"她说。

"嗯。"

她转身走了两步，又停下来，回过头。

"我忘了问你，你叫什么？"

你想了想。该不该告诉她？你不知道。也许不告诉更好，让这个夜晚永远停留在"一个陌生女孩"的阶段。但最后你还是说了你的名字。

"我叫——"

算了，这不重要。重要的是她笑了一下，然后也说了自己的名字。一个很好听的名字，但你后来怎么也想不起来了。不是因为你不在意，而是因为那个清晨的光线太亮了，她站在逆光里，整个人像一团模糊的白色光晕，名字从她嘴里说出来，被风吹散了，你只听到了一个音节的尾韵，像是远处传来的风铃声。

她挥了挥手，然后转身走进了清晨的阳光里。灰色的卫衣在光线中变成了浅灰色，然后越来越小、越来越远，最后消失在街角。

你站在便利店门口，看着她消失的方向，站了很久。

## 七、再也没有见到

你第二天又去了那家便利店。

还是凌晨两点，还是那盏冷白色的日光灯，还是那个打瞌睡的店员。你推门进去，欢迎光临的电子音响了一下。你四下看了看——货架上整整齐齐摆着泡面和啤酒，冷柜里关东煮冒着热气，收银台旁边的牛奶在冰柜里排成一排。

但没有她。

你在店里转了一圈，在冷柜前站了一会儿，又走到啤酒货架旁边看了看。没有灰色卫衣，没有大眼睛和红鼻尖，没有那双发抖的手。便利店里只有你一个客人。

你买了一包老坛酸菜味的泡面——你没买红烧牛肉的，你不知道为什么。你还买了一瓶牛奶，全脂的，玻璃瓶装的那种。你接了热水，坐在门口的台阶上，就着清晨的凉风吃完了泡面，喝完了牛奶。

没有人和你说话。没有人把啤酒推到你面前。没有人在旁边吃关东煮被烫到然后轻轻嘶一声。

你觉得台阶比昨晚更凉了。不是温度变了，是你变了。

第三天你又去了。还是没有她。第四天，第五天，第六天。你每天凌晨都去那家便利店，有时候买泡面，有时候买牛奶，有时候什么都不买就坐在台阶上发呆。店员已经认识你了，每次看到你进来会多看你一眼，那种"你怎么又来了"的眼神。

你不知道自己在等什么。也许是在等她。也许不是。也许你只是想回到那个凌晨两点的便利店门口，回到那个跟一个陌生人交换故事的夜晚。那晚之后，你发现你的失眠好了一些。不是因为想开了，而是因为你终于把那些堵在心里的东西说出来了——虽然是说给一个陌生人听的，但说出来就是说出来，不管对面坐着的是谁，话一旦离开嘴巴，就不再只是你一个人的事了。

你后来再也没有见到她。

你去了很多次，在不同的时间——凌晨一点、凌晨两点、凌晨三点。你甚至在傍晚和中午也去过几次，明知道她只会在凌晨出现，但你还是去了。每次推门进去的时候，欢迎光临的电子音响起，你都会下意识地往冷柜的方向看一眼。

空无一人。

