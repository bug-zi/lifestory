"回来了？"ta回头看了你一眼，"吃了没？"

"还没。"你换了拖鞋走进厨房，探头看了一眼锅里，"做的什么？"

"西红柿鸡蛋面，多煮了一点。"ta用筷子搅了搅锅里的面条，"你也吃一点吧，反正也做多了。"

你想说不用了，但肚子很不争气地叫了一声。

ta笑出了声。"坐下吧，马上好。"

你坐在餐桌前，看着ta端了两个碗出来——一碗面，上面卧着一个煎得金黄的荷包蛋，西红柿切成了小块，汤汁红亮亮的，撒了几粒葱花。

"你做的？"你夹了一口面条。

"嗯。一个人住习惯了，总得会做几样。"

面条很筋道，汤底酸酸甜甜的，煎蛋的边缘焦脆，咬开之后蛋黄还是溏心的。你吃得很慢，一根一根地挑，好像吃得慢一点，这碗面就不会见底。

"好吃吗？"ta坐在对面，捧着自己的那碗，下巴搁在碗沿上看你。

"嗯，挺好的。"你低下头继续吃。

那天晚上你洗碗的时候想，冰箱公约里没有说可以帮对方做饭这一条。你也没有说谢谢说得很郑重，因为怕太郑重了，就像是在确认什么你们都不该确认的东西。

