也许。

你的手机亮了一下。你拿起来看，是那个微信群里的消息——有人在群里发了一张上次同学会的合影。你放大了看，找到了你自己，又找到了ta。你们站在人群的两端，中间隔着十几个笑脸盈盈的同学。

