是班长老周发的。他用一种故作轻松但掩不住兴奋的语气写道："各位同学，转眼间咱们毕业都十五年了！我跟几个同学商量了一下，打算搞一次同学聚会，时间定在下个月第一个周六，地点在老城区那家新开的'归来'餐厅。能来的接龙报名啊！"

你盯着这条消息看了很久。

十五年了。这个数字在你脑子里转了好几圈，你试图把它和一个具体的时间线对应起来，却发现记忆像是被人打碎的拼图，碎片散落得到处都是。你记得高考结束那天下午的蝉鸣，记得教室后面黑板上值日生还没来得及擦掉的板书，记得走廊里永远弥漫着粉笔灰和洗衣液混合的味道。但你记不清这十五年是怎么过去的，就好像有人在你的人生里按下了快进键，等回过神来，你已经是一个三十三岁的大人了。

群里越来越热闹。接龙名单不断变长，名字一个接一个冒出来，有些你能对上号，有些完全陌生。你的手指悬在屏幕上方，犹豫着要不要打上自己的名字。

你犹豫的原因很简单——你不知道那个人会不会来。

你想了想，还是把手机扣在了枕头旁边。天花板上有一小片水渍，形状像一朵云，你盯着它发呆，思绪不知道飘到了哪里去。窗外的阳光慢慢移动，从地板爬上了墙壁，你始终没有动。

直到手机又震了一下。

你拿起来看，是群里的好友张雪儿私聊你："你是不是在纠结去不去？"

你回了一个省略号。

张雪儿秒回："我知道你在想谁。"

你没有回复。你把手机放到一边，闭上眼睛。窗帘被风轻轻吹动，发出窸窸窣窣的声响，像是有人在耳边细语。你突然想起了一首歌的旋律，是高中时广播站经常放的那首，歌名你已经忘了，但那个旋律还在，像是刻在了骨头里。

下午三点，你又打开了微信群。接龙已经有二十多个人了，你从上往下看了一遍——没有那个名字。你松了口气，又莫名觉得失落。

你盯着屏幕看了三分钟，然后在接龙的最末尾，打上了自己的名字。

放下手机的时候，你的心跳得有点快。你对自己说，这不过是去见见老同学而已，没什么大不了的。可你知道这不是真话。

窗外的阳光已经移到了另一面墙上。你躺在床上，看着天花板上那朵云形的水渍，忽然觉得它像一张脸。你笑了笑，翻了个身，告诉自己别胡思乱想了。

但你整晚都在想。

## 第二章 准备

同学聚会是下个月第一个周六，但你从那天开始就忍不住地准备起来。

倒不是准备什么惊天动地的东西——你只是开始翻箱倒柜地找一样东西。你记得它应该还在，在某个角落里，在某个被你刻意遗忘但又始终舍不得丢掉的角落里。

第一天你没找到。第二天也没找到。第三天你把书房的柜子翻了个底朝天，在一堆旧杂志和过期的 warranty 卡片底下，发现了一个锈迹斑斑的铁皮饼干盒。

你坐在地板上，打开盒子，一股陈年的纸张气息扑面而来。

盒子里装着你的高中遗物。一张皱巴巴的校报，上面有你写的一篇作文被当作范文刊登了。一个塑料胸牌，上面印着"高二三班 27号"。一张食堂饭卡，余额显示还有三块五毛钱。还有几张大头贴，几个同学挤在小小的镜头前做着夸张的表情。

你在最底下找到了那张毕业照。

照片很大，长条形的，背景是学校操场边那排法国梧桐。所有人都穿着白色短袖校服，站成四排，笑得像是世界上没有什么值得发愁的事情。你看着那些面孔，有些已经模糊了，像是隔着一层毛玻璃。但你的目光很快就找到了你想找的那个人。

ta在第二排，从左边数第七个。穿着和别人一样的校服，头发比大多数人长一点，额前有一缕碎发被风吹起来。ta没有看镜头，而是在看旁边的什么人——你仔细看了看，ta看的那个人，刚好是你自己。

你盯着照片上自己的脸。那时候的你瘦瘦的，皮肤晒得有点黑，笑得有些拘谨，像是不知道该怎么在镜头前自然地待着。而ta看着你，嘴角带着一丝若有若无的笑意，那种笑你太熟悉了，因为那是ta看你的专属表情。

你把照片放在膝盖上平展开来，用手指轻轻碰了碰ta的脸。照片上的像素点在你的指纹下变得模糊，你赶紧缩回了手，怕把它弄坏。

铁皮盒子里还有别的东西。一叠折叠得整整齐齐的纸条，纸张已经泛黄，上面是ta的字迹——圆润但有力，偶尔带着一点潦草，像是写的时候太着急了。你没有打开那些纸条，你还没准备好。你只是把它们捧在手心里，感受着那些薄如蝉翼的纸张传递过来的微弱的温度——当然那不是真的温度，是你自己手心的热量，但你愿意假装那是来自十五年前的余温。

你又翻出了几样东西。一个涂改带，外壳上贴着一张小小的便利贴，上面写着"用完记得还我"，旁边画了一个歪歪扭扭的笑脸。一块橡皮，被切成两半，你一半ta一半——这是你们之间的老规矩，什么东西都可以分。还有一支笔帽被咬得坑坑洼洼的中性笔，你记得那是ta的笔，不知道什么时候混进了你的笔袋里，后来就一直没还回去。

你把这些东西一件件摆在地上，像是摆一个小小的展览。你的猫走过来，好奇地嗅了嗅那块橡皮，你赶紧把它拿开了。

你坐在地板上，被这些旧物包围着，忽然觉得时间是一件很奇怪的事情。十五年前的东西，现在看起来又近又远，像是隔着一池水看湖底的石头——看得清清楚楚，却怎么也捞不起来。

你把东西都放回了铁皮盒子里，但毕业照你拿了出来，压在了书桌的玻璃台板下面。你想了想，又把那张照片翻拍了存进手机里。

接下来的日子，你开始不自觉地注意起自己的外表来。你换了个发型，买了件新衬衫，还在抽屉深处翻出了那瓶一直嫌麻烦没用的牙贴。你告诉自己这和同学聚会没有关系，你只是刚好想换换形象。但你心里清楚得很。

你在镜子前站了很久，端详着自己的脸。三十三岁的你比十八岁的你多了些棱角，少了些青涩。眼角有了细纹，法令纹也隐约可见。你不知道ta看到你会不会觉得你变了太多。

你忽然有些羡慕那张毕业照里的自己。那时候多简单啊，什么都不用想，只要每天能坐在ta旁边就够了。

聚会前一周，你失眠了。你躺在床上想了一夜，想自己见到ta应该说些什么。说"好久不见"？太正式了。说"你还是老样子"？万一ta变了很多呢。说"这些年你过得好吗"？又显得太刻意。你翻来覆去地想了无数种开场白，每一种都觉得不够好。

最后你决定，到时候再说吧。就像高中时一样，走一步看一步。

## 第三章 高中回忆

你第一次见到ta是在高二的开学典礼上。

那天九月的太阳还很毒，全校学生站在操场上听校长讲话，你热得快要中暑了，正偷偷用校服袖子擦汗。就在那个时候，你听到旁边有人小声说了一句："要是能发明一种随身空调就好了。"

你扭头看过去，看到了一张新面孔。ta的校服比别人穿得整齐，领口扣得一丝不苟，但刘海已经被汗水打湿了，贴在额头上。ta侧过头看着你，眼睛里带着一点不好意思的笑意，像是觉得自己刚才的话被听到了有点丢人。

你也笑了，说："我觉得发明冰镇校服比较靠谱。"

ta愣了一下，然后笑出了声。就这样，你们在学校操场上，在九月的阳光和蝉鸣里，因为一句关于空调的笑话，认识了彼此。

后来分座位，你们被排成了同桌。你到现在都觉得那是一个奇迹——全班五十多个人，偏偏是你和ta被分到了同一张课桌。你后来问过ta，ta说当时ta也在心里偷偷高兴了一下，但面上装得很淡定。

你们同桌的日子，是你记忆里最明亮的时光。

那时候的课桌是两个人合用的长桌，中间有一条浅浅的刻痕，像一条不可逾越的边界线。但你们从来不管那条线，课本和文具随意地混在一起，到最后你也分不清哪块橡皮是谁的，哪支笔又是谁的。

ta有一个习惯，上课的时候喜欢在课本边缘画画。小小的火柴人，做着各种各样的事情——打篮球、弹吉他、放风筝。有一次你偷偷翻ta的课本，发现最近几页的火柴人变成了两个人，手牵着手。你的脸一下子红到了耳根，假装什么都没看到，把书放回原处。那天下午ta一直偷偷看你，你一直假装在认真听课，两个人的耳朵都红得发烫。

你们之间有一种默契，不需要太多言语。上课的时候，老师讲到什么好笑的地方，你们不需要对视就知道对方在想什么，嘴角同时翘起来。考试的时候，如果有一道题特别难，你会在草稿纸上画一个哭脸，推到桌子中间，ta会画一个笑脸推回来，旁边写着"加油"。你们从来没有作弊过，但你们之间的这种小交流，比作弊更让彼此安心。

传纸条是你们的日常。你们的纸条内容五花八门——讨论食堂今天的菜好不好吃，猜测班主任今天心情怎么样，吐槽数学老师的口音，分享昨晚看的电视剧。但偶尔，纸条上也会出现一些让你心跳加速的内容。

有一次，ta传了一张纸条给你，上面只有一句话："你有没有觉得，今天的风特别舒服？"

你回："还好吧，就是普通的风。"

ta又传回来："可是我觉得今天的风比平时暖一点。"

你拿着那张纸条，看了很久很久。你不知道该怎么回，最后画了一个小小的太阳，推了过去。ta看到之后笑了，笑得眼睛弯成了月牙。后来你才知道，那天的气温其实比平时低了两度。

值日是你们最盼望的事情。轮到你们一起值日的那天，你们总是故意做得很慢。扫地、擦黑板、摆桌椅，每一道工序都被你们无限拉长。你们喜欢在空荡荡的教室里待着，没有其他人的目光，只有夕阳从窗户照进来，把整个教室染成橘红色。

有一次值日的时候，ta站在窗台上擦玻璃，你在下面扶着。ta突然低头看着你，逆光中ta的头发被染成了金色，脸上带着一种你说不清的表情。你仰头看着ta，忽然觉得整个世界都安静了下来，只剩下风从窗户灌进来的声音和你自己咚咚的心跳。

"你干嘛这样看着我？"你问。

ta愣了一下，然后别过头去，继续擦玻璃。"没有啊，我在看外面。"ta说。但你看到ta的耳尖红了。

你们之间最接近表白的一次，是在高二的最后一天。那天放学后，教室里只剩下你们两个。你在收拾书包，ta站在门口等你。你抬起头的时候，发现ta正在看你，那种眼神你从来没有在别人脸上见过——温柔的、专注的、带着一点小心翼翼的。

"暑假快乐。"ta说。

"暑假快乐。"你说。

你们就那样站了几秒钟，空气里有什么东西在悄悄膨胀。然后有人从走廊经过，发出一声口哨，你们像是被电击了一样，同时移开了目光。

后来你无数次想，如果那天你勇敢一点，走上前去，会怎么样？如果你伸出手握住ta的手，或者如果你说了一句不一样的话——不是"暑假快乐"，而是"我喜欢你"——你们的故事会不会完全不同？

但你没有。你们谁都没有。你们像两颗靠得很近的星星，彼此的引力让你们越靠越近，但始终没有真正相撞。

高三的时候你们不再是同桌了。班主任重新排了座位，你被调到了教室的另一边。你们之间的距离变成了三排课桌和一条过道。那条过道看起来很短，走过去只需要几秒钟，但你再也没有走过去过。不是不想，而是不知道该以什么理由走过去。你们之间那些纸条、那些默契、那些心照不宣的温柔，忽然失去了载体的依托，像是被风吹散的蒲公英，散落在空气里，再也收不回来了。

高考结束那天，你在校门口见到了ta。ta正在和别的同学合影，笑容灿烂。你想走过去说点什么，哪怕只是说一句"考得怎么样"。但人群推着你往前走，你在茫茫人海中看了ta最后一眼，然后转身走进了属于你自己的夏天。

那之后的十五年，你们没有任何联系。没有电话，没有短信，没有微信。ta像是彻底从你的世界里消失了，只在某些深夜，在某些特定的场景里——一阵带着花香的晚风、一首老歌的前奏、街角两个并肩走的年轻人——突然出现在你的脑海里，让你措手不及。

你以为自己已经放下了。直到看到那个微信群里的接龙消息，你才知道，你从来没有真正放下过。

## 第四章 同学会现场

聚会那天，你提前了四十分钟就出门了。

你换了三套衣服，最后还是穿了那件白色衬衫。你看着镜子里的自己，深呼吸了好几次，告诉自己这只是一顿普通的饭局，不需要紧张。但你的手心出了汗，你在裤子上擦了好几次。

"归来"餐厅在老城区的一条巷子里，你按照导航走了十分钟，穿过了几条熟悉又陌生的街道。有些店还在，有些店已经换了招牌。你路过学校附近那家文具店，发现它变成了一家奶茶店。门口坐着一群穿校服的高中生，他们笑着闹着，和十五年前的你们一模一样。

你在餐厅门口站了两分钟，透过玻璃门可以看到里面已经坐了不少人。灯光是暖黄色的，映着一张张已经不再年轻的面孔。你听到里面传来此起彼伏的笑声和招呼声，热闹得像过年。

你推开门走了进去。

一瞬间，有十几双眼睛看向你。有人喊出了你的名字，声音里带着惊喜。你笑着点头，一个一个认过去——这是老周，胖了一圈但笑起来还是那个样子；这是张雪儿，剪了短发差点没认出来；这是李磊，长高了好多，站起来跟你握手的时候你才发现他比你高了一个头。

你在人群中寒暄着，嘴上说着"好久不见"、"你一点都没变"之类的客套话，但你的眼睛一直在寻找。你的目光在餐厅里扫了一圈，扫过吧台，扫过角落的那张桌子，扫过窗边的位置——

然后你看到了ta。

ta坐在靠窗的位置，手里端着一杯水，正在听旁边的同学说话。ta侧着脸，你只能看到ta的侧脸。但就是这一个侧脸，让你的脚步停了下来。

ta变了。ta的脸上多了一些成熟的棱角，下巴的线条比以前更分明，额头上有了细细的纹路。ta的穿着很普通，深蓝色的外套里面是一件灰色的针织衫，和高中时候的校服一样干净整洁。ta比以前瘦了一点，坐姿还是老样子——微微侧着身，一只手搭在桌沿上，手指轻轻敲着节奏。

但ta也没变。ta的眼睛还是那样的，看你的时候带着一种温暖的光。ta笑起来的弧度还是那样的，嘴角先弯起来，然后眼睛才跟着弯。ta转头的时候，额前的碎发还是会轻轻晃动。

ta发现了你在看ta。你们的目光在半空中相遇，像两颗流星突然撞在了一起。ta的眼睛里闪过一丝你读不懂的东西——惊讶、紧张，还是别的什么——然后ta朝你笑了。

那个笑容让你的心脏猛地跳了一下。那个笑容和十五年前一模一样，温暖、明亮，像是冬天的第一缕阳光照进了你心底最深的角落。

你走过去，ta站起来。你们面对面站着，距离不到一米。十五年的时光在这一刻像是一堵透明的墙，你们看得见彼此，却隔着整整一个青春。

"好久不见。"ta说。声音比记忆里低沉了一点，但语调还是那样的，尾音微微上扬，像是在确认你的名字。

"好久不见。"你说。你的声音听起来比你自己预期的要平静，但你知道自己的手在微微发抖。

ta看了你几秒，然后说："你一点都没变。"

你知道这是假话。你比以前胖了一点，额头上有抬头纹了，发际线也比高中时候高了一点点。但你还是说："你也是。"

这句话有一半是真心的。因为ta的笑确实没有变。那个笑让你一瞬间回到了十七岁的教室，回到了那张两人合用的课桌前，回到了传纸条的那些午后。

有人过来拍你的肩膀，把你拉进了别的对话圈。你被裹挟着在餐厅里走了一圈，和这个握手，和那个碰杯，回答了无数遍"你现在在哪工作"和"结婚了没有"的问题。但你的注意力始终有一半留在ta身上。你余光里看到ta也在做同样的事情，在人群里应酬着，偶尔朝你的方向看一眼。

你们隔着整个餐厅，隔着满桌的酒菜和此起彼伏的笑声，隔着十五年的岁月，偷偷地看着彼此。

就像高三那年，你们隔着三排课桌和一条过道，做着同样的事情。

## 第五章 交谈

是ta先走过来的。

你正站在自助餐台前假装挑菜，其实已经往盘子里夹了三次同样的东西了。ta端着一个杯子走到你旁边，也假装在看菜品。

"这个糖醋排骨不错。"ta说。

你差点笑出来。你还记得高中食堂的糖醋排骨是ta最喜欢的菜，每次有这道菜ta都会跑得特别快，抢在别人前面打上满满一勺。

"你还是这么喜欢吃糖醋排骨啊。"你说。

ta看了你一眼，眼睛亮了一下。"你还记得？"

"当然记得。"你说。你想说"我记得所有关于你的事情"，但这句话太重了，你咽了回去。

你们端着盘子找了个角落的桌子坐下来。那个位置很安静，离主桌有一段距离，音乐声和说笑声传到这里已经变成了模糊的背景音。灯光在这里暗了一些，像是在为你们创造一个私密的空间。

一开始你们聊的都是安全的话题。工作、住处、通勤时间、最近看的电影。ta在一个设计公司上班，做平面设计，偶尔加班到很晚。你说了你的工作，ta认真地听着，时不时点点头。

但渐渐地，话题开始往回走了。

"你还记得我们班主任吗？"ta突然问。

"怎么不记得，"你笑了，"每次上课前都要讲十分钟的人生道理。"

"对对对，"ta也笑了，"而且每次讲的都是那几句话——'你们是我带过最差的一届'、'你们看看隔壁班'……"

"然后我们就偷偷在桌子底下传纸条吐槽他。"

ta的笑容顿了一下。"你还记得那些纸条？"

"记得啊。"你说，"你还老在纸条上画火柴人。"

ta的表情变了。那种变化很细微，如果你没有花那么多年时间研究ta脸上的每一种表情，你一定不会注意到。ta的眼睛里有一层水雾飘过来，又很快散去了。

"我以为你不会记得那些小事。"ta轻声说。

你心里涌上一种说不出的酸涩。你想说，那些怎么会是小事？那些纸条、那些火柴人、那些只有你们两个人才懂的笑话——那些是你整个高中时代最重要的事情。那些是你在这十五年里的深夜，翻来覆去回忆的东西。那些是你以为早就放下、却始终放不下的证据。

但你只是说："我当然记得。"

你们沉默了一会儿。不是尴尬的沉默，是那种两个人都知道对方在想什么、不需要说话的沉默。就像高中时上课传完纸条之后的那几秒钟，你们各自低头假装看书，但其实都在偷偷笑着。

ta先打破了沉默。

"你还记得那次一起值日吗？我站在窗台上擦玻璃那次。"

你的心跳漏了一拍。"记得。"

"那天我在看你。"ta说，声音很轻，像是在说一个秘密。"不是在看外面。"

你的手指不自觉地握紧了杯子。你张了张嘴，想说什么，但喉咙像是被什么东西堵住了。你等了十五年想听到的这句话，现在终于听到了，你却不知道该怎么回应。

"我也是。"你终于说出口。"我一直在看你。从高二第一天开始。"

ta低头笑了。那个笑容带着一点释然，又带着一点遗憾，像是两个人终于把一本翻了十五年的书读到了最后一页。

"我那时候写了好多纸条想给你，"ta说，"但都没有送出去。"

"什么样的纸条？"你问。

ta摇了摇头。"下次再说吧。"

你们又聊了很久。聊到那个总在课间偷吃零食的英语课代表，聊到体育课跑八百米时全班哀嚎的场景，聊到高三那年冬天教室里的暖气片烫得能煎鸡蛋。每一个话题都像是一把钥匙，打开一扇你以为已经锁死的门，里面涌出来的全是你以为已经忘记的细节。

你发现ta记得的比你想象的要多得多。ta记得你高中时最喜欢的那支笔是蓝色的。ta记得你每次考试前都会紧张地抖腿。ta记得你数学不好的时候总是皱着眉头咬笔帽。ta甚至记得你高三生日那天，在课桌抽屉里发现了一块巧克力——那块巧克力是ta放的，但你直到今天才知道。

"那块巧克力是你放的？"你惊讶地问。

ta点点头，脸上带着一种不好意思的表情。"我怕直接给你你会不好意思收。"

你看着ta，忽然觉得鼻子有点酸。那块巧克力的味道你早就忘了，但那种在课桌抽屉里发现惊喜的感觉你一直记得。原来那不是偶然，原来那是ta鼓了很久的勇气才做的事。

你忽然意识到，你们之间的故事，可能比你以为的要深得多。

## 第六章 散场

同学会到了尾声的时候，已经快十一点了。

餐厅里的灯光调暗了一些，人群也渐渐散了。有人喝多了趴在桌上，有人在门口依依不舍地拥抱告别。空气里弥漫着一种微妙的情绪——大家都在试图延长这个夜晚，好像只要今晚不过去，那些关于青春的记忆就不会褪色。

你和ta一起走了出来。

秋天的夜风很凉，吹得你打了个寒颤。ta注意到了，问你要不要把外套给你。你摇了摇头，说不冷。其实你只是不想让ta把外套脱了——你怕你会忍不住去闻ta外套上的味道，那就太丢人了。

你们并肩走在老城区的街道上。路灯把你们的影子拉得很长，在地上重叠在一起，像是两个拥抱的人。你们走得很慢，谁也没有说话，因为谁都知道这段路走完意味着什么。

ta先开口了。

"这些年你过得好吗？"

这个问题你想过无数次该怎么回答。你想过说"挺好的，事业有成，生活稳定"——虽然这只有一半是真的。你想过说"不太好，经常失眠，总是在深夜想起一些事情"——但这又太诚实了。你想过说"还行吧，凑合过着"——但这听起来太敷衍了。

最后你说："挺好的。"

两个字，轻飘飘的，像是秋天的最后一片落叶。

ta看了你一眼，好像想说什么，但没有说。你们又走了一段路，路过一家还亮着灯的便利店，门口的冰柜发出嗡嗡的声响，像是这座城市还没睡去的最后一个心跳。

"你呢？"你问。"这些年过得好吗？"

ta沉默了几秒，然后也说了同样的话："挺好的。"

你笑了。ta也笑了。你们都知道对方说的不完全是真话，但你们都选择了不追问。因为有些事情，不是一句"不太好"就能说清楚的。十五年的光阴里藏着太多故事，太多次辗转难眠，太多个看着手机通讯录发呆的深夜，太多句打好了又删掉的微信消息。这些东西，不是在一条秋天的街道上就能说得完的。

你们走到了一个路口，前面就是停车场。ta的车停在东边，你的车在西边。你们在路口停下了脚步，面对面站着。

路灯下ta的脸有一半在光里，一半在影里。你想把这一刻拍下来，但你没有掏出手机。有些画面，只能用眼睛去记住。

"谢谢你今天来。"ta说。

"你也是。"你说。

你们又沉默了几秒。夜风吹过来，带着远处某个地方飘来的桂花香。你想起高二那年的秋天，学校里的桂花也开了，满校园都是那种甜得发腻的香味。那天ta在纸条上写："桂花好香。"你回："是啊。"ta又写："我想把这个味道记住。"你回："用得着记吗？明年还会开的。"

可是后来你才知道，有些东西不是每年都会有的。

"那我走了。"ta说。

"嗯。"

ta转身走了几步，又停了下来。你看着ta的背影，心跳忽然变得很响。

ta回过头，看着你。

"下次再聚的时候，别等十五年了好不好？"

你愣了一下，然后点了点头。"好。"

ta笑了。那个笑容在路灯下看起来温暖极了，像是冬天里的第一杯热可可。然后ta转身走了，这次没有再回头。

你站在路口，看着ta的背影越来越小，最后消失在停车场的灯光里。你听到远处传来引擎发动的声音，然后是一束车灯从停车场出口拐出来，顺着马路向远处驶去。

你站在原地，看着那两盏红色的尾灯越来越小，最后变成了夜色里的两个小点，然后彻底消失了。

秋风又吹过来了，你裹紧了衣服。你没有马上走向自己的车，而是在路边的台阶上坐了下来。头顶的夜空没有星星，只有一层灰蒙蒙的光，那是城市的灯火映在云层上的反光。

你坐了很久。久到便利店的服务员出来看了你两次，以为你是醉汉。久到你裤子上沾了台阶上的灰尘，膝盖有点发麻。

你想起了ta问你的那个问题——"这些年过得好吗？"

你想，其实答案应该是"不太好也不太坏"。这十五年你经历了毕业、工作、恋爱、分手、跳槽、搬家。你的人生像是一列按部就班行驶的火车，该停的站都停了，该经过的风景都经过了。但总有那么一些时刻——在深夜关掉手机之后，在清晨闹钟响起之前，在某个毫无征兆的瞬间——你会想起ta。想起那张课桌、那些纸条、那个在窗台上擦玻璃的侧脸。

你以为那些记忆已经被时间稀释了，但今天晚上你才知道，它们只是沉到了水底。只要有哪怕一个微小的扰动——一个眼神、一句话、一阵带着桂花香的秋风——它们就会重新翻涌上来，搅得你心里天翻地覆。

你从台阶上站起来，拍了拍裤子上的灰，走向你的车。发动引擎的时候，你看了一眼副驾驶座上的铁皮饼干盒——你本来想今天把它带给ta，但最终没有勇气。

你把车开出停车场，汇入了空旷的夜路。车载电台里在放一首老歌，你听了几秒钟，忽然认出来了——是高中时广播站经常放的那首。

你把车停在路边，关掉引擎，在黑暗里把这首歌听完了。

## 第七章 后来

同学会之后的那一周，你的手机通讯录里多了一个新名字。

那天散场之前，你们加了微信。是张雪儿怂恿的，她把你们推到了一起，说"你们俩以前不是同桌吗，加个微信怎么了"。ta掏出手机，你也掏出手机，你们扫了彼此的二维码，然后那个熟悉的头像出现在了你的通讯录里。

ta的微信头像是一张风景照，远山和湖水，看不出是在哪里拍的。ta的朋友圈设置了三天可见，你点进去什么也看不到。你的朋友圈也是三天可见的，ta大概也什么都看不到。

你们在加完好友的那一刻互相发了一个表情包。ta发的是一个卡通人物在挥手的动图，你发了一只猫说"你好"。然后对话框就安静了下来。

一天过去了。两天过去了。一周过去了。

你们的聊天记录停在那两条消息上，像是一本只写了扉页就合上的书。你每天都会打开那个对话框，看着那两条消息，手指在键盘上悬停，输入了几个字又删掉，反反复复，最终什么也没有发出去。

