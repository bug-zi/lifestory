冰箱公约那张纸还在，但上面的字迹已经被蒸汽和油渍洇得模糊了。

你没有提议重新写一张。


## 第四章 深夜厨房

凌晨三点，你醒了。

不是被吵醒的，是那种毫无征兆的、突然睁开眼的清醒。窗外没有月光，城市的夜色像一块洗旧了的黑布，只有远处写字楼还亮着的几盏灯，像钉在布上的碎钻。

你在床上翻了两回，睡不着。索性起来倒了杯水。

厨房的灯亮着。

你走过去，看到林屿坐在餐桌前，面前摊着一本速写本，手里握着一支铅笔，正对着窗外发呆。ta穿了一件灰色的连帽卫衣，帽子扣在头上，整个人缩成一团，显得比平时小了很多。

"怎么了？"你把水杯放在桌上，在ta对面坐下来。

ta抬头看你，眼睛下面有淡淡的青色。"睡不着。"

"想什么呢？"

"没什么。"ta用橡皮擦了擦纸上的一根线条，"画不出来。"

你探头看了一眼速写本。纸上画了一扇窗户，窗户外面是一团模糊的暗影。线条很乱，擦了又画，画了又擦，纸张都起毛了。

"画什么？"

"画外面的夜色。"ta苦笑了一下，"但怎么都画不对。月光灰调不出来，总是太冷或者太暖。"

"你试过不画吗？就坐在窗边看一会儿。"

ta看了你一眼，好像在考虑这个建议。然后ta合上速写本，把铅笔夹在页间。

"你呢？怎么也醒了？"

"不知道。"你喝了一口水，"可能是因为太安静了。有时候太安静了反而睡不着。"

"嗯。"ta点点头，"我小时候也是这样。安静的时候脑子里会很吵。"

"脑子里在吵什么？"

ta沉默了一会儿，拿起桌上的水杯转了两圈。"乱七八糟的。以前的事，以后的事。比如……我是不是应该回老家，是不是不应该来这里，是不是做什么决定都是错的。"

你没有说话，只是安静地听着。厨房的灯光很柔和，照在ta低垂的睫毛上，投下一小片扇形的阴影。

"我以前觉得，一个人住挺好的。"ta继续说，声音很轻，像是怕吵醒这个沉睡的城市，"自由，没人管，想做什么做什么。但有时候夜里醒来，发现整间屋子只有自己呼吸的声音，会突然觉得……"

"觉得什么？"

"觉得好像自己不存在。"ta抬起头看你，眼眶有点泛红但没哭，"就是那种，如果明天我不见了，可能很久都不会有人发现的感觉。"

你心里某个地方被戳了一下，很轻，但很准确。

"会有人发现的。"你说。

"谁？"

"我啊。"你脱口而出。

说完你就后悔了，因为这话听起来太像什么电影台词了。你想解释一下，比如"我是说合租嘛，少一个人交房租我肯定能发现"，但你的嘴巴没有配合你的脑子。

林屿看着你，厨房里安静了很久。久到你以为ta要笑了，或者要调侃你一句"你可真会说话"之类的。

但ta没有。ta只是低下头，用手指摩挲着杯壁，轻声说了一句："谢谢你，陈词。"

"不客气。"你的声音比平时低了半个调。

