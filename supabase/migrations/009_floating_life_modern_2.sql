你想，也许有些故事注定是没有结局的。不是每个开始都需要一个结束，不是每次相遇都要有一个结果。你和ta的故事，也许最好的样子就是那个没有说出口的"我喜欢你"，那块偷偷放在课桌里的巧克力，那只在黑暗中触碰了两三秒的手。

