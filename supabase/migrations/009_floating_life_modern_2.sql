## 最终总结

这是一个关于"来不及"的故事。两个人在有限的空间里无限地靠近，却又在无限的犹豫中有限地错过。合租给了他们一个相遇的理由，却没有给他们一个表白的契机。冰箱可以分两层，但心只分了一个——等他们发现这件事的时候，其中一个已经搬走了。

故事里没有轰轰烈烈的告白，没有偶像剧式的追到机场，没有命运安排的重逢。有的只是一间两居室、一扇窗户、一幅没画完的画、一盒洗好的草莓，和两个把话藏在心底的人。

世界上最远的距离，不是天涯海角，而是你明明就站在ta面前，却说不出那句"我喜欢你"。


