$$# 深圳的雨季

## 第一章 初到深圳

你是八月底来的深圳。

从北站出来的时候，热浪像一面墙一样撞上来，你的眼镜瞬间起了一层雾。你摘下眼镜擦了擦，再看这座城市——到处都是楼，密密麻麻的楼，像是被谁随意插进地里的筷子。你拖着那个二十八寸的行李箱，箱子的轮子在车站广场的瓷砖地面上发出咔哒咔哒的声音，好像在替你数着什么。

你没有来接的人，也没有等你的灯。

你在手机上搜到了一个城中村的出租屋，月租一千二。中介带你穿过一条窄得只能并排走两个人的巷子，头顶是纵横交错的电线和晾晒的衣物，地上是永远干不了的水渍。中介是个比你还年轻的小伙子，穿着人字拖，走路飞快，你跟在后面闻到了各种味道——煮饭的油烟、下水道的潮湿、某种不知道是什么的甜腻香气。

"这间，五楼。"中介推开一扇掉了漆的铁门，"采光还行，就是夏天有点热。"

你走进去。所谓的"采光还行"，是窗户正对面三米外有另一栋楼，把所有阳光挡得严严实实。房间里只有一张床、一个衣柜、一张桌子，都是上一个租客留下来的，带着一种说不清的旧气。你把行李箱立在墙角，坐在床沿上发了十分钟的呆。

"隔壁那间也有人刚搬进来，"中介收了你的押金和第一个月租金，临走时指了指那堵薄薄的墙，"好像是做设计的，挺安静的。你放心，这里住的都是年轻人，没什么事。"

你没有在意。你只是觉得这面墙真薄，薄到你能听见隔壁有人在整理东西——塑料袋的窸窣声、椅子拖过地面的声音、还有偶尔传来的一声轻轻的叹息。

第一天晚上你睡不着。不是因为热——虽然空调确实不太制冷——而是因为陌生。窗外城中村的灯光混着远处高楼的霓虹，变成一种暧昧的橙色，映在天花板上。你听见隔壁在放音乐，声音很小，像是怕打扰到谁。你侧过身，耳朵贴着那面薄墙，听出来是一首老歌，《南方姑娘》。

你想着，隔壁这个人，大概也是和你一样，从某个北方的小城，一路坐了十几个小时的火车来到这里，手里攥着一个不太确定的未来。

你不知道的是，隔壁那个人此刻也醒着，也侧着身，也在听同一首歌。


## 第二章 雨季来临

深圳的雨来得毫无预兆。

你来的第二周，天就开始下雨了。不是那种北方短暂的阵雨，而是持续的、绵绵不绝的、好像永远也不会停的雨。气象台说这是龙舟水，每年都有，但你觉得今年的雨格外长，格外密，格外不讲道理。

你买了一把伞，第一天就被风吹断了伞骨。你又买了一把，这次是那种十块钱的透明伞，撑在城中村的巷子里，雨水顺着伞面流下来，打湿了你的裤脚。巷子太窄，伞撑不开，你只能侧着身子走，像一只在雨中赶路的猫。

每天早上七点，你出门的时候，隔壁的门也刚好打开。你第一次看清了隔壁的人——个子不算很高，穿着一件浅灰色的卫衣，头发湿漉漉的，大概是刚洗过没来得及吹干。对方看见你，愣了一下，然后笑了一下。

"你也是刚来深圳的？"声音比你想象的要温和。

你点了点头，不知道该说什么。你们就这样在门口站了几秒钟，雨声填满了所有的沉默。

"我叫林栩。"隔壁的人说。

你报了自己的名字。你们交换了名字，然后各自撑着伞，往相反的方向走了。你走到巷口的时候回头看了一眼，那个浅灰色的身影已经消失在雨幕里了。

那天晚上你加班到十一点，回到城中村的时候雨下得更大了。你没有带伞——早上那把十块钱的透明伞在地铁上被你遗忘了。你从地铁口跑到出租屋楼下，三百米的距离，你被浇得透湿。你在楼下屋檐下停下来，拧了拧衣服上的水，抬头看见五楼的窗户亮着暖黄色的灯。

你突然觉得那个窗口的灯光很好看。

你上楼的时候，在四楼的拐角遇到了林栩。对方手里拿着一把伞，好像正要下楼。

"你没带伞吧？"林栩看了你一眼，"我下午看见你出门的时候手上是空的。"

你愣住了。你没有想到有人会注意这种事。

"我……地铁上忘了。"

"没关系，我也经常忘。"林栩笑了一下，把伞递给你，"你先用我的，我明天不出门。"

你接过那把伞，伞柄上还带着一点体温。你想说谢谢，但喉咙好像被什么东西堵住了。

"谢谢你。"

"不客气。"林栩转身往回走，走了两步又回头，"对了，明天如果还下雨的话，可以一起走一段。反正我们到地铁站是同一个方向。"

你说好。

那天晚上你躺在床上，听着窗外不知疲倦的雨声，手里还握着那把伞。你想起林栩说的"一起走一段"，觉得这大概是深圳的雨季里，你听到的最温暖的一句话了。


## 第三章 深圳的速度

你很快发现，深圳是一座不允许你慢下来的城市。

你的公司在南山，每天早上七点出门，挤一号线再转十一号线，单程一个半小时。地铁里永远是人挤人，你被夹在各种人中间——背着双肩包的程序员、踩着高跟鞋的女孩、手里拿着煎饼果子的外卖骑手。大家都在看手机，没有人说话，车厢里安静得像一座移动的图书馆。

林栩在福田上班，做平面设计。你们的路线有一段重合——从城中村到地铁站那十五分钟的步行。于是你们开始每天早上一起走那段路。

刚开始只是沉默地并肩走着，雨声代替了对话。后来慢慢地，你们开始说一些零碎的话——"今天地铁好像人少了一点"、"不，和昨天一样多"、"你觉得那个新开的肠粉店好吃吗"、"还行，但没有我们老家的"。

"你老家是哪里的？"有一天你终于问了。

"湖南。"林栩说，"一个小地方，你可能没听过。"

"湖南哪里？"

"怀化。"

你点了点头。你确实没听过。

"你呢？"

"河南。更小的地方。"

你们都笑了。在这座两千多万人的城市里，你们各自从天南地北赶来，却住在了同一面墙的两侧。你觉得这件事有点像命运，但你不信命运，你只信巧合。

深圳的速度不只是地铁和加班，还有便利店。

你们总能在深夜的便利店遇到。你去买关东煮，林栩去买泡面。你在货架前选酸奶，林栩在隔壁的冰柜拿气泡水。一开始你们都觉得这只是巧合，后来发现不是——因为城中村方圆五百米内，只有这一家便利店，而且只有这一家是二十四小时营业的。

"又遇到了。"有一天凌晨一点，你在收银台前说。

"嗯。"林栩手里拿着一杯热可可，脸上的表情你看不太清楚，因为便利店的灯光太白太亮了，把所有人的影子都吞掉了。

"你今天加班到几点？"

"十一点半。然后去公园坐了一会儿。"

"公园？这么晚？"

"深圳的公园晚上很安静的。"林栩停顿了一下，"而且有灯。我不喜欢回到那个房间面对四面墙，至少公园有树。"

你忽然很想说"你可以来找我坐坐"，但你没有说出口。你觉得太快了，你们还不熟，而且你不知道林栩是不是那种喜欢独处的人。你只是默默点了点头，然后各自付了钱，各自走回那个城中村，各自上楼，各自关上那扇掉了漆的铁门。

但你那晚又听到了隔壁的音乐。不再是《南方姑娘》了，换成了另一首你叫不上名字的曲子，像是钢琴独奏，安安静静的，一直放到了凌晨三点才停下来。

你不知道林栩是不是也失眠了，但你确实一夜没睡好。


## 第四章 某个深夜

那是十一月的一个星期三。

你已经连续加了五天班，每天晚上十一点以后才回来。那天你特别累，因为项目赶进度，领导在群里发了一长串的需求变更，你盯着电脑屏幕改了一整天的方案，眼睛酸得快要流泪。

你回到出租屋，扔下包，连灯都没开就倒在了床上。你想哭，但没有眼泪。你拿出手机，看到妈妈发来的微信："在那边还好吗？天冷了记得加衣服。"你打了几个字——"挺好的，放心"——然后删掉了，重新打了一遍："嗯，知道了。"发出去之后你觉得这两个字太过敷衍，但又不知道该说什么。你确实不太好，但你不能说。

你正在发呆的时候，有人敲门了。

三下，很轻，像是怕打扰到你。

你以为是快递，拖着身体去开了门。

门外是林栩。

走廊的声控灯亮着昏黄的光，你看见林栩穿着一件格子衬衫，头发有点乱，手里端着一个不锈钢的锅——不是碗，是锅。

"你吃饭了吗？"林栩问。

你摇了摇头。你中午吃了一个面包，晚饭还没来得及吃。

"我做了太多。"林栩把锅往前递了递，"西红柿鸡蛋面，你要不要一起吃？"

你愣了好几秒。你看见锅上面还冒着热气，闻到了西红柿的味道，还有一种说不上来的、像是加了什么香料的味道。你突然觉得鼻子有点酸。

"好。"你说。

你让开身子，林栩走了进来。你的房间很小，除了床和桌子之外几乎没有落脚的地方，林栩把锅放在桌上，又从门外拿了两双筷子和两个碗。你看着这些动作，觉得有一种不太真实的温柔。

"你一个人住还用碗啊？"你忍不住问。

"总不能一直吃泡面吧。"林栩一边盛面一边说，"我来深圳之后学的第一个技能就是煮面。之前连水都不会烧。"

你们面对面坐着，你坐在床沿，林栩坐在那张旧椅子上。面很好吃，西红柿的酸甜、鸡蛋的嫩滑、面条的筋道，每一样都恰到好处。你吃得很慢，不想太快吃完。

"谢谢你。"你说，这次你很认真。

"谢什么，我一个人也吃不完。"

"不是谢这个。"你放下筷子，"是谢你敲门。"

林栩抬起头看了你一眼。走廊的灯灭了，房间里只有你手机屏幕的微光，你看不清林栩的表情，但你听见了一声很轻的笑。

"我今天听到你回来的时候叹了一口气，"林栩说，"很大的一声。大概你自己都没注意。"

你没有说话。你确实不记得自己叹气了。

"我知道在深圳很累，"林栩的声音很轻，像是怕惊扰到什么，"但有时候，有人跟你说一句'吃饭了吗'，好像就能好一点。"

你们把一整锅面都吃完了。林栩洗了碗——你的碗，那唯一的一个碗——然后站起来准备走。走到门口的时候，林栩回过头来。

"以后如果加班太晚，可以来敲我的门。"

"好。"

"我一般一点之前都还醒着。"

"好。"

门关上之后，你坐在桌前，看着那个空了的锅，还有洗干净倒扣在桌上的碗，你忽然觉得这个狭小的出租屋好像不那么冷了。你把椅子搬到窗边，看着外面城中村的夜景——近处的窗户里有各种灯光，有人在做饭，有人在看电视，有人在对着电脑加班。每一扇窗户后面都是一个和你一样的人，都在这座城市里用力地活着。

你又听到了隔壁传来的钢琴曲，但这次你没有觉得那是失眠的标志，你觉得那像是一种道晚安的方式。


## 第五章 雨停了

深圳的雨季终于结束了。

十二月的某一天早上，你醒来的时候发现阳光正穿过窗户照在你的脸上。你眯着眼睛看了一眼——对面的楼还是那么近，但今天它被阳光照得发亮，窗户里反射出一片金色。你看了看手机，天气显示"晴"，湿度百分之四十五。

你出门的时候没有带伞。

林栩也没带。你们在楼道里碰到了，都对着彼此空空的双手笑了一下。

"好像不用带伞了。"林栩说。

"嗯。"

你们往地铁站走。没有雨的日子，那段十五分钟的路突然变得短了很多。阳光很好，城中村的巷子在白天其实挺有生机的——有人在楼下卖早餐，蒸笼里冒着白烟；有人骑着电动车从你们身边经过，按了一声喇叭；还有一只橘猫蹲在墙头上，懒洋洋地看着你们。

"你有没有觉得，"你突然说，"不下雨之后，这段路好短。"

林栩没有马上回答。走了几步之后才说："不是路变短了，是不下雨之后走得快了。下雨的时候我们走得很慢，因为要注意脚下，要注意别踩到水坑，要撑伞。现在什么都不用注意了，反而走得快了。"

你觉得林栩说的好像不只是路。

雨停了之后，一切都变了。

你们不再一起走那段路了。不是因为不愿意，而是因为不下雨之后，每个人的步速都变快了。你七点十分出门，林栩七点十五才出来——错开了。有时候你出门的时候听到隔壁有动静，等了一会儿，但林栩没有出来，你就先走了。后来你就不等了。

你不知道的是，林栩有时候也在等你。林栩听到了你关门的声音，看了看时间，犹豫了三十秒，最终没有开门。

深圳的冬天不算冷，但你的心里不知道什么时候开始长了一层薄薄的霜。你不再每天去那家便利店了，因为公司楼下新开了一家，更近，更方便。你不再听到隔壁的钢琴曲了，不知道是林栩不再放了，还是你加班回来太晚，林栩已经睡了。

有一次你在楼道里遇到林栩，你笑着打了个招呼："最近忙吗？"

"还好。"林栩也笑了一下，"你呢？"

"也还好。"

然后就各自上楼了。你站在自己的房间里，听到隔壁关门的声音，心想：我们之间的距离，明明只有一面墙，为什么好像隔了一整个深圳？

你开始想起中介说过的话——"隔壁那间也有人刚搬进来。"那是八月底的事了。现在是十二月。四个月。四个月里你们从陌生人变成了会一起走路的邻居，从会一起走路的邻居变成了会一起吃面的朋友，然后从会一起吃面的朋友，变成了在楼道里点个头就各自关门的人。

你觉得这是深圳的规律——所有关系都在加速，从零到一百只需要几天，但从一百回到零也只需要几天。


## 第六章 搬走

过完年回来，你发现隔壁的门一直关着。

你以为林栩回老家还没回来。你等了三天、五天、一周。你开始觉得不对劲了。你敲了隔壁的门，没有人应。你问房东，房东说："搬走了啊，年前就退租了。"

"搬去哪里了？"

"不知道，说是要离开深圳了。"

你站在隔壁那扇紧闭的门前，愣了很久。你突然想起很多事——西红柿鸡蛋面的味道、透明伞上残留的体温、凌晨一点便利店的白色灯光、还有那首你始终没有问名字的钢琴曲。

你拿出手机，想给林栩发一条消息，然后你发现你们甚至没有加过微信。

你只有林栩的名字和隔壁的门牌号。

你想起很多个没有说出口的瞬间。你想说"你可以来找我坐坐"的那个便利店之夜。你想说"我等你一起走"的那些不下雨的早晨。你想说"那首钢琴曲叫什么名字"的那些听着隔壁音乐入眠的深夜。你想说"我好像有点喜欢你"的那个吃完面的夜晚。

但你什么都没有说。

一个都没有。

你后来想了很多关于林栩为什么离开的原因。也许是工作不顺心，也许是想家了，也许是在深圳待够了，也许是所有这些加在一起。但你最想知道的一个答案你永远也得不到了——林栩走的时候，有没有想过要和你说一声？

你回到自己的房间，坐在床沿上。房间和半年前一模一样——掉漆的铁门、发黄的墙壁、不制冷的空调、还有那面薄薄的墙。但隔壁安静了。再也没有塑料袋的窸窣声，再也没有椅子拖过地面的声音，再也没有轻轻的叹息，再也没有凌晨三点的钢琴曲。

那天晚上你去那家二十四小时便利店买了一杯关东煮和一瓶气泡水——这是你们各自常买的东西。你坐在便利店窗边的高脚凳上，吃着吃着就哭了。不是因为悲伤，而是因为你忽然意识到，你甚至不知道林栩喜欢吃什么口味的泡面、喜欢什么品牌的气泡水、喜欢哪个季节的深圳。你们住在同一面墙的两侧四个月，你连这些最基本的都不知道。

便利店的店员看了你一眼，没有说话。深圳的深夜，在便利店哭的人大概不止你一个。


## 第七章 后来

后来的事没什么好说的。

你还是每天早上七点出门，挤一号线再转十一号线。你还是每天加班到很晚，还是在公司楼下的便利店随便吃点东西。你还是住在那间城中村的出租屋里，隔壁搬来了新的人——一个做直播的女孩，每天晚上在房间里对着手机说话到很晚，声音透过那面薄墙传过来，嘈杂但热闹。

