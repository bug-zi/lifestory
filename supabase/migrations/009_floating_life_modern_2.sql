有些东西被删掉了，但有些东西删不掉。比如你读过的书、走过的路、爱过的人、受过的伤。这些东西不在手机里，不在聊天记录里，它们在你的身体里，在你的骨头缝里，在你的呼吸里。

你删掉了聊天记录，但你删不掉你自己。

这是你今晚学到的最重要的一件事。

窗外的天越来越亮了。鸟叫声越来越密了。你听到楼下有人在遛狗，狗链子在水泥地上发出细碎的金属声响。

新的一天开始了。

而你，终于可以放下了。


