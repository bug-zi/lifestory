电梯按钮面板上没有33楼。你按了32楼，又按了34楼，在这两个数字之间来来回回按了三遍。电梯门开了又关，关了又开。你觉得自己像个傻子。正要放弃的时候，你发现按钮面板的右下角有一条极细的缝隙，像是什么东西曾经贴在那里又被撕掉了。你用指甲抠了一下，一个小小的圆形按钮弹了出来，上面没有数字，只有一个篆体的"忘"字。

你按了下去。电梯没有任何反应，你甚至觉得这可能只是你的幻想。但几秒钟之后，电梯开始向上移动。数字跳过了33，直接显示34，然后停住了。门开了，你走出电梯，发现自己站在一条走廊里。走廊很长，灯光是那种很旧的暖黄色，墙壁上贴着暗纹壁纸，像是很多年前的装修风格。走廊尽头有一扇木门，门上挂着一块铜牌，铜牌上刻着"忘川"两个字，字体是行书，笔画像是水流的痕迹。

你站在门口，深吸一口气。你的心跳很快，手心全是汗。你抬手敲了门，门自己开了。

里面的装修出乎你的意料。你以为会是什么阴森的实验室或者神秘的暗室，但其实它看起来就像一间很普通的私人诊所。白色的墙壁，几盆绿植，一张原木色的前台桌子，墙上挂着一幅水墨画，画的是一条河流，河水从画面左侧流向右侧，消失在一片模糊的雾气里。

前台后面坐着一个人。你说是"人"，但其实你不完全确定。她看起来三十岁左右，穿着一件白色的衬衫，头发很黑很长，安静地垂在肩膀两侧。她的眼睛是深棕色的，像是两颗被河水冲刷了很久的鹅卵石，光滑、沉静、没有波澜。她看到你的时候微微笑了一下，那种笑不像是欢迎，也不像是客套，更像是一种确认——确认你是那种会被那条广告吸引来的人。

"第一次来？"她问。你点了点头。她从抽屉里拿出一张卡片递给你，卡片是深灰色的，上面印着几行字，字体很小，像是某种合同条款。

你低头看那些字。上面写着："忘川诊所服务协议。第一条：本诊所提供定向记忆清除服务，可将指定人物从您的记忆中永久移除。第二条：清除范围为与该人物相关的所有记忆片段，包括但不限于画面、声音、气味、触感及关联情感。第三条：本服务的代价是永久性的感受力下降百分之十二。第四条：百分之十二的感受力意味着您对快乐、悲伤、愤怒、恐惧、爱、恨等一切情感的感知能力将永久降低百分之十二，此变化不可逆。第五条：签署本协议即视为您已充分理解并自愿接受上述所有条款。"

你把卡片翻过来，背面是空白的，只有一个签名栏。

"百分之十二是什么概念？"你问。她从椅子上站起来，走到窗边，拉开了一半窗帘。窗外是城市的天际线，灰蒙蒙的天空，远处的楼群像一排排竖起来的多米诺骨牌。她指着窗外的天说："你看到那片灰色了吗？如果去掉百分之十二的蓝色，天空就是那个颜色。不仔细看看不出来少了什么，但你就是会觉得，天没有以前那么蓝了。"

你沉默了很久。她说："先去候诊室坐坐吧，不急。想清楚了再来签。"

她给你指了方向，候诊室在走廊的另一头。你走出前台的门，沿着走廊往前走，脚步声在空旷的走廊里回荡。你忽然觉得这里很安静，安静得像是在水下。你甚至能听到自己的心跳声，一下一下，沉闷而有力。你不知道前方等待你的是什么，但你还是走了过去。

🌙 候诊室的故事

候诊室比你想象的要大。大概有三十平米，放着四张单人沙发，一张长条茶几，茶几上摆着一壶茶和几个杯子。角落里有一盏落地灯，灯光是柔和的暖色，照在深色的木地板上，像是一层薄薄的蜂蜜。墙上挂着一面钟，但你注意到那面钟没有指针，只有空白的表盘。你不知道这是什么意思。

候诊室里已经坐了三个人。

最靠近门口的沙发上坐着一个年轻女孩。她大概二十五六岁，穿着一件米白色的针织开衫，头发扎成一个低马尾，双手捧着一杯茶，低着头，像是在看杯子里的茶叶，又像是什么都没在看。她的眼睛是红的，像是刚哭过，又像是很久没有睡觉。

你在她对面坐下来。她抬起头看了你一眼，又低下去。过了一会儿，她忽然开口说话了，声音很轻，像是在自言自语，又像是在对着空气坦白。

"我要忘掉我妈妈。"她说。你没有接话，但你的沉默本身就是一种允许。她继续说了下去。"我妈妈三年前走了，肺癌。她走的时候我才二十三岁，刚毕业，刚找到第一份工作。她这辈子最大的愿望就是看我结婚，我连男朋友都没来得及谈。她最后那段时间一直念叨，说没关系，说下辈子再见。可我不想要下辈子，我想要这辈子。"她的声音开始发抖，手指攥紧了杯子。

"她走了之后我一直在梦里见到她。每天晚上都梦到。有时候梦到她在厨房做饭，围裙上全是油渍，一边炒菜一边叫我去拿碗。有时候梦到她坐在阳台上晒太阳，手里拿着一把瓜子，一边嗑一边跟我爸聊天。有时候梦到她站在学校门口等我放学，穿着那件藏蓝色的棉袄，远远地冲我招手。每次醒来我都觉得她还在。每次清醒过来都是一次新的死亡。"她把杯子放在茶几上，用手背擦了一下眼睛。

"我不是不爱她。我就是太想她了。想到活不下去了。"

你不知道该说什么，你只是点了点头。你知道那种感觉。你太知道了。

第二个人是一个中年男人。他坐在角落里的那张沙发上，穿着一件深蓝色的西装，领带松了，衬衫领口的扣子解开了两颗。他看起来像是刚从某个重要的场合赶过来的，身上带着一种疲惫的体面。他没有喝茶，只是双手交叉放在膝盖上，直直地盯着茶几上那壶茶，像是在那壶茶里寻找什么答案。

他注意到你在看他，主动开口了。"我来看我儿子。"他说。"我儿子今年应该八岁了。但他五岁的时候就没了。车祸，就在我们小区门口。那天是我接他放学的，我让他自己过马路去对面买冰淇淋，我停在路边接了一个电话。就那么几秒钟。我听到刹车的声音，然后是我老婆的尖叫。"他停了一下，喉结上下滚动了一下，像是在吞咽什么很硬的东西。

"我不怪司机，不怪任何人。我只怪我自己。那个电话是公司打来的，说的是一个根本不重要的项目。我用我儿子的命换了一个不重要项目的三分钟。这三分钟就是我余生的全部重量。"他的声音很平，平到了一种可怕的程度，像是一潭死水，底下全都是淤泥和暗流。

"我老婆后来跟我离了婚。她说她不怪我，但她没有办法再看着我的脸了，因为每次看到我，她就会想起那天，想起那个电话。她搬走了，去了另一个城市。我一个人住在那个房子里，每天下班回来都要经过那个路口。我有时候会站在路口发呆，想象他还在那里，手里举着一支冰淇淋，远远地冲我笑。"

"你来这里是为了忘掉他？"你问。他摇了摇头。"我来这里是为了忘掉那个电话。只要忘掉那个电话，我就能觉得他不怪我了。我就不用每天晚上在梦里跪下来跟他道歉了。"

你忽然觉得喉咙很紧。你没有说话，因为你知道你说什么都是多余的。

第三个人是一个老人。他看起来七十岁左右，头发花白，穿着一件洗得有些发白的中山装，坐得笔直。他的面前放着一杯茶，茶已经凉了，他一口都没有喝。他的表情很平静，平静到了一种通透的程度，像是一面被风雨打磨了几十年的湖水，所有的波澜都已经沉入了水底。

他没有主动开口。是你先问的。"您要忘掉谁？"他看了你一眼，笑了一下。那个笑容里没有苦涩，也没有释然，只有一种你暂时还看不懂的东西。他说："我要忘掉我老伴儿。她走了十年了。十年里我每天都想她，想到后来已经不是痛苦了，是一种习惯。就像吃饭喝水一样，想她已经成了我活着的一部分。但我今年查出了病，医生说不太乐观。我不想走的时候还想着她。我想干干净净地走。"

你问他："那您这十年是怎么过的？"他说："就过呗。每天早上起来给她以前养的君子兰浇水，中午去菜市场买她爱吃的鲈鱼，晚上坐在她以前坐的那把椅子上看电视。我从来没觉得她不在了。我觉得她一直在，只是换了一种方式。"他指了指自己的胸口。"在这里。"

候诊室里安静了很久。你们四个人坐在一起，各自想着各自要忘掉的人。茶几上那壶茶从热变温，从温变凉，没有人去添水。那面没有指针的钟挂在墙上，沉默地注视着你们，像是一只没有瞳孔的眼睛。

✨ 回忆涌来

你坐在沙发上，闭上了眼睛。前台的女士说过，你可以先试一下——闭上眼睛，想着你要忘掉的那个人，看看那些记忆是什么样的。如果真的决定了，再去找她签字。

你闭上了眼睛。然后，回忆像潮水一样涌来了。

先是声音。你听到了雨声，很大很大的雨声，像是有人在天上倒水。那是你们第一次见面的那个晚上。你记得那天下了很大的雨，你没有带伞，站在公司楼下的门廊里等雨停。你看到旁边站着一个人，穿着一件灰色的风衣，围着一条红色的围巾，手里拿着一把透明的伞，但伞坏了，伞骨断了两根，伞面歪歪扭扭的，像一个瘪了嘴的笑脸。你看了她一眼，她也看了你一眼。她说："这雨是不是跟谁有仇啊。"你笑了，你说："你是不是得罪了龙王爷。"她也笑了，然后把那把坏掉的伞递给你说："送你了，反正也用不了。"你说："你送我一把坏伞是什么意思？"她说："坏伞也是伞，总比没有强。"

那把伞你后来一直留着。就放在你家门口的伞桶里。每次出门看到它，你都会想起那个雨天，想起她说话时嘴角微微上扬的样子，想起她把伞递给你的时候手指碰到你手背的那一下，凉凉的，滑滑的，像是一片被雨水打湿的花瓣。

然后是画面。你们第一次一起吃饭。她吃东西很慢，一口饭要嚼很久，她说她小时候被鱼刺卡过喉咙，所以吃东西特别小心。她点了一份糖醋排骨，吃之前先用筷子把每一块排骨翻来覆去地检查，确认没有碎骨头才敢放进嘴里。你觉得这个动作很可爱，像一只小心翼翼的松鼠。你跟她说这个比喻的时候她瞪了你一眼，说："你才是松鼠，你全家都是松鼠。"但你注意到她瞪你的时候嘴角是翘的。

画面在加速。你们第一次牵手，是在一个深秋的傍晚，走在河边的小路上。路两边都是银杏树，叶子全黄了，铺了满地，踩上去沙沙作响。你装作不经意地碰了一下她的手，她没有躲开。你就把她的手握住了。她的手很小，刚好被你的手掌包住。你感觉她的手指在你掌心里微微蜷缩了一下，像一只小动物在找一个舒适的姿势。你没有说话，她也没有说话。你们就那样牵着手走了很长很长的路，从天亮走到天黑，从路灯没亮走到路灯亮了。银杏叶落在你们的肩膀上，落在你们的头发上，落在你们牵着的手上。

再然后是味道。她身上有一种很淡的味道，不是香水，是洗衣液的味道。她一直用同一个牌子的洗衣液，你说那个味道像刚晒过太阳的棉被。她说你鼻子怎么这么灵，是不是属狗的。你说对啊，我是一条只认主人的狗。她笑着打了一下你的胳膊，说你能不能正经点。

你记得她生气的样子。她生气的时候不说话，嘴巴抿成一条线，眼睛看着别的地方，两只手交叉抱在胸前。你需要哄她很久她才会开口。有一次你们吵架了，原因你已经记不清了，可能是什么很小的事情。她气得摔门走了，你追出去，在楼下的便利店里找到了她。她站在冰柜前面，手里拿着一根冰淇淋，脸还是绷着的，但冰淇淋已经快要化了。你说："买了就吃啊，化了多浪费。"她白了你一眼，咬了一大口冰淇淋，腮帮子鼓鼓的，看起来一点都不生气了，但她还是假装生气的样子，含含糊糊地说："我还在生气。"你说好好好你继续生气，先把冰淇淋吃完。她噗嗤一下笑了出来，然后又迅速绷住脸说："没笑，我没笑。"

你记得你们一起看日出的那次。你们凌晨三点爬起来，开车去了海边。到了海边的时候天还是黑的，只有海浪的声音在黑暗里一下一下地拍打着沙滩。你们裹着一条毯子坐在沙滩上等。等了很久很久，久到你都快睡着了，海平线上终于出现了一道橙红色的光。太阳一点一点地升起来，把整片海面都染成了金色。你转头看她，她的脸上映着日出的光，眼睛亮得像两颗星星。她说："好美啊。"你想说，你更美。但你没有说出来，你只是把毯子往她身上裹了裹，把她抱得更紧了一些。

你记得所有的事情。你记得她开心的时候会拍手，记得她难过的时候会咬指甲，记得她紧张的时候会一直摸自己的耳垂。你记得她喜欢吃草莓味的任何东西，记得她害怕打雷，记得她每次打雷都会给你打电话，哪怕是大半夜。你记得她说过她小时候的梦想是当一个画家，后来因为要照顾家里放弃了。你记得你说那你以后养你你就画画，她笑着说好啊那你要努力赚钱。你记得你真的努力了，你加班，你攒钱，你甚至偷偷去看了房子的首付。

然后你记得最后的那些画面。你们坐在客厅里，她拿着手机在看什么，你从厨房端了两杯水出来。她忽然抬头看着你，很认真地说："你觉得我们会一直在一起吗？"你说当然了。她说："如果有一天我们分开了呢？"你说不会的。她没有再说什么，低下头继续看手机。但你注意到她的眼眶红了。

后来你们真的分开了。不是因为她不爱你，也不是因为你不爱她。是因为一些你无法改变的事情——她的家里出了很大的变故，她必须去另一个城市，很远的地方，远到你们之间隔了整个国家。你们试过异地，每天打电话，每天视频，但距离这个东西太残忍了，它把你们之间的温度一点一点地抽走，直到你们握着手机都感受不到对方的存在。最后是她提的分手。她在电话里说："我不想让你等我了。你不该等一个不确定会不会回来的人。"你说你可以等。她说："我知道你可以，但我不想让你这样。你应该去过你自己的生活。"

你没有再说什么。你挂了电话。那天晚上你一个人坐在客厅的地板上，把那把坏掉的透明伞从伞桶里拿出来，放在腿上，看了整整一夜。

你睁开眼睛。候诊室里还是那么安静。你的脸上是湿的，你不知道你什么时候开始流泪的。你用手背擦了擦脸，深深地吸了一口气。你感觉自己像是刚从水底浮上来，胸口有一种被挤压的钝痛。

那些画面太清晰了。清晰到你甚至能闻到她身上的味道，能感受到她手指的温度，能听到她说话的声音。你闭上眼睛的时候，她就在那里。你睁开眼睛的时候，她就不见了。这种落差让你觉得你的心脏被人用两只手捏住了，用力地、缓慢地捏着，不松手。

🌧️ 医生的话

你站起身来，走出了候诊室。你沿着走廊走回前台，那个穿白衬衫的女人还坐在那里，像是从来没有动过。你把那张深灰色的卡片放在桌上，看着那几行字。你的手指在卡片边缘摩挲着，指腹感受着卡片的纹路。你还是犹豫的。

"我能问一下吗，"你说，"来过这里的人，他们后来怎么样了？"她放下手里的笔，抬起头看着你。她的目光很平稳，像是一面没有波纹的湖。

