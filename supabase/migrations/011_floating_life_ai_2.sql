下一个画面。天台。那是你们经常去的一个天台，在你们合租的公寓楼顶。画面里是晚上，城市的灯光在远处闪烁。她站在栏杆前面，风吹起她的头发。你站在她身后，从后面抱住了她。她靠在你胸口，你们就这样站了很久。画面里有烟花——不是节日的那种大型烟花，是不知道谁在楼下放的那种小小的烟花，噗的一声升起，在半空中绽开，然后消失。她看到烟花的时候轻轻地"哇"了一声，你听到她开心的声音，哪怕隔着裂缝和时间的距离，你都能感受到那种快乐。

下一个画面，是你最不敢看的那个画面。

你们的第一次接吻。

那是在一个下雨天。你们挤在一把伞下面，伞太小了，遮不住两个人，你们的肩膀都淋湿了。画面里的你忽然停下来，把伞举高了一点，低头看着她。她也抬头看着你。雨水顺着伞的边缘滑下来，在你们之间形成一道水帘。你凑过去，她也凑过来。你们的嘴唇碰在了一起。

