她喜欢这份工作。夜班虽然辛苦，但她喜欢夜空。夜空是她见过的最诚实的东西——它不会伪装，不会说谎，不会像人一样明明想说"我喜欢你"却说"今天天气不错"。星星就在那里，亮就是亮，暗就是暗，不躲也不藏。

