有些镜子照出的是你的样子，有些镜子照出的是你没走过的路。我们总以为另一种选择会通向更好的结局，但真正困住我们的，从来不是选择了哪条路，而是始终站在路口不肯迈步。那个镜中的自己，他过的不是你的人生——他过的是你放下执念之后，才能开始的人生。错过的已经错过，但余生的路还在脚下。不是每一面镜子都需要回头看，有时候，转身向前走，才是对"意难平"最好的回答。

