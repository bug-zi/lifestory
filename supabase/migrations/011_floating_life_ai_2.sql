## 第六章：镜中人看到了你

那一天毫无征兆。

你照常在下午四点走进"拾光阁"，照常走到角落，站在镜子前面。镜中的画面是傍晚的街道，另一个你和他并肩走着，手里各拎着一个购物袋。他们在超市买了菜，正在回家的路上。

一切和往常一样。你平静地看着，像看电影一样，保持着一种安全的距离感。你已经学会了不动感情。或者说，你已经把感情压到了很深的地方，深到你自己都快要以为它不存在了。

然后另一个你忽然停下了脚步。

他站在人行道上，微微偏过头，目光越过他的肩膀，看向了一个方向。那个方向——如果镜子里的世界和现实世界是镜像关系的话——恰好是你站立的位置。

你的心跳漏了一拍。

他皱了皱眉，像是看到了什么不可思议的东西，又像是在确认自己没有看错。他伸出手，在他面前虚空中比划了一下，仿佛在触摸一扇只有他能看到的窗户。

旁边的他发现了异样，拉了拉他的袖子，问了一句什么。另一个你没有回答，只是直直地看过来。

隔着镜面，隔着不知道多远的距离，隔着两个平行的世界，你们的目光第一次交汇了。

你愣住了。双手不自觉地攥紧了衣角。

另一个你看了你很长时间。大概有十几秒，也可能有一整个世纪——在那一刻，时间的尺度完全失效了。然后他动了动嘴唇，说了三个字。

你听不到声音。但你读懂了他的唇语。

"对不起。"

你的泪水瞬间就下来了。不是那种无声的、安静的流泪，而是整个人像被什么东西击中了一样，膝盖发软，蹲了下去，双手捂住了脸，肩膀剧烈地颤抖。

对不起。另一个你在对你说对不起。为拥有了你没有拥有的一切而抱歉。为走了你没有走到的路而抱歉。为替你过上了你梦寐以求的生活而抱歉。

还是说——他在替你们之间的错过道歉？在替那个没有先低头的自己道歉？在替那三年、一千多个日夜的沉默道歉？

你不知道。你只知道那三个字比任何话语都重，压在你的心口，让你喘不过气来。

蹲在地上的你听到身后传来脚步声，老人走到你旁边，默默地站着，没有说话。过了一会儿，他轻声说："镜子里的世界，不是用来让你羡慕的。"

你抬起头，泪眼模糊地看向他。

"它是用来让你放下的。"

你回头看向镜子，另一个你已经不在那里了。镜面恢复了正常的反射，映出你蹲在地上、满脸泪痕的样子。你看起来狼狈极了，但奇怪的是，那双眼睛里除了悲伤之外，还有一点别的什么东西。

像是释然。

## 第七章：转身离开

你最后一次去"拾光阁"是在一个晴朗的早晨。

你没有站到镜子前面。你走到柜台前，看着那位老人。他依然坐在老位置，读着那本线装书，茶杯里的茶冒着热气。

"我要搬走了，"你说，"工作调去了另一个城市。"

老人放下书，看着你，点了点头。

"这面镜子——"你犹豫了一下，"它会一直在这里吗？"

"它一直都在这里，"老人说，"在你来之前就在，你走了以后也在。它不等人，也不追人。"

你沉默了一会儿。然后你从口袋里掏出手机，翻到通讯录，找到了那个三年没有拨出过的号码。你盯着那个名字看了很久，手指悬在屏幕上方，迟迟没有按下去。

"我该给他打个电话吗？"你问。但你不是在问老人，你是在问自己。

老人没有回答。他端起茶杯，慢慢喝了一口。

你最终没有拨出那个电话。不是因为不想，而是因为你终于明白了一件事——你站在镜子前面看了这么多天，不是在看另一个你过得有多好，而是在看你自己到底失去了什么。看到了，也就够了。那些错过的、遗憾的、来不及说出口的话，它们是真的，它们发生过，但它们不应该成为你的牢笼。

你把手机放回口袋，走到镜子前面，最后看了一眼。镜面映出你自己的样子——眼眶还有些红，但表情平静。你对着镜子里的自己点了点头，像是在和一个老朋友告别。

然后你转身走向门口。

铜铃又响了。这一次，声音不再急促，而是悠长的、沉稳的，像是一声温柔的祝福。

你推开门，走进阳光里。巷子里的青苔在晨光中显得格外鲜绿，头顶的电线上一只麻雀停了停，又飞走了。你深吸一口气，空气里有泥土和花开的味道。

你没有回头。

你走在去往新城市的路上，行李箱的轮子在柏油路上发出细碎的声响。口袋里的手机安安静静的，通讯录里的那个号码还在，但你已经不再觉得它是一个解不开的结了。

也许有一天你会拨出那个电话，也许不会。也许有一天你们会在某个路口重逢，也许永远不会。但不管怎样，你终于可以带着那些回忆往前走了，不再被困在"如果"两个字里。

那个镜子里的世界，那个没有错过的你，那个温暖的公寓、海边的夕阳、雨夜的拥抱——它们不是你的，但它们也不是毫无意义的。它们是你心里最柔软的部分具象化以后的模样，是你在最孤独的时候，灵魂为自己编织的一个安慰。

而你，终于到了可以不需要这个安慰的时候了。

你抬起头，看着前方。路很长，阳光很好。

你对自己说：走吧。


