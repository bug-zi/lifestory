你其实一直在等。你白天上班的时候心不在焉，对着电脑屏幕上的表格发呆，脑子里全是昨晚的画面。你提前下了班，在路边的便利店买了一份便当，回家匆匆吃完，然后关了大灯，打开台灯，坐在床上等。

