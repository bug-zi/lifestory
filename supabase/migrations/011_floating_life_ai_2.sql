然后另一个你走过去了。

他绕过茶几，蹲在他面前，伸手去拉他的手。他甩开了。另一个你又伸出手，这次没有去拉，而是轻轻地放在了他的头顶。他就那么蹲着，一只手捂着脸，另一只手慢慢摸索着，握住了另一个你的手腕。

