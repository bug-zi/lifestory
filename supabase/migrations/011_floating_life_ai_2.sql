江辰在太空站的第一千零四十七天，做了一个违规的事。

他打开星际通信阵列的控制台，在通信协议的数据流里嵌入了一段私人信息。这段信息不长，大概三千个字节，被编码成了宇宙中最基本的电磁波形式。它从太空站的天线发射出去，以光速向宇宙深处传去。

按照通信规程，这种私人信息是被严格禁止的。通信阵列只允许传输科研数据和工程指令，任何私人用途都可能导致通信信道被污染。但江辰不在乎。他已经在这个距离地球三十八万公里的太空站上待了将近三年，三年的孤独足够让一个理性的工程师做出不太理性的事。

