这些你太熟悉了。你们当初也是这样吵的。为了一件小事起头，然后翻出所有旧的伤疤，一个比一个狠，直到两个人都遍体鳞伤。

在你记忆里的那场争吵，你们谁也没有让步。你摔了门走了出去，在楼下的便利店坐了两个小时，等他打电话来找你。但电话始终没有响。你回去的时候，他已经收拾了东西走了。桌上留了一张纸条，写着"我们都冷静一下吧"。

那个"冷静一下"，最终变成了三年。

