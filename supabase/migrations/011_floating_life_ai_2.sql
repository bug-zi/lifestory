苏晚读懂了他的眼神。但她没有说什么。她只是转回头继续看流星，把围巾的一角悄悄拉过来，盖住了他搭在栏杆上的手。

他们之间始终没有那句"我喜欢你"。不是不想说，是都觉得不急。他们有足够的时间，或者他们以为自己有。

✨ 二十年后

江辰在太空站待了五年后回到了地球。回来的时候他三十二岁，腰椎出了问题，听力也下降了一些——太空站的环境对身体的消耗比预想的大。他在海边的小镇上买了一间房子，养了一条狗，过着日出而作日落而息的生活。他不再看星星了。不是不想看，是不敢。每次抬头看到夜空，他就会想起太空站上的那扇舷窗，想起那个蓝色的球体，想起苏晚那张天文台侧面的照片。

他打听过苏晚的消息。她在某个天文台工作，具体哪个不清楚。他们失去联系很久了——他从太空站回来后换了手机号，她也搬了城市。他偶尔会在天文杂志上看到她的名字，在一些论文的作者列表里。她还在看星星。有时候深夜，他会走出房子，站在海边抬头看。海面上没有灯光污染，星星特别多，密密麻麻地铺满了整个天空。他会在那些星星里找猎户座——那是苏晚最喜欢的星座，她说猎户的腰带像一条项链，是宇宙戴给黑夜的饰品。他找了十几年，每次都能找到。但找到之后又不知道该怎么办。看一眼，然后回屋睡觉。日复一日。

那段漂流瓶的信息，他早就忘了。像年轻时说过的许多话一样，说过就散了，被时间稀释得无影无踪。

十五年后，江辰五十二岁了。头发白了一半，膝盖不好使了，那条狗也老了，每天趴在门廊上晒太阳，懒得动。他在镇上的五金店打零工，日子过得平淡但安静。

那天下午，他正在店里整理货架，听到收音机里播了一条新闻："国家天文台今日宣布，在射电望远镜阵列的数据中发现了一段来自外太空的异常信号。信号经解码后，发现其内容为一段人类语言文字。据分析，该信号发送时间约为二十年前，发送位置为近地轨道空间站。目前天文台正在尝试定位信号的原始发送者。"

江辰手里的扳手掉在了地上。他站在五金店的货架中间，听着收音机里播音员继续说着——信号内容、发送时间、编码方式——每一条信息都像是一把钥匙，打开了尘封了二十年的记忆。

他的漂流瓶。被人捡到了。

🌀 银河另一端的回信

事情的经过是这样的。

江辰发出的那段信息以光速向宇宙深处传去。它穿过了太阳系，穿过了奥尔特云，穿过了最近的恒星比邻星——用了四年多的时间。它经过木星时，巨大的引力场弯曲了信号的路径，像是一个巨人弯腰看一张飘过的纸条。然后它继续前进，穿过了银河系的猎户臂，进入了一个遥远的恒星系统。

那个恒星系统里有一颗行星，上面有一个文明。这个文明比人类古老得多，他们对宇宙的理解深入到了人类无法想象的程度。他们截获了江辰的信息时，被其中的一段内容打动了——不是文字本身，他们不懂人类的语言，但他们能读取信息中蕴含的情感编码。在他们的感知里，那段信息散发着一种温暖的、柔和的频率，像是一颗恒星在低声呢喃。他们从未在其他宇宙信号中检测到这种频率。他们给它取了一个名字，翻译成人类语言大概是——"想念"。

他们决定回信。用他们最先进的量子纠缠通信技术，把一段信息"折叠"回信息发送的方向。回信用了三年才完成编码，然后在一瞬间穿越了数十光年的距离，出现在地球的射电望远镜阵列中。

回信的内容很简单。翻译成人类的语言后，只有一句话：

"我们收到了你的想念。它在宇宙里旅行了很久，变得有些模糊了，但还温暖。你想念的那个人——她叫苏晚。我们在信号的底噪中检测到了你对她说的话。你从来没有说出口的那些话，信号替你说了。去找她吧。宇宙没有那么大。"

回信还附带了一组坐标数据——不是苏晚的地址，而是江辰当初发送信号时所在的太空站的轨道参数。这意味着，那个外星文明不仅读懂了信号里的情感，还精确定位了信号的源头。他们用了二十年的时间，跨越了数十光年的距离，只为了把一句话送回它出发的地方："去找她。"

这让江辰觉得宇宙并不像他想象的那么空旷。在那些黑暗的、寂静的星际空间里，也许有无数这样的信号在飞行——带着人类的爱和想念，穿过一个又一个恒星系统，被一个又一个文明截获。也许在宇宙的某个角落，有一整座图书馆，收藏着所有被发射到太空里的私人信息。每一封都是一个人最隐秘的心事，被宇宙妥善保管着，等待着某一天被送达。

🌧️ 找到你

江辰用了三个月找到了苏晚。

她在西北的一个天文台工作，海拔三千米的山顶上，空气稀薄得让人头疼。江辰坐了十二个小时的火车、四个小时的大巴、又爬了四十分钟的山路才到达。他到的时候已经下午了，太阳正在落下去，把整片高原染成了金红色。天文台的白色天线阵列在夕阳下闪着光，像是一群沉默的巨人举着耳朵在听宇宙说话。

五十一岁的苏晚还是那么瘦，头发剪短了，戴着一副金丝眼镜。她看到江辰出现在天文台门口的时候，手里的咖啡杯差点掉了。

"江辰？"

"好久不见。"

她站在那里，穿着一件白色的实验服，胸前别着一支笔。身后是巨大的射电望远镜阵列，白色的天线指向天空，像是一群沉默的守望者。风很大，吹得她的衣角猎猎作响。

"你怎么找到这里的？"

"你的漂流瓶收到了回信。"江辰从口袋里掏出一张折了很多次的纸条，递给她。纸条上是那段回信的打印件，已经被他翻得很旧了。

苏晚接过纸条，低头看了一遍。然后她抬起头，看着江辰，眼泪无声地流了下来。不是伤心的泪，是那种等了很久很久终于等到了什么的泪。像是夜空中一颗星星的光，走了几十年终于到达了地球。

"二十年了。"她说。

"嗯。"

"你在太空站发的那个东西……"

"嗯。"

"你从来没有跟我说过。"

"嗯。"江辰站在风里，看着她。五十多岁了，皱纹爬上了眼角，但眼睛还是那么亮——像天文台那个夜晚，红色指示灯和蓝色屏幕光照亮的那种亮。"苏晚，我想跟你说一句话。二十年前的那个漂流瓶里没说够，我现在想当面说。"

"什么话？"

"我喜欢你。从天文台那个晚上就开始了。流星雨那天，我在看你，没在看流星。"

苏晚擦了擦眼泪，笑了。笑得和二十多年前一模一样——嘴角弯弯的，眼睛亮亮的，像是整个人都被光点亮了。她从实验服口袋里掏出一样东西，递给江辰。是一块很小的石头，表面光滑，带着一点淡淡的蓝色。

"这是什么？"

"天文台的屋檐上捡的。那天晚上看完流星雨之后，我偷偷捡了一块石头放在口袋里。带了二十年了。"

"为什么？"

"因为那天晚上你看着我的时候，我觉得……比流星雨好看。我把那一刻装进了石头里，怕忘了。"

石头很小，表面被时间打磨得很光滑。江辰握在手心里，感觉到它的温度——不是石头本身的温度，是她握了二十年留下的余温。

风把她的白发吹起来，又放下。江辰伸出手，握住了她握着石头的那只手。两只手都很粗糙了——他的手被太空站的金属舱壁磨出了茧子，她的手被望远镜的冰冷金属冻出了关节痛。但握在一起的时候，感觉还是和二十多年前一样。

宇宙很大。但"我喜欢你"这句话，只需要很短的距离就能传到。短到只要两个人站在一起，风就能把话送到。
