这一次的画面比昨天清晰得多，像是分辨率被调高了。你看到了一条街道，街道两边种着梧桐树，树叶是金黄色的，地上铺了一层落叶。画面里有两个人在走，是你和她。你走在她左边，她走在你右边。你们的距离很近，近到手背偶尔会碰到一起。

画面里的你忽然停下来了。她也停下来，转头看你。你从口袋里掏出一样东西——一条围巾，红色的，很柔软。你把它围在她的脖子上。她低下头让你围，围好之后抬起头，笑着说了什么。你听不到声音，但你能从她的口型猜出来，她说的是"你什么时候买的"。画面里的你耸了耸肩，装出一副无所谓的样子。她笑着打了一下你的胳膊。

画面切换了。像是有人在剪辑一部关于你们的纪录片，把最甜的片段剪在一起。

下一个画面是你们在一家餐厅里。桌上摆满了菜，火锅，红汤翻滚着冒出白气。她夹了一块毛肚放在你碗里，你又夹回去给她。她再夹给你，你再夹回去。来回几次之后她笑了，笑得前仰后合，筷子差点掉进锅里。你伸手帮她把筷子捞出来，手指上沾了油，她扯了一张纸巾帮你擦。她擦得很仔细，一根手指一根手指地擦，像是世界上最认真的事情。

