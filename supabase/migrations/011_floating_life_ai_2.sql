音乐学院的教学楼有一排琴房，两两相邻，中间隔着一堵薄薄的石膏板墙。季然在左边教钢琴，夏暖在右边教大提琴。他们从来没有约定过要一起演奏什么，但每天下午三点到五点，琴房里会自然而然地响起两个人的合奏。

季然弹的是肖邦的《降E大调夜曲》。夏暖拉的是她在上面即兴加了旋律的变奏。两个声部在石膏板墙的两侧交织在一起——钢琴的清亮和大提琴的浑厚，像是两条不同源头的河流在某个峡谷里汇合了，水花四溅，奔涌而下，然后平静地流向远方。

季然不知道她什么时候开始配合他的。也许是从第一天开始——他弹完第一乐章的时候，隔壁沉默了几秒钟，然后大提琴的声音响了起来，刚好接上了第二乐章的旋律。那个衔接太自然了，自然到他以为是巧合。但第二天、第三天、第一周、第一个月，合奏从未间断过。他弹什么，她就跟什么。他快，她就快。他慢，她就慢。他停下来呼吸的时候，她也停下来。像是两个人共用了一根神经。

季然想认识她。但他不知道怎么开口。他是个教钢琴的大学老师，三十出头，戴着一副银框眼镜，说话的时候总是慢半拍，像是每一个字都要在心里过一遍筛子才放出来。他不擅长主动社交——学生叫他"季慢慢"，因为他弹琴的时候喜欢把速度放慢，说"音乐不是赛跑，慢慢来才好听"。

三个月后的一天傍晚，季然在走廊里遇到了她。她抱着一架比她上半身还大的大提琴，从琴房里走出来。她个子不高，一米六出头，头发剪得很短，耳朵上戴着一枚很小的银色耳钉。她看到季然的时候笑了一下，说："今天的肖邦，第三小节你慢了半拍。"

季然愣了。这是她跟他说过的第一句话。不是"你好"，不是"我是夏暖"，而是指出他弹错了的地方。

"我故意的。"他说。

"骗人。"她笑了。"你故意的方向不对。慢半拍应该在第七小节，那里有一个呼吸的间隙。第三小节慢了会破坏乐句的完整性。"

季然看着她。走廊的灯光是暖黄色的，照在她短发的轮廓上，像是给她镶了一圈柔和的边。她的眼睛不大，但很亮，看人的时候像是能看透什么。

"你怎么知道我故意的方向不对？"

"因为我在听啊。"她说得理所当然，像是这是全世界最自然的事。"我每天都在听你弹琴。你以为那堵墙能挡住声音吗？"

从那天起，他们开始一起吃午饭。在音乐学院的食堂里，他们坐在靠窗的位置，各自的餐盘放在桌子两端。季然吃饭很快，夏暖吃饭很慢，她把每一口都嚼很多遍，像是在品尝什么。季然等她吃完的时候会翻手机，但不是在看什么，只是给手指找点事情做。

他们在一起是在那年秋天。十月的某个下午，合奏结束后，季然走到隔壁琴房的门口，敲了敲门。夏暖打开门，大提琴还夹在两腿之间，琴弓举在半空中。她看着他，等他说话。

"夏暖。"

"嗯？"

"明年夏天，国家大剧院有一场户外音乐会。德沃夏克的《自新大陆》。我想……和你一起去看。"

夏暖看着他，看了五秒钟。然后她笑了——不是那种"你真可爱"的笑，是那种"我终于等到了"的笑。眼睛弯弯的，嘴角往上翘，耳朵上的银色耳钉晃了一下，反射了走廊的灯光。

"好。"她说。只有一个字。但这个字比任何乐章都好听。

🌙 生前·那个夏天没有来

那个夏天没有来。

五月十七号，季然在去学校的路上出了车祸。一辆闯红灯的货车从侧面撞上了他的出租车。救护车到的时候，他已经没有了呼吸。

夏暖是在琴房里接到电话的。她当时正在拉琴，拉的是他们合奏过的那首肖邦。手机响了三次她才接。接起来听到的是季然母亲的声音，很平静，平静到像是在念一段天气预报：季然走了，今天早上，车祸。

夏暖没有说话。她把手机放在琴谱架上，继续拉琴。从头拉起。第一乐章，第二乐章，第三乐章。大提琴的声音在空荡荡的琴房里回荡，没有钢琴的配合，旋律空了一半，像是一个人只剩了影子。

她拉了三个小时。从下午拉到天黑。琴房的灯是声控的，她不动了灯就灭了。黑暗里只剩大提琴的声音，呜呜咽咽的，像是一个人在哭。

琴房管理员来敲门的时候，发现夏暖坐在地上，靠着墙，怀里抱着大提琴，琴弓松松地垂在手指间。她在黑暗里睁着眼睛，没有泪，没有表情。管理员叫了她的名字三遍，她才转过头来，说了一句："隔壁没有声音了。"

从那以后，隔壁的琴房再也没有人弹过钢琴。

夏暖每天还是去琴房，还是坐在自己的位置上，还是抱着大提琴。但她不再拉琴了。她只是坐在那里，把耳朵贴在那堵石膏板墙上，听。墙上什么声音都没有了。没有钢琴，没有肖邦，没有那个总是把第三小节慢半拍的人。

她等了一年。这一年里，她瘦了二十斤，头发长长了，不剪了。她把琴房的钢琴凳搬到自己这边来——管理员说那架钢琴已经没人用了，她想搬就搬吧。她把钢琴凳放在大提琴旁边，上面放了一本翻开的琴谱——肖邦的《降E大调夜曲》，翻到他们合奏最多的那一页。琴谱上有季然用铅笔写的指法标注，字迹工整，一笔一画的，像是在写字帖。

一年后的五月十七号，夏暖在琴房里闭上了眼睛。

管理员发现她的时候，她靠在那堵墙上，头微微偏向隔壁的方向，嘴角带着一丝很浅的笑。大提琴立在她身边，琴弓放在琴谱架上，琴谱翻到了最后一页。

没有人知道她在最后一刻听到了什么。也许是安静。也许是——那首肖邦的第一乐章，从墙壁的另一边传过来，像是有人在很远很远的地方，弹着琴等她。

✨ 死后·忘川

死后的世界比季然想象的要安静得多。

没有地狱的烈火，没有天堂的合唱，没有奈何桥和孟婆。只有一条河。河水是浅灰色的，看不清深浅，水面平静得像一面镜子，不流动，不起波澜。河的两边是灰白色的沙滩，沙子很细，踩上去没有声音。

这条河叫忘川。所有死后的灵魂都要来到这里，喝下忘川水，忘记前世的记忆，然后从河的对岸走向下一世。这是规矩。没有例外。

季然站在河的这一边，看着灰色的河水和对岸模糊的光。河边的沙滩上坐满了灵魂，有的在排队等碗，有的已经喝完了，眼神空洞地走向对岸。他们的脸上没有悲伤也没有快乐，只有一种被洗刷过的空白，像是刚被擦干净的黑板。

一个守河人走过来。他很老，穿着灰色的长袍，手里端着一个粗陶碗，碗里盛着灰色的水。水在碗里微微晃动，映出季然的脸。

"喝吧。"守河人说。"喝了就忘了。干干净净地走。"

季然看着碗里的水。水里映出的不是他现在的脸——灵魂没有固定的样貌——而是他活着时的脸。戴着银框眼镜，说话慢半拍，弹琴的时候会把速度放慢。水面上还有一个模糊的影子——一个女人，短发，银色耳钉，怀里抱着一把大提琴。

季然伸出手，碰了一下碗沿。水是凉的。他收回手。

"我不喝。"

守河人看了他一眼。这种事他见多了——每年总有几个不肯喝的。但最后都会喝的。因为记忆是重的东西，带着记忆站在忘川河边，每一天都会比前一天更累。记忆会变沉，沉到灵魂承受不住，自己就会去拿碗。

"随你。"守河人端着碗走了。

季然在忘川河边坐了下来。他选了一个位置——河的转弯处，有一块平整的石头，坐上去刚好能看到河面上游的方向。他坐在那里，闭上眼睛，在记忆里翻找那段旋律。

肖邦的《降E大调夜曲》。他在脑子里一个音一个音地弹。右手旋律，左手伴奏，第三小节慢半拍——她说过不应该在那里慢，应该在第七小节。但他偏不改。因为那是他们的合奏里唯一的"不完美"，而这个不完美是他们的秘密。

他不敢忘记这段旋律。忘川水会冲走所有的记忆——名字、面容、声音、触感。但旋律不一样。旋律不是记忆，它是频率，是振动，是比记忆更深的东西。如果他能把这段旋律刻在灵魂的最深处，忘川水就冲不走它。

所以他不喝。他守着那段旋律，坐在忘川河边，等她。

🌀 三百年

三百年是很长的时间。长到季然看着自己的父母、朋友、学生、甚至学生的学生都来到了忘川河边。他看着他们喝下忘川水，眼神从悲伤变成茫然，然后走向对岸。他没有拦他们。拦不住。每个人都要走自己的路。

他的母亲来的那天，在河边站了很久。她没有认出他——灵魂的样貌会变化，三百年足以让任何一个灵魂变得面目全非。但她临走之前回头看了他一眼，说了一句："你坐在这里很久了。你不累吗？"

季然笑了笑，说："不累。我在等人。"

他当然累。三百年的等待比任何惩罚都重。他的灵魂变得越来越薄了，像是一张被反复折叠的纸，折痕越来越多，边缘开始磨损。但他不敢放下那段旋律。旋律是他唯一的绳索，如果他松手了，就会掉进忘川水里，和她永远断开连接。

守河人每隔十年来看他一次，每次都端着那碗水。季然每次都摇头。守河人叹了口气，说："你等的人可能已经喝了水转世了。你认不出她了。"

"我认得出。"季然说。"她的灵魂带着大提琴的频率。那把琴的共振波长和别的灵魂不一样。我能听到。"

守河人走了。季然继续坐在石头上，在脑子里弹琴。右手旋律，左手伴奏。三百年来从未间断。

他有时候会做梦。在死后的世界里也会做梦——这是守河人也没法解释的事。梦里他回到了音乐学院的琴房，坐在钢琴前面，手指落在琴键上。隔壁传来大提琴的声音，温暖的、浑厚的、像是有人在用琴弦唱一首只有他们两个人听得懂的歌。他弹一句，她接一句。第三小节，他故意慢了半拍。隔壁安静了一秒，然后大提琴的声音也慢了半拍——她跟着他慢了。不是纠正他，是陪着他。

梦醒了，他又回到忘川河边。灰色的河水，灰色的沙滩，灰色的天空。三百年的灰色。但他脑海里有一段彩色的旋律，像一根线，穿过所有的灰色，系在河流上游某个他看不到的地方。

🌧️ 第三百零一年

第三百零一年的第一天，季然注意到了一个新来的灵魂。

她站在河边的队伍末尾，低着头，不像其他新来的灵魂那样茫然或害怕。她的姿态很安静，像是在听什么。她侧着头，微微偏左——那是把大提琴夹在肩膀上时的习惯性姿势。

季然从石头上站了起来。三百年来他第一次站起来。他的灵魂已经薄得像一张纸了，站起来的时候摇晃了一下，像是被风吹的。但他稳住了。他慢慢走过去，穿过沙滩上坐着的无数灵魂，走到她面前。

她没有抬头。她在听。季然走到她身边，站了一会儿。然后他开口了。声音很轻，像是怕吓到什么。

"你在听什么？"

她终于抬起了头。她的灵魂已经变得很薄了——和季然一样薄。像是被什么东西反复打磨过，所有的棱角都磨平了，只剩下核心的一点点光。她的脸不是活着时的脸，但她的眼睛是——亮的，看人的时候像是能看透什么。

"我在听一首曲子。"她说。声音沙沙的，温柔得像壁炉里的木柴。"钢琴和大提琴的合奏。从很远的地方传来的。不知道是谁在弹。"

季然的眼泪落进了忘川河里。这是忘川河三百年来第一次有人的眼泪落进去。河水被那一滴眼泪激起了一圈涟漪。涟漪很小，但扩散了很久很久，像是池塘里的涟漪不会真的消失，只是变得越来越轻，轻到肉眼看不到，但水还记得。

"那首曲子叫什么名字？"他问。

她想了很久。三百年的等待浓缩在这一刻。"我不知道名字。但我记得旋律。我已经带着它走了很远很远了。"

季然坐了下来。他没有说"我是季然"，没有说"我等了你三百年"。他只是在她身边的沙滩上坐了下来，背靠着背。就像活着的时候，隔着琴房的那堵墙——他弹钢琴，她拉大提琴。不需要面对面。不需要说话。只需要知道另一个人在那里，在同一个节奏里呼吸。

他抬起手，用手指在河边的石头上敲出了那段旋律的节奏。笃、笃笃、笃——第三小节慢了半拍。

夏暖听到了。她的身体轻轻地震了一下，像是有什么沉睡了三百年的东西被唤醒了。她开始哼。旋律从她的喉咙里流出来，沙沙的、低低的，和石头上的节奏交织在一起。大提琴的音色。三百年了，她的灵魂还记得大提琴的音色。

忘川河水在三百年后，第一次安静了下来。水面平滑如镜，不起一丝波澜。像是整条河都在听。

🕯️ 最后的选择

守河人来了。

"你们做了选择吧。"他说。声音很老很老，像是被时间磨得只剩了沙砾。"一起喝，一起走。或者留下来，做守河人，永远不走。"

季然和夏暖对视了一眼。三百年的等待让他们已经不需要语言了。他们同时说出了同一句话——

"喝。"

不是不怕忘记。是怕再等三百年，连旋律都记不住了。忘川水会冲走名字、面容、声音、触感。但他们在喝之前做了一件事——季然用手指在夏暖的手心写了一段旋律。右手旋律的前四个音。夏暖在季然的手心写了另一段。左手伴奏的前四个和弦。

他们对好了频率。下辈子如果相遇，这八个音符就是暗号。

忘川水入喉的时候是凉的。像是把一杯冰水从喉咙灌进了心脏，然后冰水带着所有的温度和颜色一起往下沉。名字先没了——"季然"和"夏暖"变成了两个空壳，像是有人把字从纸上擦掉了，只剩下浅浅的凹痕。然后是面容——他的银框眼镜、她的短发、他的慢半拍、她的银色耳钉。然后是声音——他说话时慢吞吞的语调、她指出他第三小节慢了半拍时的理所当然。然后是触感——她靠在他背上的温度、他手指落在琴键上的力度。

所有的记忆像退潮一样从灵魂里流走了。忘川河的水面泛起了细密的涟漪，像是接受了两个灵魂的馈赠。

但那八个音符没有消失。

它们不是记忆。它们是频率。刻在灵魂最底层的一种振动模式，比记忆更深，比忘川水更顽固。当所有的画面都褪成了白色、所有的声音都归零了、所有的名字都变成了空白——那八个音符还在。在灵魂的最深处，轻轻地、固执地、一遍又一遍地振动着。

像是有人在很远很远的地方，弹着琴，等一个人来和。

转世之后。也许他们在同一个城市，也许在不同的国家。也许他们是陌生人，也许擦肩而过。但如果有一天，在某条街道的拐角，或者某间琴房的隔壁，那八个音符恰好响起——他的心跳会漏掉半拍，她的呼吸会停顿一秒。他们会不自觉地转过头，看向声音传来的方向。

不知道为什么。但就是会看过去。

那是三百年的等待留下的唯一的痕迹。不是记忆，不是面容，不是名字。只是一段旋律。和一种说不清的、让心脏漏跳半拍的感觉。
