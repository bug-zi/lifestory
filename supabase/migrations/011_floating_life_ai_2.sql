然后画面开始快速切换，像是有人在翻一本相册，哗啦啦地翻。你看到了很多画面——她靠在你肩膀上睡觉、你骑自行车载着她穿过小巷、你们在超市里为了买哪种酸奶而争论、她在你生日那天做的一个歪歪扭扭的蛋糕、你们在海边光着脚踩浪花。这些画面一个接一个地出现，每一个都很短暂，但每一个都清晰得让你心疼。

最后画面定格在一个场景：你们的出租屋。她坐在沙发上，怀里抱着那只橘色的猫——对，你们一起养过一只猫，你差点忘了。她在看书，猫在她腿上打呼噜。你从厨房端了两杯水出来，递给她一杯。她接过水，抬头对你笑了一下。

那个笑容。你看着那个笑容，蹲在裂缝前面的你忽然觉得眼睛发酸。不是因为悲伤，是因为那个笑容太好了。好到你觉得它不应该属于你。好到你觉得你应该把它好好地收在某个地方，不要让它碎了。

但你知道它还是碎了。

画面消失了。裂缝暗了下去。你在黑暗中坐了很久，久到腿完全麻了，站起来的时候差点摔倒。你扶着墙，慢慢走到床边，躺下来。你闭上眼睛，脑子里全是刚才的画面。你忽然意识到一件事——裂缝播放的不是别人的故事，是你的故事。是你的、也是她的故事。是一个你以为已经结束了的故事。

但你错了。故事没有结束。它只是被藏在了墙上的裂缝里。


## 第三章：你不知道的事

裂缝在第三个晚上给你看了一些不一样的东西。

画面开始的时候，你以为是和之前一样的甜蜜重播。但这次画面里只有她一个人。没有你。这是第一次，裂缝播放的画面里没有你。

画面里是深夜。凌晨两点，你从时间戳上判断出来的。她坐在你们合租公寓的床上，手机屏幕亮着，对话框打开着。你能看到对话框上面是你的名字。她在打字，打了很长一段话，然后停下来，全部删掉。又打了几个字，又删掉。删掉之后她把手机扣在床上，仰头看着天花板，深深地叹了一口气。然后她又拿起手机，打了一行字："你在干嘛？"发送。等了三分钟，没有回复。她又把那条消息撤回了。

你看着画面里的她，忽然觉得胸口被什么东西堵住了。你记得那段日子。那是你们在一起第三年的时候，你工作特别忙，经常加班到半夜才回家。你以为她习惯了，以为她理解你。但画面告诉你的是——她没有习惯，她只是在忍耐。

画面切换了。这是另一个深夜。她一个人坐在餐桌前，面前放着一个蛋糕。是一个小小的草莓蛋糕，上面插着一根蜡烛。蜡烛已经烧了大半，蜡油滴在奶油上，凝成一团白色的硬块。她双手合十，闭上眼睛许了个愿。然后她睁开眼睛，吹灭了蜡烛。她没有切蛋糕，而是拿了一根叉子，一个人慢慢地吃。一口一口地吃，吃得很安静。桌上放着两个盘子，另一个盘子是空的。那个空盘子本来应该是你的。

你猛地想起来了。那天是她的生日。你忘了。你加班加到半夜两点才回家，推门进去的时候她已经睡了。你以为她只是困了。你甚至没有注意到桌上那个吃了一半的蛋糕。第二天早上你看到蛋糕的时候问她是谁的生日，她笑了笑说"不是什么重要的日子"。你信了。

画面里的她吃完了蛋糕，把盘子洗干净，擦干，放回橱柜里。然后她走到阳台，在你们种的那盆薄荷前面蹲下来。她摘了一片叶子放在鼻子下面闻了闻，然后自言自语地说了一句话。你听不到声音，但你看清楚了她的口型。她说的是："他还记不记得这盆薄荷是我种的？"

画面又切换了。这是你们分手前一个月。她坐在卫生间的浴缸边上，手里拿着一根验孕棒。验孕棒上显示的是两条杠。她盯着那两条杠看了很久，久到画面开始微微晃动——不是画面在晃，是她的手在抖。然后她放下验孕棒，用双手捂住了脸。你看不到她的表情，但你能看到她的肩膀在颤抖。她在哭。

你不知道这件事。你完全不知道这件事。她从来没有告诉过你。

画面继续。第二天早上，她把验孕棒用报纸包了好几层，扔进了楼下的垃圾桶。她的表情很平静，像什么都没有发生过。你那时候还在睡懒觉。她从外面回来，走进卧室，看了你一眼。你翻了个身，继续睡。她站在床边看了你很久，然后轻轻地帮你拉了拉被子。

再后来——你知道的，后来她去了医院。你不知道的是，她一个人去的。她在医院里坐了一整天，出来的时候天已经黑了。她给你打了一个电话，问你晚上想吃什么。你说随便。她说好，那就吃面吧。她回到家煮了两碗面，你们面对面坐在餐桌前吃面。她一直在笑，和平时一样。你完全看不出她那天刚刚从医院回来。

画面里还有一个你从没见过的场景。那是在一个周末的下午，你出门打球了。她一个人在家，拿出了一个鞋盒。鞋盒里面装的是一些小东西——电影票根、餐厅的小票、你们一起拍的拍立得照片、你送她的那条围巾的标签。她一样一样地拿出来看，看完之后再一样一样地放回去。最后她从鞋盒底下拿出一张纸，展开来看。那是一张你写的便条，上面的字歪歪扭扭："明天降温，多穿点。"她看着那张便条笑了，但笑着笑着，眼泪就掉下来了。她把那张便条贴在胸口，蜷缩在沙发上，抱着膝盖，安静地哭了很久。

你蹲在裂缝前面，你的手在发抖。你从来不知道这些。你从来不知道在你忙于工作、忙于自己的事情的时候，她在经历什么。你从来不知道她深夜发给你又撤回的那些消息里写了什么。你从来不知道她一个人过生日时的表情。你从来不知道她曾经怀过你的孩子，又一个人去了医院。你从来不知道她有一个装满你们回忆的鞋盒。

你以为你们的分手是突然的，是她"忽然说我们不合适"。你以为她是那种说走就走的人。你甚至在心里怨恨过她——觉得她不够爱，觉得她太轻易放弃了。

但裂缝告诉你的是另一个版本的故事。那个版本里，她比你想象中爱你一万倍。也比你想象中痛苦一万倍。


## 第四章：日常的珍贵

第四个晚上，裂缝播放的画面变了味道。不再是大悲大喜的场景，而是一些日常的碎片。那些你当时觉得平淡无奇的时刻，现在隔着裂缝看回去，每一段都闪着光。

第一个画面是春节。你们在一起过的第一个春节，两家人的城市隔得太远，你们决定不回家，在出租屋里两个人过年。画面里你们在包饺子，她负责擀皮，你负责包。你包的饺子奇形怪状，有的站不住，有的馅儿露在外面。她看了你包的饺子笑得停不下来，笑到蹲在地上站不起来。你假装生气，把面粉抹在她鼻子上。她大叫一声，抓了一把面粉朝你扔过来。面粉撒得到处都是，厨房里白茫茫的一片，像下了一场小雪。你们在面粉雪里对视了三秒钟，然后一起笑了。

后来你们把饺子煮好了，端到茶几上，打开电视看春晚。电视里的声音很大，但你们几乎没有在看。她在用手机拍你包的丑饺子，一张一张地拍，还加了滤镜。你说丑东西有什么好拍的，她说好看的东西不值得记录，丑的才值得。你们在沙发上挤在一起吃东西、看电视、聊天。聊着聊着她就靠在你肩膀上睡着了，手里还攥着一只饺子。你轻轻把饺子从她手里拿出来，发现饺子已经被她攥变形了。

画面切换。这是你们一起做饭的日常。她在切菜，切得很慢，每一刀都很认真。你在旁边炒菜，锅铲翻得飞快，油烟呛得你直咳嗽。她在旁边说你能不能小点火，你说过几天就习惯了。她把你从灶台前推开，自己来炒。她炒的菜比你好吃一百倍，但你从来不承认。你每次都说"还行吧"，然后添两碗饭。她看着你添饭的样子偷偷地笑，被你发现了也不承认。

画面里你们有一次做饭的时候吵了一架。吵的原因很小，小到你现在完全想不起来——好像是因为你把盐放多了。她尝了一口汤，皱着眉头说太咸了。你尝了一口说还好啊。她说你味觉是不是坏了。你说你挑剔。她把汤勺往锅里一扔说不吃了。你也赌气说不吃就不吃。两个人在厨房里背对背站着，谁也不理谁。过了大约五分钟，你的肚子叫了。很大声，整个厨房都能听到。她噗嗤一声笑了出来，你也笑了。她重新拿了一根汤勺，把汤倒掉，重新烧了一锅。你在旁边帮她洗菜，你们谁都没有再提刚才的争吵。

画面切换到你们遛狗的场景。不是猫——你们后来又养了一只狗，是一只小柴犬，棕色的，叫"年糕"。你每天傍晚下班之后都会带年糕出去散步，她有时候一起去，有时候不去。画面里是一个你们三个人一起出去的傍晚。年糕在前面跑，拉着你往前冲。她在你旁边走，手里拿着一杯奶茶。年糕看到一只蝴蝶，追了上去，把你拽得踉跄了一步。她赶紧伸手扶住你，奶茶洒了你一袖子。你看着袖子上的奶茶渍，又看着她一脸歉意的表情，忍不住笑了。

