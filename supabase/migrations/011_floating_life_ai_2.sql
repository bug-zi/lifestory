🌸 二十三小时五十九分

秦越在闹钟响之前就醒了。

他盯着天花板看了很久。白色的天花板，角落里有一道裂缝，从灯座的位置延伸到墙壁的边缘，像一条干涸的河流。这道裂缝他看了三年——从搬进这间公寓的第一天就注意到了。三年里他每天早上醒来第一眼看到的都是这道裂缝，但它今天看起来不一样了。不是裂缝变了，是他看裂缝的方式变了。今天是他在地球上的最后一天。

明天上午八点，他要在航天中心登上"长征九号"载人飞船，飞往火星。单程旅途需要八个月，火星任务为期十年。十年。三千六百五十天。这个数字他算过无数遍了，每一次算都觉得它太大了，大到不像是一个人的青春应该承受的重量。但这是他从十二岁起就有的梦想。他记得很清楚，十二岁那年夏天，他在爷爷家的院子里躺着看星星，看到一颗特别亮的星缓缓划过夜空。爷爷说那是人造卫星。他说长大以后我要去比那更远的地方。

爷爷笑了笑，说好。

爷爷已经不在了。但那个愿望还在。所以秦越报名了。通过了所有体能测试、心理评估、技术考核。他是三十名候选人里唯一一个没有家属签不同意书的——因为他没有家属。父母早年离异，各自有了新的家庭。他没有兄弟姐妹，没有妻子，没有孩子。报名表上"紧急联系人"那一栏，他填了一个名字，想了很久，又划掉了。

那个名字是宋知意。

🌙 宋知意

宋知意二十七岁，在一家音乐培训学校教钢琴。她个子不高，一米六出头，说话的时候喜欢歪着头，笑起来有两个浅浅的酒窝——左边的比右边的大一点。她弹琴的时候很安静，安静到像是整个人都沉进了音乐里，只剩下手指在琴键上流动。

秦越认识她是在四年前。那时候他刚通过航天员的初选，被送到西北的基地进行封闭训练。训练基地隔壁是一所音乐学校，每天傍晚，当秦越他们在操场上跑步的时候，琴房里就会传出钢琴声。不是什么复杂的曲目，大多是练习曲和简单的奏鸣曲，但旋律很好听，穿过操场边的白杨树林，飘到秦越耳朵里的时候已经被风吹得有些模糊了，像是从很远的地方传来的回声。

他第一次见到宋知意是在操场的铁丝网边上。他跑完了五公里，弯着腰喘气，汗顺着额头往下淌。抬头的时候，看到铁丝网另一边站着一个女孩，扎着马尾辫，怀里抱着一大摞琴谱，正仰头看天——看的是同一颗星星。那天黄昏，金星特别亮，挂在天边，像一颗被遗忘的钻石。

"那颗星好亮。"她说。她没看到铁丝网这边的秦越。

"那是金星。"秦越说。

她吓了一跳，琴谱差点掉了，转头看到他，隔着铁丝网对视了两秒。然后她笑了。"你知道？"

"我知道很多东西。"秦越也笑了。那是他到基地之后第一次笑。

后来他们开始了隔着铁丝网的交往。每天的跑步时间和她的练琴时间刚好重合，她站在铁丝网那边，他在这边。他们聊星星、聊音乐、聊月亮的环形山和肖邦的夜曲。她给他弹琴，他把声音录在手机里，晚上戴着耳机听，听到睡着。

三个月后，秦越第一次去她学校找她。他们一起去了学校旁边的小面馆，她点了碗牛肉面，他点了碗酸辣粉。她吃面的时候会先把所有的牛肉挑出来放在碗盖上，一口一口地吃掉，然后再吃面。秦越问她为什么，她说牛肉是精华，要单独享受。

"就像弹琴一样，"她用筷子比划着说，"高潮部分要单独拎出来练，练好了整首曲子就好听了。"

秦越看着她说话时眼睛发亮的样子，觉得她比金星还亮。

他们在一起是在那年秋天。秦越在训练中受了伤，膝盖韧带拉伤，在基地的医务室里躺了一个星期。宋知意每天下午练完琴就来医务室，带一袋橘子和一本书。她坐在病床边念书给他听，声音很轻，像是怕吵到隔壁床的伤员。念到好的句子她会停下来，说"你听这句"，然后把那句话再念一遍。

秦越听着她的声音，觉得受伤也不是什么坏事。

告白是在出院那天。他站在医务室门口，拄着拐杖，看着她收拾床头柜上的橘子皮和书。她转身要走的时候，他拉住了她的袖子。

"宋知意。"

"嗯？"

"我不想只是隔着铁丝网跟你说话了。"

她愣了一下，然后低下头，耳根红了。"那你想怎样？"

"我想一直在你旁边。不走远的那种。"

宋知意没有回答。她把手里那袋橘子往他怀里一塞，低着头快步走了。走了大概十步，她停下来，回头，冲他喊了一句："那你快点好起来啊！"

秦越笑了。拄着拐杖站在医务室门口笑，笑得护士都探出头来看到底发生了什么事。

✨ 分手

他们在一切好了之后过了三年。三年里，秦越的训练越来越忙，宋知意的学校也越办越好。他们见面的频率从一周三次变成一周一次，再变成两周一次。不是不想见，是时间不允许。航天员的训练强度在最后一年翻了一倍——模拟失重、封闭舱训练、极端环境生存、心理抗压测试。秦越的手机经常被收走，一收就是十天。

但只要手机还给他，他第一件事就是给宋知意发消息。内容永远很简单："在干嘛？"她会回一段语音，弹一小段琴给他听，然后在语音末尾说一句"想你了"。他把那些语音都存了，专门建了一个文件夹，命名为"金星"。

半年前，选拔结果出来了。秦越入选了火星任务。

他拿到通知书的那天晚上，在宿舍里坐了很久。窗外是基地的探照灯，白得刺眼，把夜空照得什么星星都看不见。他想了很久，做了他这辈子最蠢的一个决定。

他跟宋知意分手了。

不是不爱。是他觉得不能让她等十年。十年太长了，长到足以改变一个人的全部人生。她会遇到更好的人，过更好的生活，不需要每天看着新闻焦虑，不需要在每次火箭发射的时候提心吊胆。他给了她自由。或者说，他以为自己给了她自由。

他跟她说的是"我们不合适"。四个字，干净利落，像是手术刀划过皮肤。他没有给她解释的机会，没有告诉她真正的原因。他甚至没有告诉她他要去火星。

宋知意那天没有哭。她只是看着他，看了很久，然后说了一句"好"。只有一个字。声音很平，像是在说一件跟自己无关的事情。然后她转身走了。秦越看着她的背影消失在楼梯的转角处，觉得胸口被什么东西掏空了一块。

🌀 二十四小时

飞船发射前的二十四小时，秦越在酒店里收拾行李。说是行李，其实也没什么好收拾的——航天服、个人物品（限重两公斤）、几封写给家人的信。他没有家人，那些信是写给同事的。写给宋知意的那封，他写了一半就撕了。

下午两点，手机响了。是宋知意的闺蜜林可。

"秦越，你是不是要去火星？"

秦越的手停住了。"你怎么知道？"

"整个基地的食堂阿姨都知道了。你瞒她瞒了半年，结果被食堂阿姨说漏嘴了。"

"……"

"她现在在来酒泉的火车上。晚上八点到。你最好在火车站等她。"

电话挂了。秦越站在酒店窗前，看着远处的戈壁滩。阳光很烈，把沙子照成了金色。他忽然觉得自己是个懦夫。不是不敢去火星的懦夫，是不敢对她说真话的懦夫。

晚上八点，秦越站在火车站的出口。这个时间只有一趟车到站，从省城开来的慢车，要走七个小时。出站的人不多，三三两两地走出来，拖着行李箱，脸上带着旅途的疲惫。

宋知意是最后一个出来的。她穿着一件卡其色的风衣，围着一条灰色的围巾，手里拎着一个帆布包，包上印着贝多芬的头像。她看到秦越的时候，脚步停了一下。然后她走过来，站到他面前，仰头看着他。

"嘿。"她说。

"嘿。"他说。

"你们基地的食堂阿姨说你们明天出发去火星。"

"嗯。"

"你跟我说的是'我们不合适'。"

"嗯。"

宋知意点了点头。她没有哭，没有质问，没有骂他。她只是把手伸进帆布包里，掏出了两杯热可可——纸杯的那种，已经有点凉了——递给他一杯。

"喝吧。火车上买的。本来是热的，七个小时凉了。"

秦越接过杯子，低头看了一眼。杯子上的水珠顺着杯壁往下流，在底部汇成一个小小的水洼。他喝了一口。还是甜的。

"宋知意。"

"嗯？"

"对不起。"

"你别跟我说对不起。"她抬起头看着他，眼睛亮亮的，"你跟我说实话。为什么不说？"

秦越沉默了很久。戈壁滩的风从火车站的缝隙里吹进来，带着沙子打在脸上，有点疼。他看着宋知意被风吹乱的头发，看着她因为坐了七小时火车而有些浮肿的眼睛，看着她手里那杯已经凉了的热可可。

"因为我怕你等。"他终于说了。"十年太长了，长到可以改变一个人的全部人生轨迹。我不想让你的人生被一个在火星上的人拖住脚步。"

宋知意听完，笑了。不是开心的笑，是那种"我终于听到了我想听的话但我还是想打你"的笑。

"秦越，你是不是觉得你特别伟大？"

"我没有——"

"你有。你觉得自己替我做了决定。你觉得十年太长，所以你替我选了分手。你觉得我不够坚强，所以你替我扛了所有的难过。你以为你在保护我，但你有没有问过我——我愿不愿意被保护？"

秦越说不出话了。

宋知意的眼泪终于掉了下来。她没有擦，任由眼泪流过脸颊，滴在那杯凉了的热可可上。"我等的不是你去不去火星。我等的是你愿不愿意让我参与你的人生。你从来都不愿意。你把我挡在外面，觉得是保护。但对我来说，那不是保护，是抛弃。"

🌧️ 最后八小时

剩下的八个小时，他们没有再吵。

他们从火车站走到了基地旁边的戈壁滩上。月光很亮，把沙子照成了银白色，像是一片冻住的海。他们并肩走着，踩在沙子上发出沙沙的声响。宋知意的风衣被风吹得鼓起来，她缩着脖子，秦越把外套脱下来披在她身上。

他们走了很久，聊了很多。聊这半年来各自的生活，聊基地食堂的红烧肉，聊她新学会的一首曲子——拉赫玛尼诺夫的第二钢琴协奏曲，很难，她练了三个月才弹顺。聊他模拟舱训练时吐了七次的糗事。聊他们第一次在铁丝网两边看到的那颗金星。

"你还记得吗？"秦越问，"那天黄昏，你在看金星。"

"记得。你说'那是金星'。我吓了一跳。"

"你弹琴给我听的时候，我觉得你比金星亮。"

宋知意低下头，踢了一脚沙子。"那你为什么不在铁丝网那边就跟我说你要去火星？"

"那时候还不知道。"

"那你可以在知道之后说。"

"……"

"你永远都是这样。什么都不说。你觉得一个人扛着就是勇敢，但有时候勇敢是把东西放下来让别人帮你扛。"

凌晨四点，他们走回了酒店。秦越明天的集合时间是七点，他需要去基地了。他站在酒店门口，看着宋知意。她站在走廊的灯光下，头发被戈壁滩的风吹得乱七八糟的，眼睛红红的，鼻尖也红红的，但嘴唇抿着，没有哭。

"我要走了。"秦越说。

"嗯。"

"十年。"

"我知道。"

"你——"

"秦越。"宋知意打断了他。她走过来，站在他面前，踮起脚，在他额头上落了一个吻。很轻，像一片羽毛。

"你去吧。但你要答应我一件事。"

"什么事？"

"到了火星，给我弹一首曲子。用你那破破的手机录音。我不挑剔，弹什么都行。"

"我不会弹琴。"

"那你唱歌。走调也行。"

秦越笑了。笑着笑着，眼眶就红了。他伸手把她拉进怀里，抱得很紧，像是要把十年的距离都压缩在这个拥抱里。她的头发蹭着他的下巴，有一股洗发水的味道——还是大学时用的那个牌子，四年了没换过。

"我会回来的。"他说。

"嗯。"

"十年。"

"我等你。"她把脸埋在他胸口，声音闷闷的，"反正我也没什么事做。"

秦越松开她，转身走向停在路边的吉普车。他走了三步，停了一下，没有回头。然后他继续走。走到车边，拉开门，坐进去。发动引擎的时候，他从后视镜里看了一眼——宋知意还站在酒店门口，风吹着她的风衣，灰色的围巾被吹得飘了起来，像是她在挥手。

他没有看到她哭。

但那天凌晨五点，戈壁滩的某个角落，有人在荒漠里支起了一架电子琴。宋知意坐在琴凳上，手指落在琴键上，弹了一首秦越手机文件夹里存了三年的那首曲子——他录的铁丝网那边的钢琴声。她弹得很轻，怕吵醒戈壁滩上的风。但风还是听到了。它把琴声卷起来，带着它飞过了白杨树林，飞过了铁丝网，飞过了基地的围墙，落在了正在换航天服的秦越的耳朵里。

他听到了。隔着墙壁、隔着防护服、隔着即将到来的八个月太空旅途，他听到了那个旋律。

那是金星。那是宋知意。那是他在火星上十年的所有理由。
