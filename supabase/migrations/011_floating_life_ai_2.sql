散伙饭是在食堂吃的。培训班三十多个人围了三桌，菜比平时丰盛了一些，还有一瓶从地球上带来的真正的酒——不是合成酒精，是用粮食酿的。大家轮流站起来说几句，有的说得豪迈，有的说得哽咽。轮到ta的时候，ta端着杯子站起来，环顾了一桌人，说："希望以后还能再见到你们所有人。"然后ta看了你一眼。就是那一眼。那一眼里有很多东西，但你来不及细看就移开了。你低头喝了一口杯里的酒，酒很辣，从喉咙一直烧到胃里。但你觉得烧得不够。你希望那把火能烧掉你胸口堵着的那团东西，但烧不掉。

吃完饭大家各自散了。你回到宿舍收拾行李，ta在隔壁也在收拾。你听到隔壁传来箱子拉链的声音，然后是沉默，然后又是收拾东西的声音。你在自己的房间里站了很久，看着窗外漆黑的太空。你想过去敲门。你走到了门口，手都抬起来了。但你又放下了。你告诉自己，明天再说。明天送别的时候再说。明天一定说。

第二天你没有说。因为ta提前走了。ta的船凌晨四点就出发了，你醒来的时候ta的宿舍已经空了。床头柜上留了一张纸条，写着"保重"两个字。你拿着那张纸条站在空荡荡的房间里，站了很久。窗外什么都没有，只有星星。那么多星星，但你一颗都看不清，因为你的眼睛模糊了。

你后来无数次回想那个晚上。你站在门口、手抬起来又放下的那个晚上。你不知道如果当时你敲了那扇门会发生什么。也许你会说出来。也许ta会说"我也是"。也许你们会拥抱，会流泪，会在走廊的蓝光下站到天亮。但这些都是也许。现实是你没有敲那扇门。你没有说那些话。你把想说的话留给了"明天"，而"明天"没有等你。

🌧️ 失联

你们一开始还保持着联系。信号通过星际中继站传递，从你的探测器到ta的船队，中间要经过七个中继节点，单程延迟大约三个标准月。也就是说你发一条消息，要等半年才能收到回复。但你不在乎。你每个星期都给ta写一封长信，讲你最近的生活、探测器的新发现、舷窗外的景色。你把那些在培训时没有说出口的话，一点一点地写在信里。当然，你没有直接说"我喜欢你"。你只是写了很多琐碎的事情——今天食堂出了一道新菜，味道居然还不错；监听信号的时候听到了一段很像摇篮曲的电波；空间站外面有一颗彗星飞过，尾巴拖着绿色的光，很漂亮。你觉得这些琐碎的事情里藏着你的心意，你觉得ta应该能读懂。

ta的回信一开始也是每个星期一封。ta跟你讲工程船队的生活，讲半人马座α星域的景色——那里的星云是紫色的，像是有人把一桶颜料泼在了天上。ta说你一定要来看看。你说好，等有机会一定去看。你们这样通信了两年。两年里你攒了一百多封ta的信，你把它们存在一个专门的文件夹里，每晚睡前都会随机打开一封重读。

后来ta的回信开始变少了。从每周一封变成两周一封，再变成一个月一封。你安慰自己说是因为距离越来越远了，信号延迟在增加。你知道这是正常的技术原因。但你还是害怕。你怕的不是技术原因，你怕的是另一种可能——ta不想回了。或者更糟，ta出了什么事。

最后一次收到ta的回信是在两年前的某一天。那封信很短，只有几行字。ta说船队要进入一个信号盲区了，可能很长一段时间都没法联系。ta说不要担心。ta说等出来了就给你写信。信的最后一句是"保重"。和离开培训那天留在床头柜上的纸条一样的两个字。

然后就没有了。

你等了三个月，没有回信。等了半年，没有回信。等了一年，没有回信。你发了无数条消息，全都石沉大海。你查了第十二工程船队的航线——他们确实经过了一片信号盲区，但按照正常速度，最多六个月就该出来了。六个月早就过去了。你开始查更深层的信息。你翻遍了银河联邦的公开数据库，没有找到第十二工程船队出了什么事。你问了你的上级，上级说那片星域最近确实有一些不明信号干扰，但不至于导致整支船队失联。你托关系查了联邦军方的内部通报，里面只提到了"半人马座α星域出现异常能量波动，建议途经船只注意规避"。

异常能量波动。这五个字像一块石头砸在你心上。你不知道这意味着什么。也许什么都不是，也许是一场灾难。你不知道。你唯一知道的是你已经一年没有收到ta的消息了。你每天上班的时候都盯着信号监听台，盼着屏幕上跳出一条来自ta的消息。但屏幕上永远只有噪音，无穷无尽的噪音，像大海的浪声，永不停歇，也永远说不出你想听到的那个声音。

你在那些失眠的夜晚里做了很多事情。你把ta写给你的所有信都打印了出来，按时间顺序排列在桌上。你一封一封地读。读到某些句子的时候你会停下来，盯着那行字看很久。有一封信里ta说"今天看到一颗特别亮的星星，我给它取了你的名字"。你不知道ta取的是哪颗星。你也不知道那颗星现在还在不在。宇宙中的星星每天都在变，有的在燃烧，有的在熄灭。你想也许那颗星已经灭了。也许那些光已经在几百万年前就出发了，只是在到达你眼睛的时候刚好灭掉了。就像ta一样——也许那些温暖的话已经在很久以前就说出来了，只是在到达你心里的时候，说那些话的人已经不在了。

🕯️ 两百年的漂流

你写完那封信之后，把它封存在了一个金属数据片里，贴上了你最珍视的一张照片——培训结业时你们的合影。你把它装进了一个微型漂流瓶。那是一种专门用于深空投放的容器，外壳由合金制成，能抵御宇宙射线和小型碎片的撞击。你在瓶身上刻了一行字："致那个来不及说出口的人。"

你把漂流瓶交给了投放部门。投放员问你要设置什么样的航线。你说不知道，随便吧。他想了想说，可以把它编入第七探测器的次级发射程序，随着探测器的外抛物线轨道向外扩散。你说好。他没有再问。也许他看出来了你不想多说。

漂流瓶被弹出探测器的那一刻，你在通信室里看着屏幕上的发射确认信号。一个小小的亮点从探测器的轨迹上分叉出去，朝着另一个方向飞走了。你知道那个亮点很快就会消失在太空中，小到任何仪器都探测不到。它就像一滴水被倒进了大海。但那滴水里装着你所有没有说出口的话。

漂流瓶在太空中飞行。第一年，它经过了小行星带。成千上万的岩石碎片从它身边掠过，有的只有拳头大小，有的比一栋楼还大。漂流瓶很小，小到几乎没有被击中的可能。它在碎片的缝隙中穿梭，像一个迷路的旅行者在密林中穿行。有一块较大的小行星从它附近经过，引力微微拉扯了它的轨迹。它偏了一点，但继续飞。它不着急。它有的是时间。

第十七年，它飞过了一颗红矮星。红矮星的光很暗，表面温度只有太阳的三分之一，但它已经燃烧了上百亿年，还会继续燃烧上千亿年。漂流瓶从红矮星的引力边缘擦过，被轻轻甩了一个弯，加速了一些。在那一刻如果有人能看到漂流瓶内部的话，会看到数据片上的信息还在——那些字一个也没有丢。

第五十三年，它进入了一片星云。星云是淡蓝色的，由气体和尘埃组成，绵延几十光年。漂流瓶在星云中飞行了三十多年，周围只有淡淡的荧光和无穷无尽的寂静。它像一只萤火虫飞进了大雾。雾很大，路很长，但它不迷路，因为它本来就没有目的地。

第九十八年，它经过了两个黑洞的引力交界处。两个黑洞正在缓慢地互相吞噬，它们之间的时空被扭曲成奇怪的形状，光都被拉成了弧线。漂流瓶差点被其中一个黑洞捕获。它被引力拉扯着旋转了好几圈，但最终因为体积太小、质量太轻，被甩了出来。它像是被弹弓弹出去一样，加速到了前所未有的高速。金属外壳上出现了一些微小的凹痕，那是被引力潮汐力撕扯后留下的痕迹。但瓶子没有碎。里面的信还在。

第一百三十四年，它经过了一颗正在死去的恒星。那颗恒星已经膨胀成了一颗红巨星，表面几乎吞噬了它的行星。漂流瓶从红巨星的日冕层上方飞过，被高温等离子体灼烧了几秒钟。外壳的温度骤然升高，表面的合金氧化了一层。但它没有融化。它在火焰中飞了过去，带着一身焦痕继续飞行。就像有些话，被烧过、被烤过，但内核还在。

第一百七十八年，它进入了一片几乎什么都没有的区域。没有星星，没有星云，没有尘埃，什么都没有。只有黑。纯粹的黑。如果漂流瓶有意识的话，它可能会觉得孤独。但漂流瓶没有意识。它只是一个金属容器，里面装着一封信和一张照片。它不知道自己已经飞了一百七十八年，不知道自己已经穿越了大半个银河系，不知道写信的人和收信的人大概都已经不在了。它只是飞。在黑暗中飞。在寂静中飞。在什么都看不见的地方飞。因为它不知道自己该停下来。它只知道飞。

🎯 被捕获

第二百零一年的某一天，漂流瓶进入了赫拉文明的领空。

赫拉文明是一个比人类文明早发展了几万年的种族。他们的科技水平远超人类，已经实现了恒星级能源利用和跨星系通讯。他们有一种设备叫做"全频段信噪分离器"，能够在宇宙背景辐射的噪音中捕捉到任何人工信号。漂流瓶虽然没有发射信号，但它的金属外壳与宇宙射线相互作用时会产生一种极其微弱的二次辐射。赫拉人就是捕捉到了这种辐射。

一个叫瑟尔的赫拉天体物理学家在例行巡天观测中发现了漂流瓶。她用远程操控设备把它拉进了空间站的实验室。瓶子被放在一张白色的分析台上，灯光打上去，外壳上的刻痕清晰可见。那行用人类文字刻下的话，赫拉人读不懂。但他们的语言解析系统花了不到一个小时就破译了人类的文字编码。

瑟尔打开了漂流瓶，取出了数据片。她把数据片接入了解码器。屏幕上开始显示内容——先是那张照片。照片上有两个人，站在一面巨大的舷窗前，背景是无尽的星空。照片上的两个人都在笑，但那种笑不是大笑，是嘴角微微翘起来的那种，带着一点羞涩。瑟尔看着这张照片，觉得人类是一种很奇怪的生物——他们的表情系统如此简单，只有嘴角上扬或下垂、眼睛眯起或睁大这么几种组合，但就是这几种组合，能够传递出如此丰富的情感。

然后她读到了信的内容。

瑟尔读过很多来自不同文明的信号。有的信号是数学公式，有的是星际坐标，有的是威胁或者求救。但她从来没有读过这样的信号——它不是公式，不是坐标，不是威胁，不是求救。它只是一封信。一封写给某个特定的人的信。信里没有讲述任何伟大的发现，没有传递任何先进的技术，没有提出任何宇宙的终极问题。它只是说了一个人对另一个人的想念。

信里写了什么呢？写了很多小事。写了食堂里一起吃饭的下午，写了翘课在观察窗前看比邻星落下的傍晚，写了走廊里蓝色灯光下的那张侧脸，写了无数次想说又咽回去的那些话。信里有一段话瑟尔读了三遍："我不知道你现在在哪里。我不知道你还能不能收到这封信。我甚至不知道你还记不记得我。但我还是想写。因为这些话如果我再不说出来，我怕我会带着它们走完一辈子。我不想那样。我不想到了最后，连一句'我喜欢你'都没有说出口。"

瑟尔读完之后沉默了很久。她不懂人类的语言，但她懂这封信里的情感。因为赫拉人也会想念一个人。赫拉人也有想说却没有说出口的话。赫拉人也会在深夜里想起某个人的侧脸，然后睡不着。宇宙中所有的文明千差万别——有的用声波交流，有的用光信号，有的用引力波。但所有文明都有一种共同的语言，那就是"我想你"。这种语言不需要翻译。

瑟尔把这封信的翻译提交给了赫拉中央档案馆。档案馆的分类系统不知道该把它归到哪一类——它不是科学文献，不是历史记录，不是艺术作品。最后他们为它创建了一个新的分类标签，叫做"跨文明情感文献"。这是赫拉文明档案馆里的第一个此类条目。

消息传开后，很多赫拉人都读了这封信。他们觉得这封信很珍贵。不是因为它的文学价值，而是因为它的真诚。在宇宙中，真诚是最稀缺的东西。大部分文明在发展过程中都会学会伪装——伪装强大、伪装理性、伪装不需要任何人。但这封信没有任何伪装。它只是一个孤独的人，对着虚空说了一句"我想你"。

⏳ ta收到了

事情到这里并没有结束。因为赫拉文明在翻译完这封信之后，做了一个决定——他们要找到信的收件人。

这几乎是不可能的事。信上没有写收件人的名字，没有写编号，没有任何可以追踪的信息。但瑟尔注意到数据片里除了那封信和一张照片之外，还嵌入了一段很微弱的元数据。元数据是探测器通信系统的自动记录——里面包含了写信人的工号、写信的日期、以及探测器的编号。赫拉人通过这些信息，逆向追踪到了银河联邦第七星际探测器的航线记录。

他们在联邦的公开数据库中查到了探测器的船员名单。又通过船员名单交叉比对，找到了通信部门的人员记录。记录显示在漂流瓶被投放的那个时间段，通信部门只有一个工作人员——就是你。但他们要找的不是你。他们要找的是你写信的对象。

瑟尔又仔细读了那封信。信里提到了一些线索——"工程培训班"、"比邻星联盟星站二号"、"第十二工程船队"。赫拉人搜索了联邦数据库中第十二工程船队的人员名单，找到了在比邻星联盟星站二号培训过的工程师。名单上有四十七个人。瑟尔让系统逐一分析了信中描述的特征——喜欢坐在食堂的某个位置、来自一颗只有一座城市的小行星、说"至少多了"那句话。系统花了三天时间，把范围缩小到了一个人。

那个人在两百年前就已经不在了。第十二工程船队在进入半人马座α星域后遭遇了一场亚空间风暴，船队散了。大部分船员被救了回来，但有一艘小型的工程艇失联了。那个工程师就在那艘工程艇上。联邦的搜救行动持续了三个月，最终在一片残骸中找到了工程艇的碎片。没有找到遗体——太空中的遗体很快就会变成分子，散布在几百万公里的范围内。官方通报写的是"确认遇难"。

但赫拉人的数据库里有更详细的信息。那场亚空间风暴在空间中撕开了一道裂缝。裂缝存在了大约十七秒。在这十七秒里，那艘工程艇被吸了进去。残骸是在裂缝外面找到的，但那只是工程艇被撕裂时甩出来的一部分碎片。工程艇的主体——包括里面的人——被裂缝吞噬了。去向不明。

赫拉人的科学家研究了那道裂缝的性质。他们发现它连接的不是一个固定的地点，而是一个时间。裂缝的另一端是一百九十七年后的赫拉文明的领空。也就是说，那艘工程艇穿越了一百九十七年的时间，出现在了赫拉文明的家门口。

赫拉人在他们的档案中查到了那艘工程艇。工程艇在被裂缝吐出来之后，残骸漂浮在赫拉领空中。赫拉人截获了它，救出了里面唯一一个幸存者。那个幸存者是一个人类工程师——来自银河联邦第十二工程船队。ta在赫拉人的医疗中心昏迷了三个月。醒来之后发现自己身处一个完全陌生的文明，周围全是长相奇怪的外星生物，没有一个认识的人。

ta在赫拉文明生活了将近两百年。赫拉人的医疗技术可以极大地延长人类的寿命——他们改造了ta的基因，修复了ta的细胞端粒，让ta的衰老速度降低到了正常人类的五十分之一。ta学习了赫拉人的语言，在赫拉人的研究机构里工作，帮助赫拉人理解人类文明的科技和文化。ta适应了新的生活，交了新的朋友，甚至在赫拉人的艺术圈里有了一些名气——ta把人类的绘画技法教给了赫拉人，赫拉人觉得人类用颜料在平面上创造三维错觉的技术非常奇妙。

