这次的拥抱和那个雨夜不一样。雨夜的拥抱是温柔的、平静的、水到渠成的。而这一次的拥抱是狼狈的、用力的、带着颤抖的，像两个差点被洪水冲走的人终于抓住了彼此。

你站在镜子的这一边，泪水不知不觉流了满脸。

不是因为感动。而是因为你终于看到了另一种可能。原来吵架之后，是可以有人先低头的。原来愤怒到达极限之后，是可以被心疼取代的。原来"我们都冷静一下"这句话之后，不一定要跟着三年的沉默。

你蹲在镜子前面，用袖子擦了擦脸，看着镜中那两个紧紧抱在一起的人，心里有一个声音说：如果我们当时也有一个人先走过去，是不是一切都会不一样？

但"如果"这个词，是这个世界上最残忍的词。

## 第五章：你试过沟通

又过了几天，你做了一个以前从没做过的尝试。

你试着和镜子互动。

你站在镜子前面，伸出手，指尖贴在镜面上。镜面依然是凉的，像一层薄薄的冰。镜中的另一个你正在阳台上浇花，他在给一盆绿萝浇水，阳光很好，他的侧脸被镀上了一层暖光。

你开口喊了他的名字。

那个名字你在心里念过无数次，但已经很久没有发出声音了。三个字从嘴唇间滑出来的时候，你自己都被吓了一跳——声音沙哑、生涩，像是一把锁了太久的钥匙突然被拧动。

镜中的他没有任何反应。他继续浇花，哼着歌，偶尔低头看看叶片上的水珠。

你又喊了一遍，这次更大声。声音在空荡荡的店铺里回荡，连柜台后面的老人都抬起了头。但镜中的世界像被一堵透明的墙隔绝了，你的声音传不过去。

你开始用力拍打镜面。一下、两下、三下。手掌拍在玻璃上发出闷响，震得货架上的小物件微微颤抖。镜中的画面纹丝不动，另一个你放下浇水壶，走到他身边，从背后环住了他的腰，下巴搁在他的肩膀上。

你停止了拍打，手掌贴在镜面上，五指张开。镜面那头，另一个你也恰好抬起了手，手掌贴在了镜面的另一侧——但那只是在伸手去触碰他的脸。

你看着自己的手掌和他的手掌隔着镜面重合在一起，忽然觉得自己很可笑。

你在吃醋。你在吃另一个自己的醋。

接下来的几天，你试了各种方法。你在镜子前跳舞，试图引起注意；你把脸贴近镜面，用力做出夸张的表情；你甚至带来了纸条，写着"你能看到我吗"，贴在镜面上。但镜中的世界照常运转，另一个你和他在过着你们的日子，做饭、散步、看电影、吵架、和好、拥抱、亲吻。他们对镜子这一边的你一无所知。

你像是站在鱼缸外面的猫，看着里面另一个世界的自己游来游去，热热闹闹，而你只能隔着玻璃，无声地张望。

有一天下雨，你没带伞，淋着雨跑去了"拾光阁"。你站在镜子前面，浑身湿透，头发贴在额头上，水珠顺着下巴滴到地板上。镜中的画面是一片阳光明媚的午后，另一个你和他正在午睡，两个人侧躺着面对面，呼吸均匀，手牵着手。

你看着那个画面，忽然感到一种前所未有的疲惫。不是身体的疲惫，是灵魂深处的倦意。你对着镜子轻声说了一句话。

"我好想你们。"

虽然你知道，那个"你们"里面的另一个你，其实就是你自己。你缺少的不是另一个你，而是那个他。那个在你的人生里缺席了三年、在另一个人生里始终都在的人。

