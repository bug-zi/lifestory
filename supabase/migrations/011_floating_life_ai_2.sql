"嗯？"她应了一声。你能听出来她有一点意外。她大概在想你怎么突然这么正式。

"你说，我们第一次见面是在哪里？"你问。你在测试自己。你今天白天刚在笔记本上写过这件事，你记得，你知道答案。但你还是想问。你想从她嘴里听到这个答案，然后用她的声音来加固你正在碎裂的记忆。

"图书馆啊，三楼，靠窗。你忘了？"她的语气里有一点笑意。"你那时候天天坐在那里装学霸，其实偷偷在看我。"

"我没有偷偷看你，"你说。你笑了。你不知道你还能笑几次关于她的事情。

"你骗人，"她说。"你后来跟我表白的时候自己说的，你说你每天偷偷看我，看了整整两个星期才敢跟我说话。"

"是吗？我说过这种话？"你其实记得。你当然记得。你只是想让她再说一遍。

"你说的。你说'沈知意，我喜欢你，从第一次在图书馆看到你的时候就开始了'。你说这话的时候脸都红了。"

你没说话。你把手机从耳朵旁边拿开了一点，用另一只手捂住了脸。你不想让她听到你的呼吸变得不平稳。你深吸了一口气，把手机重新贴回耳朵上。

"我还在吗？"她问。"你怎么不说话了？"

"在，"你说。"我在。我就是想听听你的声音。"

电话那头安静了一会儿。你能听到她翻身的声音，被子窸窸窣窣地响。她说："你是不是有什么事？"

"没有，"你说。"就是想你了。"

她又沉默了一会儿。然后她说了一句让你几乎绷不住的话："你是不是在哭？"

"没有，"你说。但你的声音已经变了。你自己能听出来。你的鼻音很重，像是感冒了。

"你在哭，"她很确定地说。"你每次哭的时候都会否认。你忘了？上次你姥爷住院的时候你也是这样，打完电话说没事，结果我去你那儿一看，你眼睛肿得跟核桃似的。"

你没说话。她在电话那头叹了一口气，然后说："你要是睡不着，我就陪你聊聊。反正明天周末，不用早起。"

"好，"你说。你的声音很小，小到你自己都快听不见了。

"那你跟我说说，你今天干嘛了？"她问。

你不知道该怎么回答。你今天去了一趟医院，知道了你会忘记她。你回到家写了十七页关于她的笔记。你发现你已经开始忘记一些细节了。但你不能告诉她。你不想让她担心。你不想让她害怕。你更不想让她知道，她即将从你的世界里彻底消失，而你什么都做不了。

"没干嘛，"你说。"就是上班，加班，回家。"

"你骗人，"她又说。"你今天明明没加班。我下午六点给你发消息你都没回，你不是加班的话为什么不回我？"

你不知道该怎么接了。你停顿了太久。她好像感觉到了什么，语气变了，变得很轻很轻，像是怕碰碎什么："你到底怎么了？你说嘛，我又不会笑话你。"

"我没事，"你说。你用力地吸了一下鼻子。"我就是做了一个梦，梦见你不认识我了。"

她笑了。她的笑声在深夜里特别清亮，像是一颗小石子投进了静水潭里。"怎么会？我怎么会不认识你？你别做这种奇怪的梦。"

你没有说话。你把这句话在心里翻来覆去地想了很久——"我怎么会不认识你？"她说的是她不认识你。但很快，就会变成你不认识她。你不知道这两种方向的不认识，哪一种更残忍。

你们又聊了一会儿。她跟你说她今天买了一束花，白色的满天星，插在书桌上的玻璃瓶里。她跟你说她明天打算去逛书店，想买一本新出的小说。她跟你说她室友今天做了一锅排骨汤，非要她尝，她尝了一口觉得太咸了但不好意思说。你听着她说这些鸡毛蒜皮的小事，觉得这是你听过的最好的故事。每一个字你都想记住。每一个细节你都想刻在骨头里。

后来她说她困了，声音越来越小。你说那你睡吧。她嗯了一声，又说："你也是，早点睡。别想太多。明天给我打电话。"

"好，"你说。"明天给你打电话。"

"晚安。"

"晚安。"

电话挂了。你坐在黑暗的客厅里，手机屏幕的微光照着你的脸。你看到手机屏幕上显示通话时长：四十七分钟。你忽然想，如果你的人生只剩最后四十七分钟，你大概也愿意全部花在和她打电话上。

你把手机放在胸口，仰面躺在沙发上。天花板上有一道裂缝，从卧室门的方向一直延伸到窗户。你盯着那道裂缝看，觉得它很像你此刻的心情——一道不知道什么时候出现的裂痕，一直在扩大，但你没办法修补。你闭上眼睛。你不知道你明天醒来还会记得多少。你只知道，此刻，在凌晨两点钟的黑暗里，你还记得她。你记得她的名字、她的样子、她的声音、她的习惯。你记得关于她的一切。你还记得。此刻。

烛️ 第二天清晨

你是被阳光叫醒的。你睁开眼睛的时候，阳光正从窗帘的缝隙里照进来，打在你的脸上，暖暖的。你躺在沙发上，脖子很酸，后背很僵。你花了几秒钟才想起来你为什么睡在沙发上。然后你想起来了。你坐起来，伸手去摸茶几上的笔记本。笔记本还在，蓝色的封面在阳光下显得格外安静。你翻开第一页——"关于她的一切"。

你看着那几个字，心里忽然咯噔了一下。你知道这几个字是你写的。你知道这本笔记本里写了一个对你很重要的人。但你的第一反应不是"她是谁"，而是"她是谁来着"。这个念头只持续了不到一秒钟，因为你还记得。你还记得她的名字叫沈知意。你还记得你们在图书馆认识。你还记得她怕打雷、喜欢草莓蛋糕、手在冬天会很凉。但你知道这些记忆的质感变了。昨天你想起来这些事情的时候，它们是带着颜色、温度和声音的——你能看到画面，能感受到温度，能听到她的声音。今天你想起来的时候，它们变成了文字，像是你自己写在脑子里的笔记。你在读自己的笔记，而不是在回忆。

你打开手机，看了看时间。早上七点二十三分。距离你在诊室里听到那个诊断结果，已经过去了大约十八个小时。你还剩六个小时左右。也许更少。

你起身去洗手间洗脸。冷水泼在脸上的时候，你抬头看了一眼镜子。镜子里的你脸色很差，眼睛下面有很重的黑眼圈，嘴唇干裂，头发乱糟糟的。你想起来她总是说你不好好照顾自己。她说："你就不能早点睡吗？你就不能多喝点水吗？你就不能少吃点外卖吗？"你每次都说好，每次都不改。你想起来这些话的时候，忽然发现自己已经在用"想"这个字了。不是"听到"，不是"记着"，是"想"。你在努力地去把那些话从记忆的仓库里找出来。昨天它们还摆在最显眼的位置上，今天已经被推到了角落里。

你走进厨房，给自己倒了一杯水。你站在厨房里喝水的时候，目光扫过冰箱门上贴着的照片。那是一张拍立得照片，你和她站在一棵大树下，她搂着你的胳膊，笑得眼睛都快看不见了。你看着那张照片，忽然想不起那棵树是什么树了。是在哪里拍的？公园？校园？某个旅游景点？你仔细看了看照片的背景，看到了一条长椅和一个花坛。你觉得你应该认识这个地方，但它就是不肯浮上来。

你放下水杯，拿出手机，翻到那张照片的原图。你打开图片信息，看到了拍摄日期和地点。地点显示的是一个公园的名字。你看到那个名字，想起来了。是你们交往三个月的时候，她拉着你去的那个公园。她说想看枫叶。那时候是十一月，枫叶红了一半，黄了一半，阳光一照，整条路像是铺了一层彩色的地毯。她拉着你走在那条路上，一边走一边说："你看你看，那棵树好漂亮，帮我拍照。"你拍了。你拍了好多张。但你现在已经不太记得她拍照时的表情了。

你开始害怕了。不是昨天那种抽象的害怕——那种"我知道我会忘记"的害怕。是一种更具体的、更尖锐的害怕——你正在亲眼看着自己的记忆被擦掉。就像一面墙上贴满了照片，有人在你面前一张一张地揭下来。你伸手去拦，但你的手穿过了那些照片，什么都抓不住。

你决定出门。你不能再待在家里了。你待在家里只会盯着那些照片和笔记本发呆，然后在发呆的过程中发现又忘记了什么。你需要去做一件事——你需要去见她。你需要拿着这本笔记本，走到她面前，告诉她所有的事情。你不确定这样做有没有意义。也许你明天醒来，连这本笔记本上写的字都不认识了。也许你明天醒来，看到她的脸，会觉得面前站着的是一个陌生人。但你今天还认识她。你今天还来得及。

你换了衣服，把笔记本塞进背包里。你在门口换鞋的时候停了一下，回头看了一眼客厅。你看到茶几上的马克杯、沙发上的毯子、书架上的书。你看到冰箱门上那张拍立得。你忽然很想说一句什么，但你不知道该说什么。你最后什么也没说，拉开门走了出去。

早上的空气很清新，带着一股青草和泥土的味道。你走在路上，看到路边的早餐摊正在冒着热气，有人在排队买豆浆和油条。你想到她喜欢吃豆浆配油条。她每次吃油条都喜欢蘸很多糖，你说你不怕胖吗，她说"人生苦短，糖分自由"。你想到这句话的时候笑了一下。然后你意识到，你刚才想到的不是她的脸，而是她说的话。你正在从"画面记忆"退化到"文字记忆"。她的样子在你脑子里正在变得越来越模糊。

你加快了脚步。你知道时间不多了。

🎯 见面

你站在她家楼下的时候，手里攥着那本蓝色的笔记本。你的手心在出汗，笔记本的封面被你捏得有点变形。你在楼下站了五分钟，没有上去。你不知道该怎么和她说。你甚至在想，你要不要就这样算了，不上去了，不说了，让她继续做那个被你爱着的人，而不是做一个被告知"我要忘记你了"的人。

但你还是上去了。你按了门铃。你听到屋里传来脚步声，然后门开了。她站在门口，穿着一件灰色的卫衣，头发扎了一个松松垮垮的马尾，脸上没有化妆。她看到你，先是愣了一下，然后笑了。她笑起来的时候，你看到她左边脸颊上那个很浅的酒窝。你的心狠狠地揪了一下。你还看得见这个酒窝。你还认识这个笑容。你还记得这是她的脸。

"你怎么来了？"她侧身让你进门。"你昨天半夜给我打电话，今天一大早又跑过来，你到底怎么了？"

你走进她的客厅，在沙发上坐下来。你把背包放在脚边，没有马上拿出笔记本。你看着她在厨房里给你倒水。她走到你面前，把水杯递给你，然后在你旁边坐下来。她歪着头看你，表情有点疑惑，又有点担心。

"你脸色好差，"她说。她伸手摸了摸你的额头。"没发烧。你到底怎么了？你说话啊。"

你低下头，看着手里的水杯。杯子里的水在微微晃动，因为你的手在抖。你深吸了一口气，然后从背包里拿出了那本蓝色的笔记本。你把笔记本放在膝盖上，翻开第一页。

"知意，"你说。你叫她名字的时候，声音有一点沙哑。"我有件事要跟你说。"

她看到你认真的表情，脸上的笑容慢慢收了起来。她坐直了身体，看着你，等着你说下去。

"我昨天去医院了，"你说。"医生说我得了一种病。"你停了一下。你不知道怎么用一种不吓人的方式说下去。你发现根本不存在这种方式。

"什么病？"她的声音紧了一下。

"一种……记忆方面的病，"你说。你低着头，不敢看她的眼睛。"我的记忆会退化。关于你的记忆。医生说大概二十四小时左右，所有关于你的记忆都会消失。我昨天下午确诊的。现在大概还剩……几个小时。"

她没有说话。你能感觉到她在看着你。你能感觉到她的目光钉在你的脸上，像两根很细的针。你抬起头，看到了她的表情。她没有哭，也没有惊叫。她的嘴唇微微张开，像是要说什么，但什么也没说出来。她的眼睛里有一种你从来没见过的东西——不是悲伤，不是恐惧，而是一种比这些更深的东西。那种东西像是深渊，你在那双眼睛里看到了一个正在坍塌的世界。

"你在说什么？"她终于开口了。她的声音很轻，轻到几乎是从气音里挤出来的。"你说你会……忘了我？"

"嗯，"你说。你的鼻子一酸，但你忍住了。你不能哭。你今天不能哭。你还有事情要做。

"所以这个本子……"她看着你膝盖上的笔记本。

"这是我昨天晚上写的，"你说。"关于你的所有事情。我害怕我忘了，所以都写下来了。我想……我想当着你的面读给你听。"

她的眼圈红了。她咬着下嘴唇，点了点头。你翻开笔记本，开始读。

"第一条，"你念道。"她的名字叫沈知意。我们第一次见面是在大学图书馆的三楼，靠窗的位置。那天外面有一排银杏树，叶子黄了大半。她坐在对面，穿着一件米白色的针织衫，耳朵里塞着耳机，看一本很厚的书。她看书的时候会转笔，转得很好看。我看了她两个星期才敢和她说话。"

你念完这一段，抬起头看她。她的眼泪已经掉下来了，一颗一颗地砸在她交叉放在膝盖上的手指上。她在无声地哭。你继续念。

"第二条。她喜欢在雨天听歌。她说雨天听歌有一种被世界包裹住的感觉。有一次下暴雨，她给我塞了一只耳机，我听到了一首很安静的歌。那首歌的名字我不记得了，但那种感觉我记得。"

你念到这里停了一下。因为你忽然不确定了——你还记得那种感觉吗？你看着自己写的"那种感觉我记得"，觉得这句话正在变成一个谎言。那种感觉在你念出这行字的时候，已经不是"记得"了，而是"知道"。你知道那种感觉曾经存在过，但你已经感受不到了。

你继续念。你念她怕打雷。你念她喜欢草莓蛋糕。你念她冬天手会很凉。你念她笑的时候有一个酒窝。你念她的手指很细，无名指上有一个小小的疤痕。你一条一条地念，每念一条，就像是在做一次确认——是的，你写过这个，是的，这是关于她的事情。但你念到第八条的时候，你发现了一条你自己都不太理解的内容。

第八条写的是："她有一条红色的围巾，是我在她生日的时候送的。她每次围那条围巾都会说我眼光差，但每天都围。"你看着这行字，努力回忆这条围巾的样子。你记得她有一条红色的围巾。你记得她说你的眼光差。但你不记得送围巾时的场景了。你是在哪里买的？她收到的时候是什么表情？这些画面都不见了。纸上只剩下文字，文字的背后是一片空白。

你念完了全部十七页。你念了很久，中间停了好几次。不是因为嗓子疼，而是因为你念到某些地方的时候，说不出话来了。你念到最后一条的时候，手在发抖。最后一条写的是："她最后跟我说的一句话是'明天给我打电话'。那是昨天凌晨两点钟，我们在电话里说的。我说好。"

你合上了笔记本。客厅里很安静。窗外有鸟叫声，很清脆，很欢快，和这个房间里的气氛完全不搭。她坐在你旁边，没有说话。她的脸上全是泪痕，但她没有发出声音。她只是看着你，用一种你无法描述的眼神看着你。那种眼神里有很多东西，但最多的那一种，是"不愿意相信"。

"那现在呢？"她开口了，声音哑得不像她的声音。"你现在还记得我吗？"

"记得，"你说。你看着她的脸，认认真真地看了一遍。你想把这张脸印在脑子里，印在每一个细胞里。"我记得你。"

"那你说的那些你已经开始忘掉的……"她吸了一下鼻子。"那些你还记得吗？"

你想了想，诚实地回答："有些还记得，有些只记得文字，不记得画面了。就像……我知道有这么一回事，但那件事已经没有颜色了。"

她低下头，看着自己的手。然后她做了一件事——她伸出左手，握住了你的右手。她的手是温热的，不像你笔记里写的"冬天手会很凉"。也许是因为现在是五月。也许是因为她刚才一直在用力地攥着拳头。她的手指很细，你感受到了。你的手指碰到了她无名指上的那个小小的疤痕，你忽然觉得那道疤痕比什么都真实。

"你看着我，"她说。她抬起头，眼睛红红的，但目光很坚定。"你好好看着我。你现在还能看到我的脸对不对？那你看着。你就一直看着。"

