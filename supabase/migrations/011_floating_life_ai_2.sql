🌸 那面镜子

叶辞是在搬进老公寓的第三天发现那面镜子不对劲的。

镜子嵌在卫生间的墙壁里，木质边框已经发黑了，玻璃表面有一层模糊的水雾，像是经年累月的水汽浸进了镜面深处。叶辞起初没在意——老房子嘛，什么都旧。他把牙刷杯子放在洗手台上，对着镜子刮胡子，镜子里的人也刮胡子。一切正常。

直到那天晚上。

他加完班回到家，已经凌晨一点了。洗完澡，他赤着上半身站在镜子前面擦头发。镜子里的自己也在擦头发。但镜子里的背景不对。

他的卫生间是白色的瓷砖，小而逼仄，只有一个浴帘和一排挂钩。但镜子里的背景是一间卧室——不是他的卧室。卧室很大，落地窗外是城市的夜景，灯光密密麻麻的，像是有人在黑布上撒了一把碎钻。床边有一盏落地灯，灯罩是暖黄色的，光线柔软得像蜂蜜。

镜子里的叶辞站在一个衣柜前，穿着一件灰色T恤，手里拿着一件女式的米白色针织衫，正在叠。他把针织衫叠好，放进衣柜的某一格，然后轻轻关上柜门。动作很温柔，像是在对待一件很珍贵的东西。

叶辞愣住了。他低头看了看自己——手里只有一条毛巾，没有针织衫。他再看镜子，镜子里的画面已经变了，变回了正常的倒影：白色的瓷砖，逼仄的空间，赤裸上身的自己。

他以为自己太累了，出现了幻觉。

🌙 第二次

但第二天晚上，镜子里的画面又出现了。

这一次更清晰。镜子里的叶辞坐在一张沙发上，手里拿着一本书，腿上趴着一只橘色的猫。猫很胖，蜷成一团，呼噜声很响——叶辞能听到那声音，像是从镜子深处传来的，隔了一层水。沙发旁边有一张茶几，上面放着两杯茶。一杯是龙井——叶辞认得那个玻璃杯，因为那杯茶旁边放着一副眼镜，不是他的眼镜。是一副金丝边的女式眼镜，镜腿上挂着一颗小小的珍珠。

叶辞不认识那副眼镜。但他觉得它们很眼熟。

他盯着镜子看了很久。镜子里的叶辞翻了一页书，橘猫换了个姿势继续睡。画面很安静、很温暖，和叶辞住的这间冰冷潮湿的老公寓形成了刺眼的对比。他伸出手去触碰镜面，指尖碰到玻璃的一瞬间，画面抖动了一下，像是电视信号不好时的雪花。然后恢复了。

他收回手，画面依然清晰。

第三次看到镜中画面的时候，他看到了她。

🌙 沈念念

她从镜子里的卧室走出来，穿着那件米白色的针织衫，头发散着，手里端着一碗热汤。她走到沙发后面，弯腰在叶辞的额头上亲了一下，然后绕到沙发前面坐下来，把汤放在茶几上。

"喝了再看书。"她说。

她的声音很温柔，带着一点点沙哑，像是冬天里壁炉里木柴燃烧的声响。她笑起来的时候嘴角有一个小小的弧度，右边的酒窝比左边的深。

叶辞站在自己逼仄的卫生间里，看着镜子里的那个女人，心脏猛地跳了一下。

他认识她。沈念念。他的大学同学。他暗恋了四年的人。

沈念念在大学时是新闻学院的，比叶辞小一届。她总是背着一个很大的帆布包，包里塞着录音笔、笔记本、笔记本电脑和三支不同颜色的笔。她走路很快，马尾辫在脑后甩来甩去，像是在跟风赛跑。她笑起来的时候声音很大，不做作，是那种从胸腔里发出来的笑，听着就让人觉得高兴。

叶辞在大学的四年里，用"笨拙"来形容他对沈念念的态度都算客气。他从来不主动找她说话，但她经过的时候他会假装在看手机，其实在偷偷看她的倒影。他参加了她负责的校报摄影组，理由是"需要志愿时长"，实际上是为了有机会给她拍照片。他给她拍了很多——在食堂端着盘子纠结选什么菜的样子，在图书馆趴在桌上睡着嘴角流口水的样子，在操场跑步时被风吹乱了头发大笑的样子。这些照片他都存在电脑的一个隐藏文件夹里，文件夹的名字叫"参考素材"。他是个美术指导，给很多东西建过参考素材库，但只有这一个文件夹里的东西，他从来不打开看。不是不想看，是怕看了就再也出不来了。

他从来没有跟她告白。原因和所有懦夫一样——怕被拒绝，怕连朋友都做不了，怕她用一种"你是个好人但是"的眼神看他。他宁可选择沉默，至少沉默不会失去什么。

但他失去了。毕业的时候沈念念去了云南拍纪录片，他们加了微信，偶尔点赞，从不私聊。后来她的朋友圈更新越来越少，最后一条是一张高原上的星空照片，配文是"这里离星星很近"。再后来就没有了。像是她去了离星星很近的地方，就不再回来了。

✨ 每天晚上

从那以后，叶辞每天晚上都会在镜子前站很久。

镜子里的画面像一部定期更新的连续剧。他看到那个世界的叶辞和沈念念一起做饭——沈念念负责切菜，叶辞负责炒，他们配合得很好，像是已经这么做了很多年。他看到他们一起看电影，沈念念靠在叶辞肩膀上睡着了，叶辞不敢动，保持着同一个姿势两个小时，直到脖子僵了。他看到他们吵架——沈念念摔了一个杯子，碎片在地上闪着冷光，两个人都不说话。然后叶辞蹲下去捡碎片，沈念念也蹲下来，两个人的手碰到了一起，就那么蹲在碎片中间，谁也没说话。

他看到沈念念在厨房里翻叶辞大学时的照片。翻到摄影组活动的那一沓时，她停了下来。她指着其中一张照片——那是叶辞偷拍的沈念念在图书馆窗边看书的侧影——说："这张拍得好好看。是谁拍的？"

镜子里的叶辞笑了笑，说："一个笨蛋拍的。"

"什么笨蛋？"

"一个喜欢摄影的笨蛋。他暗恋一个女孩四年，从来不敢说。后来他们在一起了，他才告诉她，他电脑里有个文件夹叫'参考素材'，里面全是她的照片。"

沈念念听完，打了叶辞一下，然后笑了。笑得和大学时一模一样——声音很大，从胸腔里发出来的，不做作。

他看到镜中的叶辞有一次出差回来，沈念念在门口等他。她穿着那件条纹T恤，赤着脚站在玄关的地垫上，手里拿着一双拖鞋。叶辞换鞋的时候，她从后面环住他的腰，把脸贴在他的背上。橘猫绕着他们的脚踝转圈，喵喵叫着要吃的。叶辞回头亲了一下她的额头，说"先喂猫"。沈念念说"先喂你"。然后她松开他，走进厨房，从冰箱里拿出一盒速冻水饺。叶辞跟着她走进去，站在料理台旁边看着她烧水。水开了，饺子下锅，蒸汽升起来，模糊了她的脸。他伸手把她的头发拨到耳后。那个动作很自然，自然到像是做了一千次。

镜子外面的叶辞也想伸手去拨她的头发。但他的手碰到的只是冰凉的镜面。玻璃上有一层薄薄的水雾，是他呼出的热气凝成的。他伸手在镜面上画了一个圆，透过圆看到的是另一个世界——有暖光、有猫、有她。

镜子外面的叶辞，靠着卫生间的墙壁，慢慢滑坐在地上。他抱着膝盖，额头抵着手臂，没有哭。他只是觉得很冷。卫生间没有暖气，瓷砖是凉的，空气是潮的，像是有人在四面墙壁上不停地喷水。他坐在那里，听着镜子里的橘猫打呼噜，听着沈念念笑，听着那个世界的自己说"我给你热碗汤"。

他沉迷了。每天晚上，他不再加班，早早回家，洗完澡就坐在卫生间里看镜子。地板上铺了一件旧外套，他就坐在上面，背靠着浴缸，像是在电影院里看一场只有自己能看到的电影。有时候一看就是四五个小时，腿麻了也不动。他开始忽略现实中的事情——工作邮件不回，朋友电话不接，外卖盒子堆了一桌子。他的生活被劈成了两半：白天是灰色的、扁平的、没有温度的；晚上是暖色的、立体的、有沈念念在的。他越来越不想醒来。

🌀 碎裂

镜子是在第三十七天碎的。

那天晚上，镜子里的画面和往常一样——沈念念坐在沙发上看书，橘猫趴在她腿上，叶辞在厨房洗碗。一切都那么安静、那么好。

然后叶辞注意到沈念念的脸色有些苍白。她看书的时候眉头微微皱着，左手无意识地按着腹部的位置。镜子里的叶辞从厨房走出来，手里拿着一条湿毛巾，走过去蹲在她面前，把毛巾覆在她额头上。

"又不舒服了？"他问。

"没事，老毛病。"沈念念笑了笑，但那个笑有些勉强。

叶辞看着镜子，忽然意识到了什么。沈念念生病了。那个世界的沈念念——那个和叶辞在一起的沈念念——生病了。

他开始每天盯着镜子看她的状态。她越来越瘦了，脸色越来越白，看书的时间越来越短，大部分时间都靠在沙发上闭着眼睛。橘猫似乎感觉到了什么，不再乱跑，整天蜷在她身边，像是怕她消失。

第三十五天，镜子里的沈念念住院了。叶辞守在病床旁边，握着她的手。她的手很瘦，骨节分明，指尖发凉。床头柜上放着那副金丝边眼镜和一本翻到一半的书。监护仪在响，滴、滴、滴，规律得像心跳。

第三十七天。叶辞站在镜子前，看到镜子里的画面开始模糊了。像是有人在镜面上哈了一口气，画面变得朦胧、扭曲。沈念念躺在床上，叶辞坐在床边。她睁开眼睛，看着叶辞，嘴唇动了动。

叶辞凑近镜子去看她的唇语。她的嘴唇很干，颜色很淡，但动作很清晰。她说的是——

"去找她。"

画面碎裂了。不是整面镜子碎——只有画面碎了，像是一块屏幕突然失去了信号。镜面上出现了一道裂纹，从右上角延伸到左下角，把两个世界劈成了两半。

叶辞站在镜子前，看着裂开的镜面上映出的自己的脸。没有沈念念了。没有橘猫了。没有暖黄色的落地灯光了。只有白色瓷砖、逼仄的卫生间、一个眼眶通红的男人。

他伸出手，碰了一下那道裂纹。裂纹没有扩大，也没有愈合。它就那么横在那里，像一条无法跨越的边界。

🌧️ 那个电话

叶辞在镜子碎裂后的第三天，翻出了沈念念的微信。

他们的聊天记录停在毕业那年。最后一条消息是沈念念发的："叶辞，我要去云南了。有什么想跟我说的吗？"

他当时回了："注意安全。"

和七年前在火车站的顾珩一样——明明有一万句话想说，最后只挤出四个字。

他的手指悬在对话框上方，打了又删，删了又打。最后他什么也没打，直接按了语音通话键。

响了四声。接通了。

"喂？叶辞？"沈念念的声音从手机里传出来，带着一点惊讶。但那个声音——沙沙的、温柔的、像是冬天壁炉里木柴燃烧的声响——和镜子里的完全一样。

